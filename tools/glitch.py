"""04_glitch: a port of Workshop Computer program 57 "Glitch" (clock-synced beat-repeater) to the Nebulae.

Generated by tools/gen.py. Design notes: docs/GLITCH.md. User guide: patches/04_glitch_README.md.

Two modes share one circular buffer (Source latch: off = Glitch, on = Stutter; it applies at the next clock):
- Glitch: each clock pulse measures the beat. The first 1/div of the previous beat is replayed div times, each
  sub-slice randomly reversed and/or degraded (decimate, then bitcrush).
- Stutter: the beat is cut into div slices and played in a shuffled order. Slices may repeat, and the beat may be
  drawn from an earlier beat (drift).

Engine
- Writer: rpole~ counter + tabwrite~ (both restarted every BUF samples). Writes old*frz + in*(1-frz), so freeze holds
  the buffer while the counter keeps running. snapshot~ of the counter gives the write position at each clock edge.
- Reader: one slice counter (rpole~, cleared at every slice boundary) -> decimate -> index B + D*p (wrapped) ->
  tabread~ -> bitcrush -> edge fade -> per-slice wet gate (else live input).
- Control: everything is block-quantised (slice lengths are whole 64-sample blocks), so per-slice values sent at a
  boundary land in the same block as the counter reset.
"""

from gloop import press

SR = 48000
BUF = 2 ** 21                  # 43.7 s; a power of two keeps the index wrap exact in float32
BUFMS = BUF * 1000 / SR        # writer restart period
MAX_BEAT = 10 * SR             # longest beat (samples); a longer clock gap reuses the last beat
DRIFT_BEATS = 12               # Stutter drift reaches back at most this many beats
MARGIN = 128                   # slices end this many samples before the expected next clock (jitter room)
GRACE = 30                     # ms to wait for a late clock after the last slice of a beat
HYST = 240                     # beat changes smaller than this (samples, 5 ms) are ignored (clock jitter)
Q0 = "3.0517578e-05"           # 1/32768: bitcrush step when not crushing


def chain(c, x, y, src, texts, dy=22, outlet=0):
    """Vertical chain of objects from src (outlet `outlet`); returns the last object."""
    prev, o = src, outlet
    for t in texts:
        y += dy
        n = c.obj(x, y, t)
        c.connect(prev, o, n, 0)
        prev, o = n, 0
    return prev


def rnd(c, x, y, k, rng=4096):
    """[random rng], seeded from gt_seed (+k so every instance differs)."""
    r = c.obj(x, y, f"random {rng}")
    rs = c.obj(x + 90, y - 66, "r gt_seed")
    a = c.obj(x + 90, y - 44, f"+ {k}")
    m = c.msg(x + 90, y - 22, "seed \\$1")     # .pd files escape $ as \$
    c.connect(rs, 0, a, 0)
    c.connect(a, 0, m, 0)
    c.connect(m, 0, r, 0)
    return r


def roll(c, x, y, src, outlet, k, thresh):
    """bang -> (random 4096 < [r thresh]) -> 0/1. Returns the [<] object."""
    r = rnd(c, x, y, k)
    c.connect(src, outlet, r, 0)
    lt = c.obj(x, y + 22, "< 0")
    c.connect(r, 0, lt, 0)
    rt = c.obj(x + 60, y, f"r {thresh}")
    c.connect(rt, 0, lt, 1)
    return lt


def or_force_gate(c, x, y, src):
    """src (0/1) OR force OR gate -> 0/1."""
    a = c.obj(x, y, "+ 0")
    b = c.obj(x, y + 22, "+ 0")
    g = c.obj(x, y + 44, "> 0")
    c.connect(src, 0, a, 0)
    c.connect(a, 0, b, 0)
    c.connect(b, 0, g, 0)
    rf = c.obj(x + 60, y - 22, "r gt_force")
    rg = c.obj(x + 140, y - 22, "r gt_gate")
    c.connect(rf, 0, a, 1)
    c.connect(rg, 0, b, 1)
    return g


def ui(Canvas):
    """Nebulae controls -> gt_* parameters. Reset (jack or button) = clock."""
    c = Canvas("#N canvas 0 50 1000 600 %NAME% 0;")
    c.text(10, 5, "Source=mode (off Glitch / on Stutter). Record=force. Freeze=freeze. Reset=clock. start>0.5=gate. "
                  "size=division. density=prob. window=X. overlap=Y. blend=dry/wet")
    lb = c.obj(800, 30, "loadbang")
    d = c.obj(800, 55, "delay 1000")
    m = c.msg(800, 80, "1")
    sp = c.obj(800, 105, "s gt_primed")
    c.connect(lb, 0, d, 0)
    c.connect(d, 0, m, 0)
    c.connect(m, 0, sp, 0)
    # defaults until the module reports (it streams every value straight away)
    dflt = c.msg(560, 55, "\\; gt_mode 0 \\; gt_force 0 \\; gt_gate 0 \\; gt_freeze 0 \\; gt_zone 0 "
                          "\\; gt_pdens 0 \\; gt_px 0 \\; gt_py 0 \\; gt_x 0 \\; gt_wet 1 \\; gt_T 0 \\; gt_step 0 "
                          "\\; gt_dmul 0 \\; gt_smax 24")
    c.connect(lb, 0, dflt, 0)
    # clock: Reset (button or jack, a ~10 ms trigger), ignored for 1 s after load
    p = press(c, 10, 30, "reset", True, primed="gt_primed")
    s = c.obj(10, 140, "s gt_clock")
    c.connect(p, 0, s, 0)
    # seed the random generators from the time to the first clock
    sg = c.obj(10, 180, "spigot 1")
    c.connect(p, 0, sg, 0)
    ts = c.obj(10, 202, "t b b")
    c.connect(sg, 0, ts, 0)
    z = c.msg(80, 224, "0")
    c.connect(ts, 1, z, 0)
    c.connect(z, 0, sg, 1)
    tm = c.obj(10, 246, "timer")
    c.connect(lb, 0, tm, 0)
    c.connect(ts, 0, tm, 1)
    chain(c, 10, 246, tm, ["* 1000", "int", "s gt_seed"])
    # latch states
    for i, (src, dst) in enumerate([("source", "gt_mode"), ("record", "gt_force"), ("freeze", "gt_freeze")]):
        r = c.obj(200 + i * 110, 30, f"r {src}")
        chain(c, 200 + i * 110, 30, r, ["change", f"s {dst}"])
    # start pot + CV as a gate
    r = c.obj(530, 160, "r start")
    chain(c, 530, 160, r, ["> 0.5", "change", "s gt_gate"])
    # size -> zone 0..4
    r = c.obj(200, 160, "r size")
    chain(c, 200, 160, r, ["* 5", "int", "clip 0 4", "change", "s gt_zone"])
    # probabilities as 0..4095 thresholds (like the WC's 12-bit knobs)
    for i, (src, dst) in enumerate([("density", "gt_pdens"), ("overlap", "gt_py")]):
        r = c.obj(10 + i * 110, 330, f"r {src}")
        chain(c, 10 + i * 110, 330, r, ["* 4095", f"s {dst}"])
    r = c.obj(230, 330, "r window")
    t = c.obj(230, 352, "t f f")
    c.connect(r, 0, t, 0)
    chain(c, 290, 352, t, ["* 4095", "s gt_px"], outlet=1)
    sx = c.obj(230, 396, "s gt_x")
    c.connect(t, 0, sx, 0)
    # Pitch (+1V/oct): transpose the glitches, semitones = round(pitch*60) - 36 (click 0.6 = 0), live
    r = c.obj(530, 260, "r pitch")
    chain(c, 530, 260, r, ["* 60", "+ 0.5", "int", "- 36", "change", "s gt_T"])
    # Speed: semitones per repeat = round(24*(speed - 0.5)): centre 0, click +-3, ends +-12 (latched per slice)
    r = c.obj(680, 260, "r speed")
    chain(c, 680, 260, r, ["- 0.5", "* 24", "+ 12.5", "int", "- 12", "change", "s gt_step"])
    r = c.obj(400, 330, "r blend")
    chain(c, 400, 330, r, ["s gt_wet"])
    return c


def clock(Canvas):
    """Clock edge -> beat length, write position, slice geometry; slice scheduler."""
    c = Canvas("#N canvas 0 50 1300 800 %NAME% 0;")
    c.text(10, 5, "Clock edge: measure beat L -> snapshot write pos -> v (freeze-aware) -> geometry -> restart slices")
    rc = c.obj(10, 30, "r gt_clock")
    te = c.obj(10, 55, "t b b b b b b")
    c.connect(rc, 0, te, 0)

    # --- o5: beat length L (samples, whole blocks, hysteresis) ---
    x = 10
    tt = c.obj(x, 90, "t b b")
    c.connect(te, 5, tt, 0)
    tm = c.obj(x, 112, "timer")
    c.connect(tt, 1, tm, 1)        # output the time since the last edge...
    c.connect(tt, 0, tm, 0)        # ...then restart
    mo = c.obj(x, 134, f"moses {MAX_BEAT * 1000 // SR}")
    c.connect(tm, 0, mo, 0)
    blk = chain(c, x, 134, mo, [f"* {SR / 1000 / 64:g}", "+ 0.5", "int", "* 64", "max 64"])
    tb = c.obj(x + 100, 156, "t b")
    c.connect(mo, 1, tb, 0)
    fb = c.obj(x + 100, 178, f"f {MAX_BEAT}")     # clock gap > MAX_BEAT: keep the last beat length
    c.connect(tb, 0, fb, 0)
    h = c.obj(x, 290, "t b f f")
    c.connect(blk, 0, h, 0)
    c.connect(fb, 0, h, 0)
    cand = c.obj(x + 150, 312, "f")
    c.connect(h, 2, cand, 1)
    dif = c.obj(x + 80, 312, "-")
    c.connect(h, 1, dif, 0)
    ab = c.obj(x + 80, 334, "abs")
    c.connect(dif, 0, ab, 0)
    mh = c.obj(x + 80, 356, f"moses {HYST + 1}")
    c.connect(ab, 0, mh, 0)
    tb2 = c.obj(x + 150, 378, "t b")
    c.connect(mh, 1, tb2, 0)
    c.connect(tb2, 0, cand, 0)
    lacc = c.obj(x, 400, "f")
    c.connect(cand, 0, lacc, 1)
    c.connect(h, 0, lacc, 0)
    c.connect(lacc, 0, dif, 1)
    c.connect(lacc, 0, fb, 1)
    sl = c.obj(x, 422, "s gt_L")
    c.connect(lacc, 0, sl, 0)

    # --- o4: write position ---
    ss = c.obj(260, 90, "s gt_snap")
    c.connect(te, 4, ss, 0)

    # --- freeze bookkeeping: wf = position at freeze, cu = position at unfreeze, hold = still on frozen beat ---
    x = 600
    rf = c.obj(x, 30, "r gt_freeze")
    sf = c.obj(x, 52, "sel 1 0")
    c.connect(rf, 0, sf, 0)
    hold = c.obj(400, 300, "f 0")
    wf = c.obj(560, 420, "f")
    cu = c.obj(470, 440, "-")              # right inlet stores cu
    for outlet, dest in [(0, "wf"), (1, "cu")]:
        t = c.obj(x + outlet * 160, 80, "t b b")
        c.connect(sf, outlet, t, 0)
        s = c.obj(x + outlet * 160 + 60, 102, "s gt_snap")
        c.connect(t, 1, s, 0)
        f = c.obj(x + outlet * 160, 124, "f")
        rcp = c.obj(x + outlet * 160 + 40, 102, "r gt_c")
        c.connect(rcp, 0, f, 1)
        c.connect(t, 0, f, 0)
        if dest == "wf":
            c.connect(f, 0, wf, 1)
            one = c.msg(x + 60, 146, "1")
            c.connect(t, 0, one, 0)
            c.connect(one, 0, hold, 1)
        else:
            c.connect(f, 0, cu, 1)

    # --- o3: virtual write position v ---
    def fc(xx, yy):
        f = c.obj(xx, yy, "f")
        r = c.obj(xx + 30, yy - 22, "r gt_c")
        c.connect(r, 0, f, 1)
        return f
    sv = c.obj(400, 520, "s gt_v")
    c.connect(te, 3, hold, 0)
    hs = c.obj(400, 322, "sel 0")
    c.connect(hold, 0, hs, 0)
    fcc = fc(400, 366)
    c.connect(hs, 0, fcc, 0)
    c.connect(fcc, 0, sv, 0)
    tbh = c.obj(470, 344, "t b")
    c.connect(hs, 1, tbh, 0)
    frz = c.obj(470, 366, "f")
    rfz = c.obj(510, 344, "r gt_freeze")
    c.connect(rfz, 0, frz, 1)
    c.connect(tbh, 0, frz, 0)
    fs = c.obj(470, 388, "sel 1")
    c.connect(frz, 0, fs, 0)
    c.connect(fs, 0, wf, 0)                # frozen: replay the beat before the freeze point
    c.connect(wf, 0, sv, 0)
    tbu = c.obj(470, 410, "t b")
    c.connect(fs, 1, tbu, 0)
    fcd = fc(470, 432)
    c.connect(tbu, 0, fcd, 0)
    c.connect(fcd, 0, cu, 0)               # samples written since unfreeze
    wr = chain(c, 470, 440, cu, [f"+ {BUF}", f"mod {BUF}", ">= 0"])
    rl = c.obj(560, 484, "r gt_L")
    c.connect(rl, 0, wr, 1)
    gs = c.obj(470, 528, "sel 1 0")
    c.connect(wr, 0, gs, 0)
    t3 = c.obj(470, 550, "t b b")
    c.connect(gs, 0, t3, 0)
    z = c.msg(530, 572, "0")
    c.connect(t3, 1, z, 0)
    c.connect(z, 0, hold, 1)               # a full fresh beat is in: back to live
    fce = fc(470, 594)
    c.connect(t3, 0, fce, 0)
    c.connect(fce, 0, sv, 0)
    c.connect(gs, 1, wf, 0)                # not yet: keep replaying the frozen beat

    # --- o2: geometry (division, slice length, mode) ---
    x = 750
    g3 = c.obj(x, 200, "t b b b")
    c.connect(te, 2, g3, 0)
    fz = c.obj(x + 200, 222, "f")
    rz = c.obj(x + 240, 200, "r gt_zone")
    c.connect(rz, 0, fz, 1)
    c.connect(g3, 2, fz, 0)
    mz = c.obj(x + 200, 244, "moses 4")
    c.connect(fz, 0, mz, 0)
    p1 = c.obj(x + 200, 266, "+ 1")
    c.connect(mz, 0, p1, 0)
    tb6 = c.obj(x + 260, 266, "t b")
    c.connect(mz, 1, tb6, 0)
    f6 = c.obj(x + 260, 288, "f 6")        # top zone: 6 (Glitch) or 8 (Stutter)
    c.connect(tb6, 0, f6, 0)
    rm = c.obj(x + 330, 222, "r gt_mode")
    m6 = chain(c, x + 330, 222, rm, ["* 2", "+ 6"])
    c.connect(m6, 0, f6, 1)
    sd = c.obj(x + 200, 320, "s gt_div")
    c.connect(p1, 0, sd, 0)
    c.connect(f6, 0, sd, 0)
    fl = c.obj(x + 100, 350, "f")
    rl2 = c.obj(x + 140, 328, "r gt_L")
    c.connect(rl2, 0, fl, 1)
    c.connect(g3, 1, fl, 0)
    dv = chain(c, x + 100, 350, fl, [f"- {MARGIN}", "/ 1"])
    rd = c.obj(x + 160, 372, "r gt_div")
    c.connect(rd, 0, dv, 1)
    ln = chain(c, x + 100, 394, dv, ["/ 64", "int", "* 64", "max 64", "s gt_len"])
    fm = c.obj(x, 500, "f")
    rm2 = c.obj(x + 40, 478, "r gt_mode")
    c.connect(rm2, 0, fm, 1)
    c.connect(g3, 0, fm, 0)
    tf = c.obj(x, 522, "t f f")
    c.connect(fm, 0, tf, 0)
    slm = c.obj(x + 60, 544, "s gt_lmode")
    c.connect(tf, 1, slm, 0)
    sm = c.obj(x, 544, "sel 0 1")
    c.connect(tf, 0, sm, 0)
    c.connect(sm, 0, c.obj(x, 566, "s gt_gstart"), 0)
    c.connect(sm, 1, c.obj(x + 90, 566, "s gt_sstart"), 0)

    # --- slice scheduler: E(first) -> boundary in the latched mode, arm the slice delay ---
    x = 1000
    e = c.obj(x, 620, "t b f")
    ffirst = c.obj(x + 100, 664, "f")
    c.connect(e, 1, ffirst, 1)
    tb3 = c.obj(x, 642, "t b b")
    c.connect(e, 0, tb3, 0)
    flm = c.obj(x + 50, 664, "f")
    rlm = c.obj(x + 90, 642, "r gt_lmode")
    c.connect(rlm, 0, flm, 1)
    c.connect(tb3, 1, flm, 0)
    sl2 = c.obj(x + 50, 686, "sel 0 1")
    c.connect(flm, 0, sl2, 0)
    c.connect(sl2, 0, c.obj(x + 50, 730, "s gt_gbnd"), 0)
    c.connect(sl2, 1, ffirst, 0)
    c.connect(ffirst, 0, c.obj(x + 140, 730, "s gt_sbnd"), 0)
    sdel = c.obj(x - 200, 664, "delay 1000")
    c.connect(tb3, 0, sdel, 0)
    rln = c.obj(x - 120, 620, "r gt_len")
    lms = c.obj(x - 120, 642, f"/ {SR / 1000:g}")
    c.connect(rln, 0, lms, 0)
    c.connect(lms, 0, sdel, 1)
    fk = c.obj(x - 200, 686, "f")
    c.connect(sdel, 0, fk, 0)
    pk = c.obj(x - 200, 708, "+ 1")
    c.connect(fk, 0, pk, 0)
    tk = c.obj(x - 200, 730, "t f f")
    c.connect(pk, 0, tk, 0)
    c.connect(tk, 1, fk, 1)
    km = c.obj(x - 200, 752, "mod 1")
    c.connect(tk, 0, km, 0)
    rdv = c.obj(x - 140, 730, "r gt_div")
    c.connect(rdv, 0, km, 1)
    tkm = c.obj(x - 200, 763, "t f f")
    c.connect(km, 0, tkm, 0)
    c.connect(tkm, 1, c.obj(x - 260, 785, "s gt_k"), 0)     # slice index within the beat (for the Speed ramp)
    ks = c.obj(x - 200, 785, "sel 0")
    c.connect(tkm, 0, ks, 0)
    gdel = c.obj(x - 200, 796, f"delay {GRACE}")    # last slice of the beat: give a late clock time to arrive
    c.connect(ks, 0, gdel, 0)
    tbk = c.obj(x - 100, 796, "t b")
    c.connect(ks, 1, tbk, 0)
    m0 = c.msg(x - 150, 818, "0")
    c.connect(gdel, 0, m0, 0)
    c.connect(tbk, 0, m0, 0)
    c.connect(m0, 0, e, 0)
    # --- o1: stop pending slices, k = 0;  o0: first slice of the beat ---
    stp = c.msg(x - 200, 600, "stop")
    c.connect(te, 1, stp, 0)
    c.connect(stp, 0, sdel, 0)
    c.connect(stp, 0, gdel, 0)
    z0 = c.msg(x - 140, 600, "0")
    c.connect(te, 1, z0, 0)
    c.connect(z0, 0, fk, 1)
    c.connect(z0, 0, c.obj(x - 140, 575, "s gt_k"), 0)
    m1 = c.msg(x, 598, "1")
    c.connect(te, 0, m1, 0)
    c.connect(m1, 0, e, 0)
    return c


def glitch_mode(Canvas):
    """Glitch mode: start = v - L. Each sub-slice rolls glitch, reverse (density) and degrade (overlap)."""
    c = Canvas("#N canvas 0 50 1100 600 %NAME% 0;")
    c.text(10, 5, "Glitch: replay the first 1/div of the last beat. Per slice: glitch? reverse? degrade?")
    rs = c.obj(10, 30, "r gt_gstart")
    fv = c.obj(10, 52, "f")
    rv = c.obj(50, 30, "r gt_v")
    c.connect(rv, 0, fv, 1)
    c.connect(rs, 0, fv, 0)
    sb = c.obj(10, 74, "- 0")
    rl = c.obj(80, 52, "r gt_L")
    c.connect(rl, 0, sb, 1)
    c.connect(fv, 0, sb, 0)
    st = chain(c, 10, 74, sb, [f"+ {2 * BUF}", f"mod {BUF}"])
    s1 = c.obj(300, 250, "f")
    s2 = c.obj(400, 250, "f")
    c.connect(st, 0, s1, 1)
    c.connect(st, 0, s2, 1)

    rb = c.obj(10, 160, "r gt_gbnd")
    tg = c.obj(10, 182, "t b b b b")
    c.connect(rb, 0, tg, 0)
    # o3: glitch this slice?
    g = roll(c, 700, 270, tg, 3, 11, "gt_pdens")
    gg = or_force_gate(c, 700, 330, g)
    c.connect(gg, 0, c.obj(700, 400, "s gt_gsel"), 0)
    # o2: reverse?  forward: B = S, D = 1;  reverse: B = S + len - 1, D = -1
    rv2 = roll(c, 300, 160, tg, 2, 12, "gt_pdens")
    sr = c.obj(300, 204, "sel 0 1")
    c.connect(rv2, 0, sr, 0)
    c.connect(sr, 0, s1, 0)
    c.connect(sr, 1, s2, 0)
    sB = c.obj(300, 330, "s gt_B")
    c.connect(s1, 0, sB, 0)
    ad = c.obj(400, 272, "+ 0")
    c.connect(s2, 0, ad, 0)
    rln = c.obj(470, 228, "r gt_len")
    lm1 = c.obj(470, 250, "- 1")
    c.connect(rln, 0, lm1, 0)
    c.connect(lm1, 0, ad, 1)
    c.connect(ad, 0, sB, 0)
    f1 = c.msg(240, 228, "\\; gt_D 1")
    c.connect(sr, 0, f1, 0)
    r1 = c.msg(400, 300, "\\; gt_D -1")
    c.connect(sr, 1, r1, 0)
    # o1: degrade?  window -> decimation (first half) then decimation 16 + bitcrush 0..7 bits (second half)
    dg = roll(c, 10, 300, tg, 1, 13, "gt_py")
    sd = c.obj(10, 344, "sel 1 0")
    c.connect(dg, 0, sd, 0)
    dx = c.obj(10, 400, "f 1")
    qx = c.obj(80, 400, f"f {Q0}")
    t1 = c.obj(10, 366, "t b b")
    c.connect(sd, 0, t1, 0)
    c.connect(t1, 1, qx, 0)
    c.connect(t1, 0, dx, 0)
    c.connect(dx, 0, c.obj(10, 430, "s gt_dec"), 0)
    c.connect(dx, 0, c.obj(10, 452, "s gt_dmul"), 0)
    c.connect(qx, 0, c.obj(80, 430, "s gt_q"), 0)
    clean = c.msg(150, 400, f"\\; gt_dec 1 \\; gt_dmul 0 \\; gt_q {Q0}")
    c.connect(sd, 1, clean, 0)
    rx = c.obj(10, 470, "r gt_x")
    mx = chain(c, 10, 470, rx, ["* 4095", "int", "moses 2048"])
    tl = c.obj(10, 558, "t f b")
    c.connect(mx, 0, tl, 0)
    q0 = c.msg(70, 580, Q0)
    c.connect(tl, 1, q0, 0)
    c.connect(q0, 0, qx, 1)
    dd = chain(c, 10, 558, tl, ["* 15", "/ 2048", "int", "+ 1"])
    c.connect(dd, 0, dx, 1)
    th = c.obj(200, 558, "t f b")
    c.connect(mx, 1, th, 0)
    d16 = c.msg(260, 580, "16")
    c.connect(th, 1, d16, 0)
    c.connect(d16, 0, dx, 1)
    qq = chain(c, 200, 558, th, ["- 2048", "/ 256", "int", "* 0.693147", "exp", "/ 32768"])
    c.connect(qq, 0, qx, 1)
    # o0: restart the slice counter (same logical time as the values above -> same block)
    c.connect(tg, 0, c.obj(10, 230, "s gt_slice"), 0)
    return c


