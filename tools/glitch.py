def writer(Canvas):
    """Circular stereo writer. Freeze writes the old samples back (the buffer holds; the counter keeps going)."""
    c = Canvas("#N canvas 0 50 900 500 %NAME% 0;")
    c.text(10, 5, f"Writer: rpole~ counter + tabwrite~, restarted every {BUF} samples. "
                  "Writes old*frz + in*(1-frz). gt_snap -> counter (= next write index) -> gt_c")
    il = c.obj(10, 30, "inlet~")
    ir = c.obj(400, 30, "inlet~")
    lb = c.obj(600, 30, "loadbang")
    d = c.obj(600, 52, "delay 300")       # with DSP on (controls subpatch), so the counter starts at the table start
    met = c.obj(600, 74, f"metro {BUFMS:.4f}")
    c.connect(lb, 0, d, 0)
    c.connect(d, 0, met, 0)
    clr = c.msg(600, 100, "clear")
    c.connect(met, 0, clr, 0)
    one = c.obj(150, 30, "sig~ 1")
    rp = c.obj(150, 124, "rpole~ 1")
    c.connect(one, 0, rp, 0)
    c.connect(clr, 0, rp, 0)
    idx = c.obj(150, 146, "-~ 0.5")       # counts 1,2,3..: n - 0.5 reads the sample about to be written
    c.connect(rp, 0, idx, 0)
    # dummy outlet: the patch connects it to the reader so DSP always runs the writer first (slice-locked reads
    # start right at the write head and must see this block's samples)
    c.connect(idx, 0, c.obj(150, 440, "outlet~"), 0)
    rs = c.obj(300, 124, "r gt_snap")
    sn = c.obj(300, 168, "snapshot~")
    c.connect(rp, 0, sn, 0)
    c.connect(rs, 0, sn, 0)
    c.connect(sn, 0, c.obj(300, 190, "s gt_c"), 0)
    rf = c.obj(600, 150, "r gt_freeze")
    frz = chain(c, 600, 150, rf, ["pack f 5", "line~"])
    nf = chain(c, 700, 194, frz, ["*~ -1", "+~ 1"])
    for side, inl, x in [("l", il, 10), ("r", ir, 400)]:
        old = c.obj(x, 250, f"tabread~ gt_buf{side}")
        c.connect(idx, 0, old, 0)
        k = c.obj(x, 280, "*~")
        c.connect(old, 0, k, 0)
        c.connect(frz, 0, k, 1)
        i = c.obj(x + 100, 280, "*~")
        c.connect(inl, 0, i, 0)
        c.connect(nf, 0, i, 1)
        s = c.obj(x, 310, "+~")
        c.connect(k, 0, s, 0)
        c.connect(i, 0, s, 1)
        tw = c.obj(x, 340, f"tabwrite~ gt_buf{side}")
        c.connect(s, 0, tw, 0)
        c.connect(met, 0, tw, 0)
    return c


def reader(Canvas):
    """Slice playback: counter -> decimate -> wrapped index -> tabread~ -> bitcrush -> fade -> wet gate."""
    c = Canvas("#N canvas 0 50 1100 700 %NAME% 0;")
    c.text(10, 5, "Reader: p = samples into slice. idx = wrap(B + D*floor(p/dec)*dec). "
                  "out = g*fade*crush(buf[idx]) + (1-g)*live")
    il = c.obj(10, 30, "inlet~")
    ir = c.obj(500, 30, "inlet~")
    c.obj(1050, 30, "inlet~")             # from the writer, unused: only forces writer-before-reader DSP order
    rs = c.obj(150, 30, "r gt_slice")
    clr = c.msg(150, 52, "clear")
    c.connect(rs, 0, clr, 0)
    one = c.obj(250, 52, "sig~ 1")
    rp = c.obj(150, 80, "rpole~ 1")
    c.connect(one, 0, rp, 0)
    c.connect(clr, 0, rp, 0)
    p = c.obj(150, 102, "-~ 1")            # time into the slice (samples): drives the fades
    c.connect(rp, 0, p, 0)
    # read position: integrated rate (Pitch transpose x Speed ramp), so live rate changes never jump
    rr = c.obj(50, 52, "r gt_rate")
    rsig = c.obj(50, 74, "sig~ 1")
    c.connect(rr, 0, rsig, 0)
    rp2 = c.obj(50, 96, "rpole~ 1")
    c.connect(rsig, 0, rp2, 0)
    c.connect(clr, 0, rp2, 0)
    pr = c.obj(50, 118, "-~")              # sum of rates so far, minus this sample's: 0 at the first sample
    c.connect(rp2, 0, pr, 0)
    c.connect(rsig, 0, pr, 1)
    # decimation: eff = pr - wrap~(pr/dec)*dmul  = floor(pr/dec)*dec when degrading (dmul = dec), else pr (dmul 0)
    z = c.obj(150, 130, "*~ 1")
    c.connect(pr, 0, z, 0)
    wz = c.obj(220, 152, "wrap~")
    c.connect(z, 0, wz, 0)
    wm = c.obj(220, 174, "*~ 0")
    c.connect(wz, 0, wm, 0)
    eff = c.obj(150, 196, "-~")
    c.connect(pr, 0, eff, 0)
    c.connect(wm, 0, eff, 1)
    rdm = c.obj(300, 152, "r gt_dmul")
    c.connect(rdm, 0, wm, 1)
    rdec = c.obj(400, 80, "r gt_dec")
    sw = c.obj(400, 124, "swap 1")
    dv = c.obj(400, 146, "/")
    c.connect(rdec, 0, sw, 0)
    c.connect(sw, 1, dv, 1)
    c.connect(sw, 0, dv, 0)
    c.connect(dv, 0, z, 1)
    # index = wrap((B + BUF + D*eff) / BUF) * BUF   (power-of-two BUF: exact), read with tabread4~
    de = c.obj(150, 230, "*~ 1")
    c.connect(eff, 0, de, 0)
    rD = c.obj(250, 208, "r gt_D")
    c.connect(rD, 0, de, 1)
    ab = c.obj(150, 252, f"+~ {BUF}")
    c.connect(de, 0, ab, 0)
    rB = c.obj(300, 208, "r gt_B")
    pb = c.obj(300, 230, f"+ {BUF}")
    c.connect(rB, 0, pb, 0)
    c.connect(pb, 0, ab, 1)
    ix = chain(c, 150, 252, ab, [f"*~ {1 / BUF!r}", "wrap~", f"*~ {BUF}"])
    # bitcrush step q: y = (floor(x/q + 65536) - 65536) * q
    rq = c.obj(600, 80, "r gt_q")
    tq = c.obj(600, 102, "t f f")
    c.connect(rq, 0, tq, 0)
    swq = c.obj(600, 124, "swap 1")
    dq = c.obj(600, 146, "/")
    c.connect(tq, 0, swq, 0)
    c.connect(swq, 1, dq, 1)
    c.connect(swq, 0, dq, 0)
    # edge fade: clip(p/64) * clip((len-1-max(p, pr))/64): a sped-up slice also ends when its own material runs out
    # (it only ever reads its region [B, B+len), so it never reads ahead of the writer)
    f1 = chain(c, 800, 102, p, ["*~ 0.015625", "clip~ 0 1"])
    pm = c.obj(900, 102, "max~")
    c.connect(p, 0, pm, 0)
    c.connect(pr, 0, pm, 1)
    f2a = c.obj(900, 124, "*~ -1")
    c.connect(pm, 0, f2a, 0)
    f2b = c.obj(900, 146, "+~ 0")
    c.connect(f2a, 0, f2b, 0)
    rl = c.obj(980, 102, "r gt_len")
    lm = c.obj(980, 124, "- 1")
    c.connect(rl, 0, lm, 0)
    c.connect(lm, 0, f2b, 1)
    f2 = chain(c, 900, 146, f2b, ["*~ 0.015625", "clip~ 0 1"])
    fe = c.obj(800, 230, "*~")
    c.connect(f1, 0, fe, 0)
    c.connect(f2, 0, fe, 1)
    # wet gate (one-block ramp)
    rg = c.obj(800, 260, "r gt_g")
    g = chain(c, 800, 260, rg, ["pack f 1.5", "line~"])
    ng = chain(c, 900, 304, g, ["*~ -1", "+~ 1"])
    fg = c.obj(800, 360, "*~")
    c.connect(fe, 0, fg, 0)
    c.connect(g, 0, fg, 1)
    for side, inl, x in [("l", il, 10), ("r", ir, 500)]:
        rd = c.obj(x, 400, f"tabread4~ gt_buf{side}")   # integer index (rate 1 / decimating) = that exact sample
        c.connect(ix, 0, rd, 0)
        a = c.obj(x, 422, "*~ 32768")
        c.connect(rd, 0, a, 0)
        c.connect(dq, 0, a, 1)
        zz = c.obj(x, 444, "+~ 65536")
        c.connect(a, 0, zz, 0)
        wzz = c.obj(x + 80, 466, "wrap~")
        c.connect(zz, 0, wzz, 0)
        fl = c.obj(x, 488, "-~")
        c.connect(zz, 0, fl, 0)
        c.connect(wzz, 0, fl, 1)
        cr = chain(c, x, 488, fl, ["-~ 65536", f"*~ {Q0}"])
        c.connect(tq, 1, cr, 1)
        w = c.obj(x, 560, "*~")
        c.connect(cr, 0, w, 0)
        c.connect(fg, 0, w, 1)
        lv = c.obj(x + 100, 560, "*~")
        c.connect(inl, 0, lv, 0)
        c.connect(ng, 0, lv, 1)
        s = c.obj(x, 590, "+~")
        c.connect(w, 0, s, 0)
        c.connect(lv, 0, s, 1)
        c.connect(s, 0, c.obj(x, 620, "outlet~"), 0)
    return c


def beat_source(Canvas):
    """Test input: on [r gt_tclkon 1] a 500 ms clock sends Reset pulses and restarts a 440 Hz rising ramp.
    Odd beats ramp to 1, even beats to 0.5, so 'the previous beat' is visible in 50 ms peaks. gt_tmute 1 mutes."""
    s = Canvas("#N canvas 0 50 600 400 %NAME% 0;")
    r = s.obj(10, 10, "r gt_tclkon")
    met = s.obj(10, 32, "metro 500")
    s.connect(r, 0, met, 0)
    t = s.obj(10, 54, "t b b")
    s.connect(met, 0, t, 0)
    on = s.msg(200, 76, "\\; reset 1")
    s.connect(t, 1, on, 0)
    d = s.obj(300, 76, "delay 10")
    s.connect(t, 1, d, 0)
    off = s.msg(300, 98, "\\; reset 0")
    s.connect(d, 0, off, 0)
    cnt = s.obj(10, 76, "f")
    inc = s.obj(60, 98, "+ 1")
    s.connect(t, 0, cnt, 0)
    s.connect(cnt, 0, inc, 0)
    s.connect(inc, 0, cnt, 1)
    md = s.obj(10, 98, "mod 2")
    s.connect(cnt, 0, md, 0)
    sl = s.obj(10, 120, "sel 0 1")
    s.connect(md, 0, sl, 0)
    m1 = s.msg(10, 142, "0 \\, 1 490")
    m2 = s.msg(100, 142, "0 \\, 0.5 490")
    s.connect(sl, 0, m1, 0)
    s.connect(sl, 1, m2, 0)
    vl = s.obj(10, 170, "vline~")
    s.connect(m1, 0, vl, 0)
    s.connect(m2, 0, vl, 0)
    osc = s.obj(150, 170, "osc~ 440")
    mul = s.obj(10, 200, "*~")
    s.connect(vl, 0, mul, 0)
    s.connect(osc, 0, mul, 1)
    rm = s.obj(250, 170, "r gt_tmute")
    lb = s.obj(350, 150, "loadbang")
    z = s.msg(350, 172, "0")
    s.connect(lb, 0, z, 0)
    eq = s.obj(250, 194, "== 0")
    s.connect(rm, 0, eq, 0)
    s.connect(z, 0, eq, 0)
    mg = chain(s, 250, 194, eq, ["pack f 5", "line~"])
    mm = s.obj(10, 260, "*~")
    s.connect(mul, 0, mm, 0)
    s.connect(mg, 0, mm, 1)
    s.connect(mm, 0, s.obj(10, 290, "outlet~"), 0)
    s.connect(mm, 0, s.obj(80, 290, "outlet~"), 0)
    return s


def glitch_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "04_glitch: clock-synced beat-repeater (port of Workshop Computer #57 Glitch). See docs/GLITCH.md.")
    c.text(10, 20, "Clock into Reset. Source = Glitch/Stutter. Record = force. Freeze = freeze. Start > half = gate.")
    c.text(10, 35, "size = division. density = probability (glitch+reverse / drift). window = X. overlap = Y. "
                   "blend = dry/wet.")
    c.sub(10, 60, "nebulae_controls", controls_canvas())
    c.obj(200, 60, f"table gt_bufl {BUF}")
    c.obj(400, 60, f"table gt_bufr {BUF}")
    c.obj(600, 60, "table gt_order 8")
    c.sub(10, 90, "ui", ui(Canvas))
    c.sub(100, 90, "clock", clock(Canvas))
    c.sub(200, 90, "glitch", glitch_mode(Canvas))
    c.sub(300, 90, "stutter", stutter_mode(Canvas))
    c.sub(400, 90, "shuffle", shuffle(Canvas))
    c.sub(500, 90, "pass_rate", pass_rate(Canvas))
    adc = c.sub(10, 140, "testsrc", beat_source(Canvas)) if test else c.obj(10, 140, "adc~ 1 2")
    wr = c.sub(10, 180, "writer", writer(Canvas))
    rd = c.sub(200, 180, "reader", reader(Canvas))
    for ch in (0, 1):
        c.connect(adc, ch, wr, ch)
        c.connect(adc, ch, rd, ch)
    c.connect(wr, 0, rd, 2)               # DSP order: writer before reader
    # blend: dry*(1-wet) + glitch*wet
    rw = c.obj(400, 140, "r gt_wet")
    wet = chain(c, 400, 140, rw, ["pack f 20", "line~"])
    dry = chain(c, 500, 184, wet, ["*~ -1", "+~ 1"])
    outs = []
    for ch, x in [(0, 10), (1, 220)]:
        wm = c.obj(x, 250, "*~")
        c.connect(rd, ch, wm, 0)
        c.connect(wet, 0, wm, 1)
        dm = c.obj(x + 100, 250, "*~")
        c.connect(adc, ch, dm, 0)
        c.connect(dry, 0, dm, 1)
        sm = c.obj(x, 280, "+~")
        c.connect(wm, 0, sm, 0)
        c.connect(dm, 0, sm, 1)
        cl = c.obj(x, 305, "clip~ -1 1")
        c.connect(sm, 0, cl, 0)
        outs.append(cl)
    dac = c.obj(10, 340, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        lb = c.obj(600, 340, "loadbang")
        steps = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps):
            if wav and "pd quit" in msg:
                msg = "\\; gt_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 365 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 387 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            # record into tables and save at quit: writesf~ drops audio in fast -batch runs (its disk thread lags)
            n = int(max(ms for ms, _ in steps) * SR / 1000)
            for ch, x in [(0, 10), (1, 200)]:
                side = "lr"[ch]
                c.obj(x, 470, f"table gt_rec{side} {n}")
                tw = c.obj(x, 440, f"tabwrite~ gt_rec{side}")
                c.connect(outs[ch], 0, tw, 0)
                c.connect(lb, 0, tw, 0)        # starts with DSP: WAV time 0 = DSP start
            rs = c.obj(400, 440, "r gt_save")
            wm2 = c.msg(400, 462, f"write -bytes 4 {wav} gt_recl gt_recr")
            sf = c.obj(400, 484, "soundfiler")
            c.connect(rs, 0, wm2, 0)
            c.connect(wm2, 0, sf, 0)
    return c
