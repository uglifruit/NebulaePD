"""08_resonator: exciter -> pitched delay-line resonator -> BBD-style delay (after the Morphor ECHON, one voice).

Generated by tools/gen.py. Design notes: docs/RESONATOR.md. User guide: patches/08_resonator_README.md.

Signal flow
  [exciter] internal (sine/tri/saw/square/noise/S&H morph x envelope, struck by Reset) or the audio input (Source)
     -> DC block -> input LP 12 dB -> x freeze mute
  [res] (block~ 16, one canvas for both sides): x + fb -> delwrite~;  vd~ D -> lop~ damping -> hip~ 1 -> x +-g
     -> soft clip -> fb.  Out = exciter dry / resonator read (alt Blend).
  [bbd] stereo delay: vd~ (time glide + wobble) -> tone LP -> hip~ -> ping-pong cross -> soft clip -> x fb
  out = equal-power mix (Blend) -> soft clip -> dac~

- Pitch: Pitch (V/oct) drives the resonator and/or the exciter (File short press: Coupled / Res only / Exc only);
  the side that doesn't follow sits at C4 + the alt Window offset.
- Tuning: the loop delay D = period - phase delay of the damping LP + phase lead of the DC blocker, all at the
  resonator pitch (control rate). Record = inverted feedback: the loop sounds at 1/(2 loop time), so the period is
  halved and the note stays put.
- Decay: g = 10^(-3 loop time / T60) / |H_lp(f)| (capped at 1), so Size is a T60 at every pitch.
"""

import math

from gloop import press
from glitch import chain
from spectral import op, fl, step, softclip, pickup
from shimmer import sig, watch

SR = 48000
C4 = 261.6256
FMIN, FMAX = 20.0, 2600.0          # resonator pitch clamp (top: the 16-sample loop minimum; half when inverted)
EMIN, EMAX = 10.0, 8000.0          # exciter pitch clamp
RBLOCK = 16                        # [pd res] block size: the shortest loop delay
DMIN = RBLOCK + 1                  # samples (vd~ interpolation needs one more)
KRES = 0.0                         # residual loop latency in samples (measured offline: see docs/RESONATOR.md)
HIPF = 1.0                         # loop DC blocker (Hz)
EXC = 0.8                          # internal exciter level into the loop (x (1 + periods per strike)^-0.75)
SHAPE_K = [0.85, 1.0, 1.0, 0.6, 2.0, 3.0]  # sine, tri, saw, square, noise, S&H (noise builds up less)
KX = 1.0                           # audio-input exciter: x min(1, KX sqrt(1 - G)) (G = loop gain at the pitch)
AGC_DB = 91                        # auto-level: excitation backs off while the resonator is above this (env~ dB)
AGC_ATT, AGC_REL = 0.5, 0.1        # per env~ period (5.3 ms): -0.5 x the excess dB / +0.1 dB back, to 0 dB
AGC_MIN = -40
TONE_LO, TONE_HI = 1500.0, 16000.0  # delay tone LP (alt Overlap)
WOB_MS = 1.5                       # delay wobble depth at the murkiest tone
DT_LO, DT_HI = 20.0, 2000.0        # delay time (Speed)
HOLD_MS = 300                      # File held this long = delay hold; shorter = step the V/oct mode
LN2 = math.log(2)
TAU = 2 * math.pi
# alt-layer defaults (load, and Source + Record): input LP open, spread 6 cents, no auto-repeat, delay tone 0.35,
# offset 0, resonator only (no exciter dry), V/oct mode Coupled
ALT_RESET = ("\\; rs_ilp 100000 \\; rs_sp 6 \\; rs_repk 0 \\; rs_tonek 0.35 \\; rs_Ochg set 0 \\; rs_O 0 "
             "\\; rs_bal 1 \\; rs_mode 0")


# --- control-rate expressions --------------------------------------------------------------------------------------
# Old Pd has no [expr]: E trees compile to chains of [+ - * / pow max min == != sin cos atan exp sqrt abs] fed by
# [v name] and constants, evaluated right to left by [t b b] (right operand first, into the cold inlet).
class E:
    def __init__(self, o, *a):
        self.o, self.a = o, a

    def __add__(self, b):
        return E("+", self, lift(b))

    def __radd__(self, b):
        return E("+", lift(b), self)

    def __sub__(self, b):
        return E("-", self, lift(b))

    def __rsub__(self, b):
        return E("-", lift(b), self)

    def __mul__(self, b):
        return E("*", self, lift(b))

    def __rmul__(self, b):
        return E("*", lift(b), self)

    def __truediv__(self, b):
        return E("/", self, lift(b))

    def __rtruediv__(self, b):
        return E("/", lift(b), self)


def lift(x):
    return x if isinstance(x, E) else E("k", float(x))


def V(name):
    return E("v", name)


def _f1(name):
    return lambda a: E(name, lift(a))


sin, cos, atan, exp, log, sqrt, fabs = (_f1(n) for n in ("sin", "cos", "atan", "exp", "log", "sqrt", "abs"))


def mn(a, b):
    return E("min", lift(a), lift(b))


def mx(a, b):
    return E("max", lift(a), lift(b))


def eq(a, b):
    return E("==", lift(a), lift(b))


def gt(a, b):
    return E(">", lift(a), lift(b))


def ne(a, b):
    return E("!=", lift(a), lift(b))


def fmt(v):
    return f"{v:.9g}"


COMMUTE = {"+", "*", "max", "min", "==", "!="}


class Prog:
    """Lays out and emits E trees on canvas c, in columns from (x, y)."""
    def __init__(self, c, x, y):
        self.c, self.x, self.y, self.n = c, x, y, 0

    def _pos(self):
        i = self.n
        self.n += 1
        return self.x + (i // 45) * 120, self.y + (i % 45) * 22

    def obj(self, text):
        return self.c.obj(*self._pos(), text)

    def msg(self, text):
        return self.c.msg(*self._pos(), text)

    def emit(self, e, src):
        """src (id, outlet) bangs -> returns the object whose outlet 0 sends the value of e."""
        c = self.c
        if e.o == "k":
            n = self.msg(fmt(e.a[0]))
            c.connect(src[0], src[1], n, 0)
            return n
        if e.o == "v":
            n = self.obj(f"v {e.a[0]}")
            c.connect(src[0], src[1], n, 0)
            return n
        if len(e.a) == 1:
            a = self.emit(e.a[0], src)
            n = self.obj(e.o)
            c.connect(a, 0, n, 0)
            return n
        a, b = e.a
        if a.o == "k" and b.o != "k" and e.o in COMMUTE:
            a, b = b, a
        if b.o == "k":
            ao = self.emit(a, src)
            n = self.obj(f"{e.o} {fmt(b.a[0])}")
            c.connect(ao, 0, n, 0)
            return n
        t = self.obj("t b b")
        c.connect(src[0], src[1], t, 0)
        bo = self.emit(b, (t, 1))
        n = self.obj(e.o)
        c.connect(bo, 0, n, 1)
        ao = self.emit(a, (t, 0))
        c.connect(ao, 0, n, 0)
        return n


def program(c, x, y, src, assigns):
    """On each bang from src run assigns [(targets, E)] in list order. targets: space-separated 's:name' (send) or
    'v:name' (set [v name], for later assigns)."""
    p = Prog(c, x, y)
    n = len(assigns)
    t = p.obj("t" + " b" * n)
    s, o = src if isinstance(src, tuple) else (src, 0)
    c.connect(s, o, t, 0)
    for i, (targets, e) in enumerate(assigns):
        out = p.emit(e, (t, n - 1 - i))
        for tg in targets.split():
            kind, name = tg.split(":")
            c.connect(out, 0, p.obj(f"{'s' if kind == 's' else 'v'} {name}"), 0)
    return t


def watched(c, x, y, names, assigns):
    """watch(names) -> one program."""
    comp = c.obj(x, y + 70, "t b")
    watch(c, x, y, names, comp)
    return program(c, x, y + 100, comp, assigns)


