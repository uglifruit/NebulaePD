def resonator_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "08_resonator: exciter -> pitched delay-line resonator -> BBD delay. See docs/RESONATOR.md.")
    c.text(10, 20, "pitch=V/oct start=material size=decay density=envelope window=damping overlap=delay fb "
                   "blend=delay mix speed=delay time.")
    c.text(10, 35, "Reset=strike Freeze=hold Source=audio in Record=invert File short=V/oct mode (coupled/res/exc) "
                   "File held=delay hold. Alt: start=input LP size=spread density=repeat overlap=delay tone "
                   "window=offset blend=dry/res pitch=ping-pong.")
    c.sub(10, 60, "nebulae_controls", controls_canvas())
    c.sub(150, 60, "ui", ui(Canvas, test=bool(test)))
    adc = c.sub(10, 100, "testsrc", test_source(Canvas)) if test else c.obj(10, 100, "adc~ 1 2")
    ex = c.sub(10, 140, "exciter", exciter(Canvas))
    rv = c.sub(10, 170, "res", res(Canvas))
    dl = c.sub(10, 200, "bbd", bbd(Canvas))
    for s in (0, 1):
        c.connect(adc, s, ex, s)
        c.connect(ex, s, rv, s)
        c.connect(rv, s, dl, s)
    # auto-level: the resonator's rms (env~ dB) above AGC_DB pulls the excitation down, then it recovers
    ev = chain(c, 400, 300, op(c, 400, 300, "*~ 0.5", op(c, 400, 280, "+~", (rv, 0), (rv, 1))), ["env~ 1024 256"])
    c.connect(ev, 0, c.obj(400, 344, "v rs_env"), 0)
    G, OV = V("rs_agcdb"), V("rs_env") - AGC_DB
    program(c, 520, 300, ev, [
        ("v:rs_agcdb", mx(AGC_MIN, mn(0, G + gt(OV, 0) * OV * -AGC_ATT + (1 - gt(OV, 0)) * AGC_REL))),
        ("s:rs_agc", exp(G * (math.log(10) / 20)))])
    gw = sig(c, 400, 100, "rs_gw", 30)
    gd = sig(c, 500, 100, "rs_gd", 30)
    outs = []
    for s, x in [(0, 10), (1, 220)]:
        o = op(c, x, 260, "+~", op(c, x, 238, "*~", (rv, s), gd), op(c, x + 100, 238, "*~", (dl, s), gw))
        outs.append(softclip(c, x, 290, o))
    dac = c.obj(10, 420, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        lb = c.obj(600, 340, "loadbang")
        steps_ = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps_):
            if wav and "pd quit" in msg:
                msg = "\\; rs_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 365 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 387 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            # record into tables and save at quit: writesf~ drops audio in fast -batch runs (its disk thread lags)
            n = int(max(ms for ms, _ in steps_) * SR / 1000)
            for ch_, x in [(0, 10), (1, 200)]:
                side = "lr"[ch_]
                c.obj(x, 500, f"table rs_rec{side} {n}")
                tw = c.obj(x, 470, f"tabwrite~ rs_rec{side}")
                c.connect(outs[ch_], 0, tw, 0)
                c.connect(lb, 0, tw, 0)        # starts with DSP: WAV time 0 = DSP start
            rs = c.obj(400, 470, "r rs_save")
            wm2 = c.msg(400, 492, f"write -bytes 4 {wav} rs_recl rs_recr")
            sf = c.obj(400, 514, "soundfiler")
            c.connect(rs, 0, wm2, 0)
            c.connect(wm2, 0, sf, 0)
    return c
