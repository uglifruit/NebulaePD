def exciter(Canvas):
    """Internal exciter (6 materials x envelope) or the audio input -> DC block -> 12 dB LP -> x freeze mute."""
    c = Canvas("#N canvas 0 50 1100 700 %NAME% 0;")
    c.text(10, 5, "phasor~ at rs_fexc -> sine/tri/saw/square/noise/S&H (crossfade weights rs_x0..5) x envelope^2")
    ins = [c.obj(10 + s * 500, 400, "inlet~") for s in (0, 1)]
    ph = op(c, 10, 52, "phasor~", sig(c, 10, 8, "rs_fexc", 5))
    rs = op(c, 300, 30, "t b b b", c.obj(300, 8, "r rs_strike"))
    z = c.msg(150, 52, "0")
    c.connect(rs, 2, z, 0)
    c.connect(z, 0, ph, 1)
    pk = c.obj(300, 96, "pack f f")
    c.connect(op(c, 360, 66, "v rs_Dc", (rs, 1)), 0, pk, 1)
    c.connect(op(c, 300, 66, "v rs_A", (rs, 0)), 0, pk, 0)
    m = c.msg(300, 118, "1 \\$1 \\, 0 \\$2 \\$1")
    c.connect(pk, 0, m, 0)
    env = op(c, 300, 140, "vline~", m)
    env2 = op(c, 300, 162, "*~", env, env)
    shapes = [
        op(c, 10, 120, "cos~", op(c, 10, 98, "+~ 0.75", ph)),
        chain(c, 100, 98, op(c, 100, 98, "-~ 0.5", ph), ["abs~", "*~ -4", "+~ 1"]),
        chain(c, 200, 98, op(c, 200, 98, "*~ 2", ph), ["-~ 1"]),
        chain(c, 300, 222, step(c, 300, 200, op(c, 300, 178, "-~ 0.5", ph)), ["*~ 2", "-~ 1"]),
    ]
    nz = c.obj(500, 98, "noise~")
    shapes += [nz, op(c, 600, 120, "samphold~", nz, ph)]
    tot = None
    for k, s in enumerate(shapes):
        xk = 10 + k * 110
        w = op(c, xk, 300, "*~", op(c, xk, 278, f"*~ {SHAPE_K[k]:g}", s), sig(c, xk + 60, 234, f"rs_x{k}", 20))
        tot = w if tot is None else op(c, xk, 322, "+~", tot, w)
    kf = sig(c, 100, 322, "rs_kf", 20)
    internal = op(c, 10, 366, f"*~ {EXC:g}", op(c, 10, 344, "*~", tot, op(c, 100, 344, "*~", env2, kf)))
    ext = sig(c, 800, 300, "rs_ext", 20)
    icx = sig(c, 900, 300, "rs_icx", 50)
    nf = op(c, 1000, 344, "*~", sig(c, 1000, 300, "rs_nf", 10), sig(c, 1060, 300, "rs_agc", 6))
    nint = op(c, 800, 390, "*~", internal, op(c, 800, 368, "+~ 1", op(c, 800, 346, "*~ -1", ext)))
    gx = op(c, 900, 368, "*~", ext, icx)
    for s in (0, 1):
        x0 = 10 + s * 500
        e = op(c, x0, 450, "+~", nint, op(c, x0 + 60, 428, "*~", ins[s], gx))
        h = op(c, x0, 472, "hip~ 20", e)
        lp = fl(c, x0, 520, "lop~ 100000", fl(c, x0, 498, "lop~ 100000", h, "rs_ilp"), "rs_ilp")
        c.connect(op(c, x0, 542, "*~", lp, nf), 0, c.obj(x0, 570, "outlet~"), 0)
    return c


def res(Canvas):
    """Two pitched feedback loops (L/R) in one block~ 16 canvas. Out = exciter * (1 - bal) + read * bal."""
    c = Canvas("#N canvas 0 50 900 600 %NAME% 0;")
    c.text(10, 5, "x + fb -> delwrite~ / vd~ D -> lop~ damping -> hip~ 1 -> x g -> soft clip -> fb. "
                  f"block~ {RBLOCK}: the shortest loop is {RBLOCK} samples.")
    c.obj(700, 5, f"block~ {RBLOCK}")
    g = sig(c, 600, 30, "rs_g", 20)
    bal = sig(c, 700, 30, "rs_bal", 50)
    nbal = op(c, 700, 96, "+~ 1", op(c, 700, 74, "*~ -1", bal))
    for s in (0, 1):
        x0 = 10 + s * 300
        e = c.obj(x0, 30, "inlet~")
        r = op(c, x0 + 100, 110, f"vd~ rs_r{s}", sig(c, x0 + 100, 44, f"rs_D{s}", 5))
        z = fl(c, x0 + 100, 154, "lop~ 100000", r, "rs_damp")
        h = op(c, x0 + 100, 176, f"hip~ {HIPF:g}", z)
        f = softclip(c, x0 + 100, 220, op(c, x0 + 100, 198, "*~", h, g))
        w = op(c, x0, 360, "+~", e, f)
        c.connect(w, 0, c.obj(x0, 382, f"delwrite~ rs_r{s} 60"), 0)
        o = op(c, x0, 440, "+~", op(c, x0, 418, "*~", e, nbal), op(c, x0 + 100, 418, "*~", r, bal))
        c.connect(o, 0, c.obj(x0, 470, "outlet~"), 0)
    return c


def bbd(Canvas):
    """Stereo BBD-style delay: time glide + wobble, tone LP and low cut in the loop, ping-pong, soft clip."""
    c = Canvas("#N canvas 0 50 1000 700 %NAME% 0;")
    c.text(10, 5, "in -> (+ fb) -> delwrite~ / vd~ (time + wobble) -> tone LP -> hip~ -> ping-pong -> soft clip x fb")
    lb = c.obj(900, 5, "loadbang")
    il, ir = c.obj(10, 30, "inlet~"), c.obj(400, 30, "inlet~")
    pp = sig(c, 600, 30, "rs_pp", 50)
    npp = op(c, 600, 96, "+~ 1", op(c, 600, 74, "*~ -1", pp))
    ein = sig(c, 700, 30, "rs_ein", 20)
    eg = sig(c, 800, 30, "rs_eg", 20)
    dt = sig(c, 600, 130, "rs_dt", 150)
    wob = sig(c, 700, 130, "rs_wob", 100)
    # ping-pong input: all to L (as the mono sum) at pp = 1
    mono = op(c, 10, 140, "*~", op(c, 10, 118, "*~ 0.5", op(c, 10, 96, "+~", il, ir)), pp)
    a = [op(c, 10, 184, "*~", op(c, 10, 162, "+~", op(c, 100, 140, "*~", il, npp), mono), ein),
         op(c, 400, 184, "*~", op(c, 400, 140, "*~", ir, npp), ein)]
    rd, z = [], []
    for s in (0, 1):
        x0 = 10 + s * 400
        osc = op(c, x0 + 200, 230, "osc~", c.obj(x0 + 200, 208, f"sig~ {0.3 * (1 + 0.23 * s):g}"))
        ph = c.msg(x0 + 260, 208, f"{0.5 * s:g}")
        c.connect(lb, 0, ph, 0)
        c.connect(ph, 0, osc, 1)
        wv = op(c, x0 + 200, 274, "*~", op(c, x0 + 200, 252, "*~ 0.5", op(c, x0 + 200, 230 + 22, "+~ 1", osc)), wob)
        r = op(c, x0, 320, f"vd~ rs_e{s}", op(c, x0, 298, "+~", dt, wv))
        rd.append(r)
        z.append(fl(c, x0, 386, "hip~ 60", fl(c, x0, 364, "lop~ 5000", r, "rs_etone"), "rs_ehp"))
    for s in (0, 1):
        x0 = 10 + s * 400
        f = op(c, x0, 452, "+~", op(c, x0, 430, "*~", z[s], npp), op(c, x0 + 80, 430, "*~", z[1 - s], pp))
        w = op(c, x0, 600, "+~", a[s], softclip(c, x0, 474, op(c, x0, 452 + 22, "*~", f, eg)))
        c.connect(w, 0, c.obj(x0, 630, f"delwrite~ rs_e{s} 2100"), 0)
        c.connect(z[s], 0, c.obj(x0 + 200, 660, "outlet~"), 0)
    return c


