SR = 48000
C4 = 261.6256
FMIN, FMAX = 20.0, 2600.0          # resonator pitch clamp (top: the 16-sample loop minimum; half when inverted)
EMIN, EMAX = 10.0, 8000.0          # exciter pitch clamp
RBLOCK = 16                        # [pd res] block size: the shortest loop delay
DMIN = RBLOCK + 1                  # samples (vd~ interpolation needs one more)
KRES = 0.0                         # residual loop latency in samples (measured offline: see docs/RESONATOR.md)
HIPF = 1.0                         # loop DC blocker (Hz)
EXC = 0.8                          # internal exciter level into the loop (x (1 + periods per strike)^-0.75)
SHAPE_K = [0.85, 1.0, 1.0, 0.6, 2.0, 3.0]  # sine, tri, saw, square, noise, S&H (noise builds up less)
KX = 1.0                           # audio-input exciter: x min(1, KX sqrt(1 - G)) (G = loop gain at the pitch)
AGC_DB = 85                        # auto-level, per voice (-15 dB rms; 4 voices on one pitch sum +12): its excitation backs off above this (env~ dB)
AGC_ATT, AGC_REL = 0.5, 0.1        # per env~ period (5.3 ms): -0.5 x the excess dB / +0.1 dB back, to 0 dB
AGC_MIN = -40
TONE_LO, TONE_HI = 1500.0, 16000.0  # delay tone LP (alt Overlap)
WOB_MS = 1.5                       # delay wobble depth at the murkiest tone
DT_LO, DT_HI = 20.0, 2000.0        # delay time (Speed)
HOLD_MS = 300                      # File held this long = delay hold; shorter = step the V/oct mode
VOICES = 4                         # notes; each strike takes the next voice = the oldest note (note stealing)
CATCH_MS = 10                      # a new note follows Pitch this long after its strike, then holds its pitch
                                   # (about 2 poll passes: catches a CV that lands one pass after the gate)
PAN = [-1.0, 1.0, -1 / 3, 1 / 3]   # voice pan positions x width (alt Size); consecutive notes alternate sides
VOICE_G = 0.8                      # resonator output per voice (4 can ring at once)
MUTE_DOWN, MUTE_UP = 0.5, 0.25     # steal mute ramps (ms); the new strike starts after both (STRIKE_LAG)
STRIKE_LAG = MUTE_DOWN + MUTE_UP   # so none of the new excitation lands while the loop is muted
LN2 = math.log(2)
TAU = 2 * math.pi
# alt-layer defaults (load, and Source + Record): input LP open, stereo width 0.6, no auto-repeat, delay tone 0.35,
# offset 0, resonator only (no exciter dry), V/oct mode Coupled
ALT_RESET = ("\\; rs_ilp 100000 \\; rs_wd 0.6 \\; rs_repk 0 \\; rs_tonek 0.35 \\; rs_Ochg set 0 \\; rs_O 0 "
             "\\; rs_bal 1 \\; rs_mode 0")


# --- control-rate expressions --------------------------------------------------------------------------------------
# Old Pd has no [expr]: E trees compile to chains of [+ - * / pow max min == != sin cos atan exp sqrt abs] fed by
# [v name] and constants, evaluated right to left by [t b b] (right operand first, into the cold inlet).
class E:
    def __init__(self, o, *a):
        self.o, self.a = o, a

    def __add__(self, b):
        return E("+", self, lift(b))

    def __radd__(self, b):
        return E("+", lift(b), self)

    def __sub__(self, b):
        return E("-", self, lift(b))

    def __rsub__(self, b):
        return E("-", lift(b), self)

    def __mul__(self, b):
        return E("*", self, lift(b))

    def __rmul__(self, b):
        return E("*", lift(b), self)

    def __truediv__(self, b):
        return E("/", self, lift(b))

    def __rtruediv__(self, b):
        return E("/", lift(b), self)


def lift(x):
    return x if isinstance(x, E) else E("k", float(x))


def V(name):
    return E("v", name)


def _f1(name):
    return lambda a: E(name, lift(a))


sin, cos, atan, exp, log, sqrt, fabs = (_f1(n) for n in ("sin", "cos", "atan", "exp", "log", "sqrt", "abs"))


def mn(a, b):
    return E("min", lift(a), lift(b))


def mx(a, b):
    return E("max", lift(a), lift(b))


def eq(a, b):
    return E("==", lift(a), lift(b))


def gt(a, b):
    return E(">", lift(a), lift(b))


def ne(a, b):
    return E("!=", lift(a), lift(b))


def fmt(v):
    return f"{v:.9g}"


COMMUTE = {"+", "*", "max", "min", "==", "!="}


class Prog:
    """Lays out and emits E trees on canvas c, in columns from (x, y)."""
    def __init__(self, c, x, y):
        self.c, self.x, self.y, self.n = c, x, y, 0

    def _pos(self):
        i = self.n
        self.n += 1
        return self.x + (i // 45) * 120, self.y + (i % 45) * 22

    def obj(self, text):
        return self.c.obj(*self._pos(), text)

    def msg(self, text):
        return self.c.msg(*self._pos(), text)

    def emit(self, e, src):
        """src (id, outlet) bangs -> returns the object whose outlet 0 sends the value of e."""
        c = self.c
        if e.o == "k":
            n = self.msg(fmt(e.a[0]))
            c.connect(src[0], src[1], n, 0)
            return n
        if e.o == "v":
            n = self.obj(f"v {e.a[0]}")
            c.connect(src[0], src[1], n, 0)
            return n
        if len(e.a) == 1:
            a = self.emit(e.a[0], src)
            n = self.obj(e.o)
            c.connect(a, 0, n, 0)
            return n
        a, b = e.a
        if a.o == "k" and b.o != "k" and e.o in COMMUTE:
            a, b = b, a
        if b.o == "k":
            ao = self.emit(a, src)
            n = self.obj(f"{e.o} {fmt(b.a[0])}")
            c.connect(ao, 0, n, 0)
            return n
        t = self.obj("t b b")
        c.connect(src[0], src[1], t, 0)
        bo = self.emit(b, (t, 1))
        n = self.obj(e.o)
        c.connect(bo, 0, n, 1)
        ao = self.emit(a, (t, 0))
        c.connect(ao, 0, n, 0)
        return n


def program(c, x, y, src, assigns):
    """On each bang from src run assigns [(targets, E)] in list order. targets: space-separated 's:name' (send) or
    'v:name' (set [v name], for later assigns)."""
    p = Prog(c, x, y)
    n = len(assigns)
    t = p.obj("t" + " b" * n)
    s, o = src if isinstance(src, tuple) else (src, 0)
    c.connect(s, o, t, 0)
    for i, (targets, e) in enumerate(assigns):
        out = p.emit(e, (t, n - 1 - i))
        for tg in targets.split():
            kind, name = tg.split(":")
            c.connect(out, 0, p.obj(f"{'s' if kind == 's' else 'v'} {name}"), 0)
    return t


def watched(c, x, y, names, assigns):
    """watch(names) -> one program."""
    comp = c.obj(x, y + 70, "t b")
    watch(c, x, y, names, comp)
    return program(c, x, y + 100, comp, assigns)


def voice_assigns(k):
    """Voice k: damping, gain, loop delay, exciter level and audio-input level from its own pitch rs_frk<k>."""
    INV, W, RT, FRZ, D = V("rs_inv_v"), V("rs_w_v"), V("rs_rt_v"), V("rs_frz_v"), V("rs_d_v")
    FR, FC, B, H, OM = V(f"rs_fq{k}"), V(f"rs_fc{k}"), V(f"rs_b{k}"), V(f"rs_H{k}"), V(f"rs_om{k}")
    loss = mn(1, exp(-6.9078 * (1 - 0.5 * INV) / (FR * RT)) / H)          # per-pass gain for T60, capped at 1
    return [
        (f"v:rs_fq{k}", mx(FMIN, mn(FMAX * (1 - 0.5 * INV), V(f"rs_frk{k}_v")))),
        (f"v:rs_fc{k} s:rs_damp{k}", FRZ * 100000 + (1 - FRZ) * FR * exp((1 + 5.5 * W) * LN2)),
        (f"v:rs_b{k}", 1 - mn(1, FC * (TAU / SR))),
        (f"v:rs_om{k}", FR * (TAU / SR)),
        (f"v:rs_H{k}", (1 - B) / sqrt(1 - 2 * B * cos(OM) + B * B)),
        (f"s:rs_g{k}", (FRZ + (1 - FRZ) * loss) * (1 - 2 * INV)),
        (f"s:rs_icx{k}", mn(1, KX * sqrt(mx(0, 1 - loss * H)))),
        (f"v:rs_Dv{k} s:rs_D{k}", mx(DMIN, SR * (1 - 0.5 * INV) / FR - atan(B * sin(OM) / (1 - B * cos(OM))) / OM
                                      + atan(HIPF / FR) / OM - KRES) * (1000 / SR)),
        # internal exciter gain: a strike spanning more periods of a matched tone builds up more
        (f"s:rs_kf{k}", exp(-0.75 * log(1 + FR * (0.5 * exp(D * math.log(3000)) + 2.5 * exp(D * math.log(600)))
                                        / 1000))),
    ]


def voices_ctl(c, x, y):
    """rs_go (a strike): the next voice (= the oldest note) takes the live pitches now and for CATCH_MS, its output and
    feedback are muted for one period of its new note (flushes the stolen note), then its exciter fires."""
    vrecv(c, x, y, "rs_av")
    for k in range(VOICES):
        vrecv(c, x + 300 + k * 100, y, f"rs_agcdb{k}")
    fr, fe = c.obj(x, y + 66, "r rs_fr"), c.obj(x + 120, y + 66, "r rs_fexc")
    for k in range(VOICES):
        xk = x + k * 240
        gate = c.obj(xk, y + 110, f"r rs_cat{k}")
        for j, (src, dst) in enumerate(((fr, f"rs_frk{k}"), (fe, f"rs_fek{k}"))):
            sp = op(c, xk + j * 110, y + 154, "spigot", src, gate)
            c.connect(sp, 0, c.obj(xk + j * 110, y + 176, f"s {dst}"), 0)
    catch_off = " ".join(f"\\; rs_cat{k} 0" for k in range(VOICES))
    tg = op(c, x, y + 242, "t b b b b", c.obj(x, y + 220, "r rs_go"))
    # 1. next voice
    c.connect(chain(c, x + 600, y + 242, op(c, x + 600, y + 264, "v rs_av", (tg, 3)), ["+ 1", f"mod {VOICES}"]), 0,
              c.obj(x + 600, y + 330, "s rs_av"), 0)
    # 2. open its catch window (only its own) and restart the timer that closes it
    dl = c.obj(x + 400, y + 308, f"delay {CATCH_MS}")
    c.connect(dl, 0, c.msg(x + 400, y + 330, catch_off), 0)
    t2 = op(c, x + 400, y + 264, "t b b", (tg, 2))
    c.connect(t2, 0, dl, 0)
    sl = op(c, x + 200, y + 330, f"sel {' '.join(map(str, range(VOICES)))}",
            op(c, x + 200, y + 308, "v rs_av", (t2, 1)))
    # 3. per voice: catch on + push the live pitches (its program computes D), mute for D, fire its exciter
    for k in range(VOICES):
        xk = x + k * 240
        tk = op(c, xk, y + 400, "t b b b b", (sl, k))
        c.connect(tk, 3, c.msg(xk + 150, y + 422,
                               " ".join(f"\\; rs_cat{j} {int(j == k)}" for j in range(VOICES))), 0)
        c.connect(op(c, xk + 100, y + 444, "v rs_fenow", (tk, 2)), 0, c.obj(xk + 100, y + 466, f"s rs_fek{k}"), 0)
        c.connect(op(c, xk + 50, y + 422, "v rs_frnow", (tk, 2)), 0, c.obj(xk + 50, y + 466, f"s rs_frk{k}"), 0)
        # mute: down in MUTE_DOWN, back up once everything written before then has left the line (D + MUTE_DOWN);
        # the strike waits STRIKE_LAG, so its excitation is written only after the loop is open again
        m = c.msg(xk, y + 510, f"0 {MUTE_DOWN:g} \\, 1 {MUTE_UP:g} \\$1")
        c.connect(chain(c, xk, y + 444, op(c, xk, y + 466, f"v rs_Dv{k}", (tk, 1)), [f"+ {MUTE_DOWN:g}"]), 0, m, 0)
        c.connect(tk, 1, c.msg(xk + 60, y + 554, f"\\; rs_agcdb{k} 0 \\; rs_agc{k} 1"), 0)
        c.connect(m, 0, c.obj(xk, y + 532, f"s rs_mute{k}"), 0)
        c.connect(chain(c, xk + 120, y + 466, tk, [f"delay {STRIKE_LAG:g}"]), 0, c.obj(xk + 120, y + 510,
                                                                                       f"s rs_strike{k}"), 0)


def vrecv(c, x, y, name):
    """[r name] -> [v name]: a '; name value' message sets the variable."""
    c.connect(c.obj(x, y, f"r {name}"), 0, c.obj(x, y + 22, f"v {name}"), 0)


