"""12_shift: a frequency shifter inside a tape-ish feedback delay (barber-pole echoes) for the Nebulae.

Generated by tools/gen.py. Design notes: docs/SHIFT.md. User guide: patches/12_shift_README.md.

Designed with the owner on 2026-11-14 (Pitch = shift amount, Speed = time with Reset clocking it, three modes,
tape-ish loop). Pd can't light LEDs, so the modes became Source = Ring (its light) and File = Barber.

Per side (left, right: the right side's shift is scaled by 1 - 2 x Size, so Size fully clockwise = opposite):
  in x (1 - freeze) + feedback x [(1 - pingpong) x own wet + pingpong x other side's wet] -> delwrite~
  vd~ (time: Speed / clock, a 250 ms tape glide, wow) -> Hilbert pair (Pd's hilbert~ coefficients)
     -> single sideband (re cos - im sin; the shift's sign sets the direction) or Ring (re cos, x sqrt 2)
     -> tone (lop~ + hip~ on Window) or Barber (band-pass bell on Window) -> low cut
     -> drive x softclip / drive = wet (heard, and fed back)
  + direct: the input through its own Hilbert pair and the same oscillator (Overlap) = a plain shifter, no delay
  out = equal-power mix (Blend) of dry and wet -> soft clip
"""

import math

from gloop import press
from glitch import chain
from spectral import op, softclip, pickup
from shimmer import sig
from resonator import V, E, lift, mn, mx, gt, exp, fabs, watched, program

SR = 48000
BUF_MS = 10000                           # delay buffer per side
T_MIN, T_MAX = 2.0, 9500.0               # ms (the feedback loop is at least one 64-sample block)
FREE_MAX = 2000.0                        # Speed free range 1 .. 2000 ms (2000^speed, clipped at T_MIN)
DIVS = [("1/16", 0.25), ("1/8", 0.5), ("1/8.", 0.75), ("1/4", 1), ("1/2", 2), ("1 bar", 4), ("2 bars", 8)]
CLK_MIN, CLK_MAX = 30, 4000              # ms between clock pulses that count as a clock
CLK_TIMEOUT = 2000                       # ms without a pulse (or 2.5 beats, if longer) -> free again
JUMP = 15                                # ms: an interval this far from the average = a new tempo
AVG_K = 0.3                              # running-average step per pulse (jitter of 1-3 ms averages out)
HYST_FINE = 1.0                          # ms: the time follows the average only past this
SHIFT_MIN, SHIFT_MAX, SHIFT_CAP = 0.1, 1000.0, 2000.0   # Hz at the deadband edge / full turn / CV limit
DEAD = 0.004                             # Pitch deadband around the click (0.6)
UP_SPAN, DN_SPAN = 0.4 - DEAD, 0.6 - DEAD
GLIDE_MS = 250                           # delay-time slew (a tape-like pitch bend when the time changes)
HILBERT = [  # Pd's extra/hilbert~.pd (Favreau's 4X pair): real branch, imaginary branch
    ["-0.02569 0.260502 -0.260502 0.02569 1", "1.8685 -0.870686 0.870686 -1.8685 1"],
    ["1.94632 -0.94657 0.94657 -1.94632 1", "0.83774 -0.06338 0.06338 -0.83774 1"],
]
BARBER_Q = 1.0
BARBER_GAIN = 0.632                     # bp~ peaks +4 dB at its centre (Q 1): measured in tools/shift_tests.py
FREEZE_LC = 5.0                         # Hz: the low cut while frozen (the loop holds; DC still goes)
# alt defaults (load, and Source + Record): wow 0.6 ms, drive x2, low cut ~27 Hz, wow rate ~0.5 Hz
ALT = dict(wd=0.15, dr=0.2, lc=0.1, wr=0.4)


def wow_ms(x):
    return 4.0 * x


def drive_of(x):
    return 1 + 5 * x


def lowcut_of(x):
    return 20 * 25 ** x


def wowrate_of(x):
    return 0.1 * 50 ** x


ALT_RESET = (f"\\; sh_wd {wow_ms(ALT['wd']):g} \\; sh_g {drive_of(ALT['dr']):g} "
             f"\\; sh_gi {1 / drive_of(ALT['dr']):.6g} \\; sh_lc {lowcut_of(ALT['lc']):.4g} "
             f"\\; sh_wr {wowrate_of(ALT['wr']):.4g}")


def shift_hz(p):
    """Pitch value -> shift in Hz (the patch computes the same; tests use this and its inverse)."""
    x = p - 0.6
    d = max(0.0, abs(x) - DEAD)
    if d == 0:
        return 0.0
    m = d / (UP_SPAN if x > 0 else DN_SPAN)
    return math.copysign(min(SHIFT_CAP, SHIFT_MIN * (SHIFT_MAX / SHIFT_MIN) ** m), x)


def pitch_for(hz):
    m = math.log(abs(hz) / SHIFT_MIN) / math.log(SHIFT_MAX / SHIFT_MIN)
    return 0.6 + math.copysign(DEAD + m * (UP_SPAN if hz > 0 else DN_SPAN), hz)


def free_ms(speed):
    return max(T_MIN, FREE_MAX ** speed)


def E_int(a):
    return E("int", lift(a))


def E_tab(name, i):
    return E(f"tabread {name}", lift(i))


def ui(Canvas, test=False):
    c = Canvas("#N canvas 0 50 1500 1100 %NAME% 0;")
    c.text(10, 5, "pitch=shift speed=time (Reset clock: division) density=feedback window=tone blend=mix size=stereo "
                  "start=ping-pong overlap=direct. Source=Ring File=Barber Record=flip Freeze=hold. "
                  "alt: start=wow size=drive density=low cut overlap=wow rate")
    lb = c.obj(1300, 30, "loadbang")
    c.connect(chain(c, 1300, 30, lb, ["delay 1000"]), 0, c.msg(1300, 80, "\\; sh_primed 1"), 0)
    c.connect(lb, 0, c.msg(700, 30, "\\; sh_P 0.6 \\; sh_rec 0 \\; sh_sz 0 \\; sh_spd 0.5 \\; sh_per 500 "
                                    "\\; sh_clk 0 \\; sh_arm 0 \\; sh_fb 0.4 \\; sh_frz 0 \\; sh_w 0.5 \\; sh_lc 27 "
                                    "\\; sh_gw 0.7071 \\; sh_gd 0.7071 \\; sh_pp 0 \\; sh_dl 0 \\; sh_ring 0 "
                                    "\\; sh_bb 0 " + ALT_RESET), 0)
    c.obj(1300, 120, f"table sh_divs {len(DIVS)}")
    c.connect(lb, 0, c.msg(1300, 142, "\\; sh_divs 0 " + " ".join(f"{m:g}" for _, m in DIVS)), 0)
    x, y = 10, 60
    for i, (src, dst, conv) in enumerate([
            ("pitch", "sh_P", []), ("size", "sh_sz", ["clip 0 1"]), ("speed", "sh_spd", ["clip 0 1"]),
            ("density", "sh_fb", ["clip 0 1", "* 1.1"]), ("window", "sh_w", ["clip 0 1"]),
            ("start", "sh_pp", ["clip 0 1"]), ("overlap", "sh_dl", ["clip 0 1"]),
            ("record", "sh_rec", []), ("source", "sh_ring", []), ("freeze", "sh_frz", [])]):
        # change -1: the first value always passes (a knob fully down must still replace the load default)
        chain(c, x + i * 120, y, c.obj(x + i * 120, y, f"r {src}"), ["change -1"] + conv + [f"s {dst}"])
    tb = op(c, x, y + 150, "t f f", chain(c, x, y + 100, c.obj(x, y + 100, "r blend"),
                                          ["change -1", "clip 0 1", "* 1.5708"]))
    chain(c, x + 60, y + 150, tb, ["sin", "s sh_gw"], outlet=1)
    chain(c, x, y + 150, tb, ["cos", "s sh_gd"])
    # File (the raw button) toggles Barber
    fp = press(c, x + 200, y + 100, "filestate", True, primed="sh_primed")
    cnt = op(c, x + 200, y + 190, "f", fp)
    tc = op(c, x + 200, y + 234, "t f f", chain(c, x + 200, y + 190, cnt, ["+ 1", "mod 2"]))
    c.connect(tc, 1, cnt, 1)
    c.connect(tc, 0, c.obj(x + 200, y + 256, "s sh_bb"), 0)

    # shift (Hz) per side: Pitch -> signed, deadband at the click; Record flips; Size scales the right side
    P, REC, SZ = V("sh_P_v"), V("sh_rec_v"), V("sh_sz_v")
    xx = P - 0.6
    up = gt(xx, 0)
    d = mx(0, fabs(xx) - DEAD)
    m = d / (up * UP_SPAN + (1 - up) * DN_SPAN)
    mag = gt(d, 0) * mn(SHIFT_CAP, SHIFT_MIN * exp(m * math.log(SHIFT_MAX / SHIFT_MIN)))
    S = (2 * up - 1) * mag * (1 - 2 * REC)
    watched(c, 10, 400, ["sh_P", "sh_rec", "sh_sz"], [("v:sh_S s:sh_fl", S), ("s:sh_fr", V("sh_S") * (1 - 2 * SZ))])

    # delay time: free = 2000^speed ms; clocked = beat x division (Speed in 7 zones)
    SPD, PER, CLK = V("sh_spd_v"), V("sh_per_v"), V("sh_clk_v")
    idx = E_int(mn(len(DIVS) - 1, SPD * len(DIVS)))
    T = CLK * mn(T_MAX, PER * E_tab("sh_divs", idx)) + (1 - CLK) * mx(T_MIN, exp(SPD * math.log(FREE_MAX)))
    watched(c, 400, 400, ["sh_spd", "sh_per", "sh_clk"], [("s:sh_T", T)])

    # feedback (Freeze = 1), tone, barber centre, low cut
    FB, FRZ, W, LC = V("sh_fb_v"), V("sh_frz_v"), V("sh_w_v"), V("sh_lc_v")
    watched(c, 700, 400, ["sh_fb", "sh_frz", "sh_w", "sh_lc"], [
        ("s:sh_fbe", FRZ + (1 - FRZ) * FB),
        ("s:sh_lp", mn(20000, 300 * exp(mn(1, W / 0.45) * math.log(20000 / 300)))),
        ("s:sh_hp", mx(LC * (1 - FRZ) + FREEZE_LC * FRZ, 20 * exp(mx(0, (W - 0.55) / 0.45) * math.log(150)))),
        ("s:sh_bc", 200 * exp(W * math.log(20))),
    ])

    # clock: Reset pulses (jack or button). An interval of 30 ms .. 4 s is a beat; changes under 5 ms are ignored.
    x, y = 10, 750
    rp = press(c, x, y, "reset", True, primed="sh_primed")
    tr = op(c, x, y + 88, "t b b b", rp)
    tm = c.obj(x, y + 132, "timer")
    c.connect(tr, 2, tm, 1)                                   # elapsed since the last pulse
    c.connect(tr, 1, tm, 0)                                   # then restart
    arm = op(c, x, y + 154, "spigot", tm)                     # only between two pulses in a row
    c.connect(c.obj(x + 60, y + 132, "r sh_arm"), 0, arm, 1)
    lo = op(c, x, y + 176, f"moses {CLK_MIN}", arm)
    hi = op(c, x, y + 198, f"moses {CLK_MAX}", (lo, 1))
    c.connect(hi, 0, c.obj(x, y + 220, "v sh_iv"), 0)
    tiv = op(c, x + 100, y + 220, "t b", hi)
    # the beat: a running average of the intervals (a jump of more than JUMP ms = a new tempo, taken at once);
    # the time follows it only when it drifts more than HYST_FINE ms, so clock jitter never bends the echoes
    IV, AVG, PERV = V("sh_iv"), V("sh_avg"), V("sh_per_v")
    big = mx(1 - V("sh_clk_v"), gt(fabs(IV - AVG), JUMP))
    program(c, x + 100, y + 250, tiv, [
        ("v:sh_avg", big * IV + (1 - big) * (AVG + AVG_K * (IV - AVG))),
        ("v:sh_np", PERV + mx(big, gt(fabs(V("sh_avg") - PERV), HYST_FINE)) * (V("sh_avg") - PERV)),
        ("s:sh_per", V("sh_np")), ("s:sh_tmo", mx(CLK_TIMEOUT, 2.5 * V("sh_np"))), ("s:sh_clk", lift(1))])
    # every pulse: arm the next interval and restart the timeout (which disarms and frees the time)
    tpl = op(c, x + 400, y + 110, "t b b", (tr, 0))
    c.connect(tpl, 1, c.msg(x + 480, y + 132, "\\; sh_arm 1"), 0)
    dl = c.obj(x + 400, y + 154, f"delay {CLK_TIMEOUT}")
    c.connect(tpl, 0, dl, 0)
    c.connect(c.obj(x + 480, y + 154, "r sh_tmo"), 0, dl, 1)
    c.connect(dl, 0, c.msg(x + 400, y + 176, "\\; sh_clk 0 \\; sh_arm 0"), 0)

    # alt layer (pickup by movement); Source + Record = defaults
    rb = "sh_altrb"
    tar = op(c, 1100, 600, "t b b", press(c, 1100, 530, "record_alt", primed="sh_primed"))
    c.connect(tar, 1, c.msg(1200, 622, "\\; sh_altrb bang"), 0)
    c.connect(tar, 0, c.msg(1100, 644, ALT_RESET), 0)
    x, y = 600, 700
    pickup(c, x, y, "start_alt", "sh_wd", ["clip 0 1", "* 4"], rebase=rb)
    pickup(c, x + 250, y, "size_alt", "sh_dr", ["clip 0 1", "* 5", "+ 1"], rebase=rb)
    tdr = op(c, x + 250, y + 252, "t f f", c.obj(x + 250, y + 230, "r sh_dr"))
    c.connect(tdr, 1, c.obj(x + 330, y + 276, "s sh_g"), 0)
    sw = op(c, x + 250, y + 276, "swap 1", tdr)                # -> 1 / drive
    dv = op(c, x + 250, y + 298, "/", sw, (sw, 1))
    c.connect(dv, 0, c.obj(x + 250, y + 320, "s sh_gi"), 0)
    pickup(c, x + 500, y, "density_alt", "sh_lc", ["clip 0 1", f"* {math.log(25):.6f}", "exp", "* 20"], rebase=rb)
    pickup(c, x + 750, y, "overlap_alt", "sh_wr", ["clip 0 1", f"* {math.log(50):.6f}", "exp", "* 0.1"],
           rebase=rb)
    if test:
        for i, n in enumerate(["sh_fl", "sh_fr", "sh_T", "sh_clk", "sh_per", "sh_bb"]):
            c.connect(c.obj(10 + i * 120, 1050, f"r {n}"), 0, c.obj(10 + i * 120, 1072, f"print {n[3:]}"), 0)
    return c


def hilbert(c, x, y, src):
    """src -> (real, imaginary) biquad~ pairs."""
    outs = []
    for k, (b1, b2) in enumerate(HILBERT):
        outs.append(op(c, x + k * 250, y + 22, f"biquad~ {b2}", op(c, x + k * 250, y, f"biquad~ {b1}", src)))
    return outs


def side(Canvas, s):
    """One side's loop. inlet~ = input; outlet~ = wet (loop + direct)."""
    o = "r" if s == "l" else "l"
    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, f"side {s}: delwrite~ sh_buf{s}; vd~ -> hilbert -> shift / ring -> tone / barber -> low cut -> "
                  "drive softclip = wet; direct = the input shifted (no delay)")
    inp = c.obj(10, 30, "inlet~")
    # oscillator (shared by the loop and the direct path)
    ph = op(c, 700, 74, "phasor~", sig(c, 700, 30, f"sh_f{s}", 20))
    cs = op(c, 700, 96, "cos~", ph)
    sn = op(c, 800, 118, "cos~", op(c, 800, 96, "+~ -0.25", ph))
    ring = sig(c, 900, 30, "sh_ring", 20)
    nring = op(c, 900, 90, "-~", c.obj(900, 70, "sig~ 1"), ring)

    def shifter(x, y, src):
        re, im = hilbert(c, x, y, src)
        a = op(c, x, y + 66, "*~", re, cs)
        ssb = op(c, x, y + 110, "-~", a, op(c, x + 250, y + 66, "*~", im, sn))
        rg = op(c, x + 100, y + 110, "*~ 1.41421", a)
        return op(c, x, y + 154, "+~", op(c, x, y + 132, "*~", ssb, nring), op(c, x + 100, y + 132, "*~", rg, ring))

    # time: glide + wow
    T = sig(c, 10, 300, "sh_T", GLIDE_MS)
    osc = op(c, 150, 344, "osc~", c.obj(150, 322, "r sh_wr"))
    if s == "r":                                              # the right side's wow runs 90 degrees on
        c.connect(chain(c, 250, 300, c.obj(250, 300, "loadbang"), ["delay 400"]), 0, c.msg(250, 344, "0.25"), 0)
        c.connect(c.n - 1, 0, osc, 1)
    wow = op(c, 150, 366, "*~", osc, sig(c, 350, 300, "sh_wd", 50))
    tt = op(c, 10, 410, f"clip~ {T_MIN:g} {T_MAX:g}", op(c, 10, 388, "+~", T, wow))
    rd = op(c, 10, 432, f"vd~ sh_buf{s}", tt)
    sh = shifter(10, 460, rd)
    # tone (lop~ + hip~) or barber (band-pass bell), then the low cut
    tone = chain(c, 10, 620, sh, ["lop~ 20000", "hip~ 20"])
    c.connect(c.obj(120, 600, "r sh_lp"), 0, tone - 1, 1)
    c.connect(c.obj(200, 620, "r sh_hp"), 0, tone, 1)
    bp = op(c, 300, 642, f"bp~ 1000 {BARBER_Q:g}", sh)
    c.connect(c.obj(400, 620, "r sh_bc"), 0, bp, 1)
    bp = op(c, 300, 664, f"*~ {BARBER_GAIN:g}", bp)
    bb = sig(c, 500, 600, "sh_bb", 30)
    nbb = op(c, 500, 660, "-~", c.obj(500, 640, "sig~ 1"), bb)
    filt = op(c, 10, 710, "+~", op(c, 10, 688, "*~", tone, nbb), op(c, 300, 688, "*~", bp, bb))
    lcut = op(c, 10, 732, "hip~ 27", filt)
    c.connect(c.obj(120, 712, "r sh_lc"), 0, lcut, 1)
    g = op(c, 10, 754, "*~ 2", lcut)
    c.connect(c.obj(120, 734, "r sh_g"), 0, g, 1)
    wet = op(c, 10, 890, "*~ 0.5", softclip(c, 10, 776, g))
    c.connect(c.obj(120, 870, "r sh_gi"), 0, wet, 1)
    c.connect(wet, 0, c.obj(400, 900, f"send~ sh_w{s}"), 0)
    # write: input x (1 - freeze) + feedback x mix of own / other wet
    frz = sig(c, 600, 200, "sh_frz", 30)
    nin = op(c, 10, 90, "*~", inp, op(c, 600, 260, "-~", c.obj(600, 240, "sig~ 1"), frz))
    pp = sig(c, 1000, 200, "sh_pp", 30)
    npp = op(c, 1000, 260, "-~", c.obj(1000, 240, "sig~ 1"), pp)
    oth = c.obj(1100, 280, f"receive~ sh_w{o}")
    fbm = op(c, 1000, 330, "+~", op(c, 1000, 300, "*~", wet, npp), op(c, 1100, 300, "*~", oth, pp))
    fbx = op(c, 1000, 380, "*~", fbm, sig(c, 1150, 330, "sh_fbe", 50))
    wr = op(c, 10, 140, "+~", nin, fbx)
    c.connect(wr, 0, c.obj(10, 162, f"delwrite~ sh_buf{s} {BUF_MS}"), 0)
    # direct: the input through its own Hilbert pair, same oscillator
    dr = op(c, 1000, 760, "*~", shifter(1000, 560, inp), sig(c, 1200, 700, "sh_dl", 30))
    out = op(c, 10, 920, "+~", wet, dr)
    c.connect(out, 0, c.obj(10, 942, "outlet~"), 0)
    return c


def test_source(Canvas):
    """Left = right = sine sh_tsf at sh_tsa + noise at sh_tna (bursts: send sh_tna, then 0)."""
    c = Canvas("#N canvas 0 50 700 400 %NAME% 0;")
    s = op(c, 10, 40, "*~", op(c, 10, 30, "osc~ 1000", c.obj(10, 8, "r sh_tsf")), sig(c, 100, 8, "sh_tsa", 2))
    n = op(c, 200, 40, "*~", c.obj(200, 20, "noise~"), sig(c, 260, 8, "sh_tna", 1))
    m = op(c, 10, 100, "+~", s, n)
    c.connect(m, 0, c.obj(10, 140, "outlet~"), 0)
    c.connect(m, 0, c.obj(200, 140, "outlet~"), 0)
    return c


def shift_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "12_shift: frequency shifter in a feedback delay. See docs/SHIFT.md and patches/12_shift_README.md.")
    c.text(10, 20, "Pitch = shift (click = none). Speed = time (Reset clock = division). Density = feedback. "
                   "Source = Ring. File = Barber. Record = flip. Freeze = hold.")
    c.sub(10, 50, "nebulae_controls", controls_canvas())
    c.sub(10, 80, "ui", ui(Canvas, bool(test)))
    src = c.sub(10, 120, "testsrc", test_source(Canvas)) if test else c.obj(10, 120, "adc~ 1 2")
    sl = c.sub(10, 200, "side_l", side(Canvas, "l"))
    sr_ = c.sub(260, 200, "side_r", side(Canvas, "r"))
    c.connect(src, 0, sl, 0)
    c.connect(src, 1, sr_, 0)
    wet = sig(c, 400, 240, "sh_gw", 20)
    dry = sig(c, 500, 240, "sh_gd", 20)
    outs = []
    for ch, s_, x in ((0, sl, 10), (1, sr_, 260)):
        mix = op(c, x, 380, "+~", op(c, x, 356, "*~", s_, wet), op(c, x + 80, 356, "*~", (src, ch), dry))
        outs.append(softclip(c, x, 410, mix))
    dac = c.obj(10, 560, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        lb = c.obj(600, 420, "loadbang")
        steps = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps):
            if wav and "pd quit" in msg:
                msg = "\\; sh_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 445 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 467 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            n = int(max(ms for ms, _ in steps) * SR / 1000)
            for ch, x in [(0, 10), (1, 200)]:
                sd = "lr"[ch]
                c.obj(x, 650, f"table sh_rec{sd} {n}")
                tw = c.obj(x, 620, f"tabwrite~ sh_rec{sd}")
                c.connect(outs[ch], 0, tw, 0)
                c.connect(lb, 0, tw, 0)
            rs = c.obj(600, 620, "r sh_save")
            wm = c.msg(600, 642, f"write -bytes 4 {wav} sh_recl sh_recr")
            c.connect(rs, 0, wm, 0)
            c.connect(wm, 0, c.obj(600, 664, "soundfiler"), 0)
    return c
