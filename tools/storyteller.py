#!/usr/bin/env python3
"""Build instr/bt_storyteller.instr: the factory granular looper + the storyteller's ears (docs/BLUETOOTH.md).

  python tools/storyteller.py            -> instr/bt_storyteller.instr

The looper (firmware/src/.../instr/a_granularlooper.instr) is copied verbatim, nebconfig included, so it sounds
and plays exactly as the factory one. Appended after it, started from the orchestra's global code:
  instr 97  (once)   the launcher: starts bt/run.sh story through systemd-run (the bt_test pattern)
  instr 98  (always) the ears: every control change, onset and a 4 Hz analysis frame -> /dev/shm/neb_bt/events
  instr 99  (always) reads the Bluetooth state once a second (GEN23 table: no process is started) -> quiet cues
CPU: three rms followers, one butlp, a 1024-point centroid FFT 4 times a second, and change detection on 22
controls. The narration runs outside Csound (bt/narrator.py).
Csound 6.11 notes: fprintks's format has no %s for strings, so each control's name is written into its own
format string (hence this generator); fprintks files are line-buffered (each line reaches the narrator at once).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOOPER = os.path.join(ROOT, "firmware", "src", "QB_Nebulae_V2", "Code", "instr", "a_granularlooper.instr")
OUT = os.path.join(ROOT, "instr", "bt_storyteller.instr")
EVENTS = "/dev/shm/neb_bt/events"
STATE = "/dev/shm/neb_bt/state"

# (name in the events, Csound global, threshold, minimum seconds between reports)
KNOBS = [("pitch", "gkpitch", 0.003), ("speed", "gkspeed", 0.003), ("start", "gkloopstart", 0.004),
         ("size", "gkloopsize", 0.004), ("density", "gkdensity", 0.004), ("overlap", "gkoverlap", 0.004),
         ("window", "gkwindow", 0.004), ("blend", "gkblend", 0.004)]
DIGITAL = [("freeze", "gkfreeze"), ("record", "gkrecord"), ("source", "gksource"), ("reset", "gkreset"),
           ("file", "gkfilesel")]
ALTS = [("start_alt", "gkloopstart_alt"), ("size_alt", "gkloopsize_alt"), ("density_alt", "gkdensity_alt"),
        ("overlap_alt", "gkoverlap_alt"), ("window_alt", "gkwindow_alt"), ("pitch_alt", "gkpitch_alt"),
        ("blend_alt", "gkblend_alt"), ("freeze_alt", "gkfreeze_alt"), ("record_alt", "gkrecord_alt"),
        ("source_alt", "gksource_alt")]

HEADER = """; bt_storyteller.instr - the Nebulae tells a Windows PC, as a Bluetooth keyboard, what is happening to it.
; GENERATED by tools/storyteller.py from the factory a_granularlooper.instr (verbatim) + the storyteller's ears.
; Needs on the stick: the bt_keyboard/ folder (btkbd, run.sh, narrator.py, phrases.py). Nothing on the SD card
; changes. Pair once with bt_test or this instrument (Settings, Bluetooth, Add device, Nebulae), open Notepad.
; Plays exactly like the factory granular looper. Quiet cues: a soft double blip every 8 s = waiting to pair,
; one blip = reconnecting, a rising chime = connected, one low tone = Bluetooth failed (the looper plays on).
"""

EARS = r"""
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;;;; the storyteller (tools/storyteller.py) ;;;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
gSnebev = "%(events)s"
gknebst init 0
ganebcue init 0

; the launcher: once, when the instrument loads (no dollar signs or semicolons in the shell text)
instr 97
ires system_i 1, {{mkdir -p /mnt/memory
grep -q " /mnt/memory " /proc/mounts || mount /dev/sda1 /mnt/memory
systemctl stop neb-bt
rm -rf /dev/shm/neb_bt
mkdir -p /dev/shm/neb_bt
echo starting > %(state)s
echo 0 > %(state)s.code
if [ -f /mnt/memory/bt_keyboard/run.sh ]
then
cp /mnt/memory/bt_keyboard/run.sh /dev/shm/neb_bt/run.sh
systemd-run --unit=neb-bt --collect sh /dev/shm/neb_bt/run.sh story
else
echo "failed: no bt_keyboard folder on the stick" > %(state)s
echo 4 > %(state)s.code
fi}}
endin

; the ears
instr 98
ktime times
%(watch)s
; what comes in, and what the looper sends out (monitor: this cycle's output so far)
ainl, ainr inch 1, 2
ain = (ainl + ainr) * 0.5
aol, aor monitor
aout = (aol + aor) * 0.5
krin rms ain, 4
krout rms aout, 4
alow butlp ain, 160
krlow rms alow, 4
kfast rms ain, 40
kslow rms ain, 1.5
ktick metro 4
kcent centroid ain, ktick, 1024
if ktick == 1 then
    kin = 20 * log10(krin + 0.00001)
    kout = 20 * log10(krout + 0.00001)
    klow = krlow / (krin + 0.00001)
    fprintks gSnebev, "a %%.3f %%.1f %%.1f %%.0f %%.3f\n", ktime, kin, kout, kcent, (klow > 1 ? 1 : klow)
endif
; onsets: the fast level jumps 9 dB above the slow one (60 ms apart at least)
kfdb = 20 * log10(kfast + 0.00001)
ksdb = 20 * log10(kslow + 0.00001)
klastonset init -1
if kfdb - ksdb > 9 && kfdb > -45 && ktime - klastonset > 0.06 then
    klastonset = ktime
    fprintks gSnebev, "o %%.3f %%.1f\n", ktime, kfdb - ksdb
endif
endin

; the Bluetooth state, once a second, without starting a process
instr 99
kpoll metro 1
schedkwhen kpoll, 0, 1, 96, 0, 0.01
kph phasor 0.125
kt = kph * 8
kwait = (gknebst == 1 && (kt < 0.06 || (kt > 0.2 && kt < 0.26)) ? 0.05 : 0)
krec = (gknebst == 2 && kt < 0.06 ? 0.05 : 0)
kwait portk kwait + krec, 0.004
ablip oscili kwait, 880
kprev init 0
if gknebst != kprev then
    if gknebst == 3 then
        event "i", 95, 0, 0.9, 1
    elseif gknebst == 4 then
        event "i", 95, 0, 1.5, 0
    endif
endif
kprev = gknebst
outs ablip + ganebcue, ablip + ganebcue
ganebcue = 0
endin

; btkbd keeps the state as a number in state.code (1 waiting, 2 reconnecting, 3 connected, 4 failed, 0 other).
; GEN23 reads it into a temporary table: no process is started, and the file is opened afresh each time
; (readfi keeps its file open in a reused instance, so it can't re-read).
instr 96
ift ftgentmp 0, 0, 4, -23, "%(state)s.code"
gknebst init tab_i(0, ift)
endin

; a cue: p4 1 = connected (three rising notes), 0 = failed (one low tone)
instr 95
if p4 == 1 then
    kf = (timeinsts() < 0.3 ? 880 : (timeinsts() < 0.6 ? 1109 : 1320))
    kenv linseg 0, 0.01, 0.08, 0.85, 0
else
    kf = 220
    kenv linseg 0, 0.05, 0.08, 1.4, 0
endif
ganebcue = ganebcue + oscili(kenv, kf)
endin

; start the storyteller with the orchestra (the firmware starts instr 1 at 1 s)
event_i "i", 97, 0, 0.01
event_i "i", 98, 0.5, -1
event_i "i", 99, 1, -1
"""


def watch_code():
    lines = []
    rows = [(name, var, th, 0.03) for name, var, th in KNOBS]
    for name, var in DIGITAL + ALTS:
        continuous = name.endswith("_alt") and name.split("_")[0] not in ("freeze", "record", "source")
        rows.append((name, var, 0.004 if continuous else 0.5, 0.03 if continuous else 0))
    # inline (a UDO call per control per k-cycle cost ~20% CPU in the PC render)
    for name, var, th, gap in rows:
        lines.append("kl_%s init -1000" % name)
        lines.append("kt_%s init -1000" % name)
        cond = "abs(%s - kl_%s) > %g" % (var, name, th)
        if gap:
            cond += " && ktime - kt_%s >= %g" % (name, gap)
        lines.append("if %s then" % cond)
        lines.append("    kl_%s = %s" % (name, var))
        lines.append("    kt_%s = ktime" % name)
        lines.append('    fprintks gSnebev, "k %%.3f %s %%.4f\\n", ktime, %s' % (name, var))
        lines.append("endif")
    return "\n".join(lines)


def build():
    with open(LOOPER, encoding="utf-8", newline="") as f:
        looper = f.read().replace("\r\n", "\n")
    assert looper.startswith("nebconfigbegin"), "the looper must start with its nebconfig block"
    end = looper.index("nebconfigend") + len("nebconfigend\n")
    config, body = looper[:end], looper[end:]
    ears = EARS % {"events": EVENTS, "state": STATE, "watch": watch_code()}
    text = config + "\n" + HEADER + body.rstrip("\n") + "\n" + ears
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), text.count("\n")))


if __name__ == "__main__":
    build()
