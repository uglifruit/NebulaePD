def clock(Canvas):
    """Beats (Reset pulses, or internal at the last tempo) -> 16th steps [s ch_step] 0..3."""
    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, "pulse: restart (first / after a gap) | absorb (just after an internal beat: re-anchor) | beat. "
                  "Internal beat after L ms without a pulse. Sub-steps at L/4 (odd ones swung).")
    lb = c.obj(600, 30, "loadbang")
    tmr = c.obj(10, 120, "timer")
    c.connect(lb, 0, tmr, 0)
    rp = c.obj(10, 30, "r ch_pulse")
    t3 = op(c, 10, 52, "t b b b", rp)
    c.connect(t3, 2, tmr, 1)
    c.connect(tmr, 0, c.obj(10, 142, "v ch_gap"), 0)
    c.connect(t3, 1, tmr, 0)
    G, L, HV, PV = V("ch_gap"), V("ch_L"), V("ch_have"), V("ch_prov")
    rs = gt((1 - HV) + gt(G, mx(2000, 1.5 * L)), 0)
    mode = op(c, 10, 300, "sel 0 1 2", val(c, 200, 30, (t3, 0), iff(rs, 0, iff(PV, 1, 2))))
    newL = [("v:ch_dl", mn(0.25 * L, fabs(G - L))),
            ("v:ch_L", iff(lt(fabs(G - L), SMOOTH * L), L + 0.5 * (G - L), mn(LMAX, mx(LMIN, G))))]
    d = {n: c.obj(400 + i * 110, 700, "delay 1000") for i, n in enumerate(["d1", "d2", "d3", "dint", "dprov"])}

    def arm(x, y, src, emit0, internal=False):
        """stop everything; sub-steps 1..3 and the internal beat from now (after a pulse: L + grace, so a jittered
        pulse always comes first; internal: L); then step 0 (emit0)."""
        tb = op(c, x, y, "t b b b b", src)
        stp = c.msg(x + 200, y + 22, "stop")
        c.connect(tb, 3, stp, 0)
        for n in d:
            c.connect(stp, 0, d[n], 0)
        SW = V("ch_sw")
        prog(c, x + 300, y, (tb, 2), [("v:ch_o1", L * 0.25 * (1 + SW)), ("v:ch_o2", L * 0.5),
                                      ("v:ch_o3", L * 0.75 + L * 0.25 * SW), ("v:ch_oi", L + GRACE_INT + V("ch_dl"))])
