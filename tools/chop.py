"""09_chop: a slice sequencer for the Nebulae (designed with the owner, 2026-11-14).

Generated by tools/gen.py. Design notes: docs/CHOP.md. User guide: patches/09_chop_README.md.

What it does
- Source: Record grabs the next 1/2/4 bars of the input (from a bar line, so the loop is in time); File loads the
  next .wav/.aif from the stick (FLAC can't be read by Pd 0.52). File held = back to the last grab.
- Slicing: an onset detector (fast/slow energy ratio, our own: bonk~ can't analyse a stored file faster than real
  time, because its outputs are clock-driven) runs over the stored audio in small chunks ([switch~] bang = one
  block, synchronously). The strongest onset near each 16th step makes that step a slice start; too few onsets
  (pads) or alt Size fully CCW = equal 16ths.
- Clock: Reset = a beat (tap tempo works). 16th steps run inside it, swung by alt Density. With no clock it
  free-runs at the last tempo (120 BPM from load); pulses phase-lock it (a pulse up to a fifth of a beat after
  an internal beat is absorbed, not counted twice). A gap > 2 s (or 1.5 beats) = the next pulse is step 1.
- Pattern: as long as the loop (16 steps a bar). The hits stay where the loop has its slice starts; per hit, dice
  decide: play at all (Density), another slice (Start = Shuffle), repeat the previous hit's slice (alt Blend =
  stutter), reverse (Window), ratchet 2..6x (Overlap; range on alt Overlap), pitch jump (Speed). Freeze keeps the
  dice (knobs still morph); otherwise they are re-rolled at every cycle start.
- Playback: two voices taken in turn; each hit is a vline~ index ramp (sample-accurate start) over the slice at
  2^(semitones/12) x file sr / 48k, with a vline~ envelope (alt Window edges); the next hit fades the other voice
  out over the same edge (choke). Gate (Size) shortens hits.
- Buffers: 4 stereo slots of 2^21 samples (43.7 s): 0/1 = grabs, 2/3 = files. A grab or a load always goes into a
  slot that isn't playing; it takes over at a bar line (a grab at the bar line where it ends).
"""

