# --- control-rate expressions (resonator's E compiler + tables, random, loops) ------------------------------------
_seed = itertools.count(1)


def tab(name, i):
    return E(f"tabread {name}", lift(i))


def lt(a, b):
    return E("<", lift(a), lift(b))


def ge(a, b):
    return E(">=", lift(a), lift(b))


def fint(a):
    """Truncation ([int]); use on non-negative values only."""
    return E("int", lift(a))


def mod(a, b):
    return E("mod", lift(a), lift(b))


def iff(c, a, b):
    """c is 0/1."""
    return c * a + (1 - c) * b


def tabd(name, recv, i):
    return E("tabd", name, recv, lift(i))


def rand():
    return E("rand", next(_seed))


class CP(Prog):
    def emit(self, e, src):
        if e.o == "rand":
            c = self.c
            t = self.obj("t b")
            c.connect(src[0], src[1], t, 0)
            r = self.obj("random 65536")
            c.connect(t, 0, r, 0)
            rs, a, m = self.obj("r ch_seed"), self.obj(f"+ {e.a[0]}"), self.msg("seed \\$1")
            c.connect(rs, 0, a, 0)
            c.connect(a, 0, m, 0)
            c.connect(m, 0, r, 0)
            d = self.obj("/ 65536")
            c.connect(r, 0, d, 0)
            return d
        if e.o == "tabd":                       # [tabread name] whose table is switched by [r recv] (set ...)
            name, recv, idx = e.a
            io = self.emit(idx, src)
            n = self.obj(f"tabread {name}")
            self.c.connect(io, 0, n, 0)
            self.c.connect(self.obj(f"r {recv}"), 0, n, 0)
            return n
        return super().emit(e, src)


def _src(src):
    return src if isinstance(src, tuple) else (src, 0)


def prog(c, x, y, src, assigns):
    """On each bang from src run assigns [(targets, E)] in order. targets (space separated): 's:name' send,
    'v:name' set [v name], 'w:table:ivar' write [tabwrite table] at index [v ivar]."""
    p = CP(c, x, y)
    n = len(assigns)
    t = p.obj("t" + " b" * n)
    s, o = _src(src)
    c.connect(s, o, t, 0)
    for i, (targets, e) in enumerate(assigns):
        out = p.emit(lift(e), (t, n - 1 - i))
        for tg in targets.split():
            kind, _, rest = tg.partition(":")
            if kind in ("s", "v"):
                c.connect(out, 0, p.obj(f"{kind} {rest}"), 0)
            elif kind == "w":
                tname, iv = rest.split(":")
                tf = p.obj("t f b")
                c.connect(out, 0, tf, 0)
                vi = p.obj(f"v {iv}")
                c.connect(tf, 1, vi, 0)
                tw = p.obj(f"tabwrite {tname}")
                c.connect(vi, 0, tw, 1)
                c.connect(tf, 0, tw, 0)
            else:
                raise ValueError(tg)
    return t


def val(c, x, y, src, e):
    """src (anything: it is turned into a bang first, a float must not set a [v]) -> the returned object's outlet 0
    sends the value of e."""
    p = CP(c, x, y)
    t = p.obj("t b")
    s, o = _src(src)
    c.connect(s, o, t, 0)
    return p.emit(lift(e), (t, 0))


def when(c, x, y, src, e, both=False):
    """[sel 1] (or [sel 1 0]) on the value of e."""
    return op(c, x, y, "sel 1 0" if both else "sel 1", val(c, x, y + 30, src, e))


def loop(c, x, y, count_src, ivar, assigns):
    """count_src outlet 0 sends N -> assigns run N times with [v ivar] = 0..N-1. Returns the [t f b]."""
    t = op(c, x, y, "t f b", count_src)
    z = c.msg(x + 80, y + 22, "0")
    c.connect(t, 1, z, 0)
    c.connect(z, 0, c.obj(x + 80, y + 44, f"v {ivar}"), 0)
    u = op(c, x, y + 66, "until", op(c, x, y + 44, "max 0", (t, 0)))
    prog(c, x, y + 100, u, assigns + [(f"v:{ivar}", V(ivar) + 1)])
    return t


def vrecv(c, x, y, name):
    """[r name] -> [v name]: a '; name value' message sets the variable."""
    c.connect(c.obj(x, y, f"r {name}"), 0, c.obj(x, y + 22, f"v {name}"), 0)


def tprint(c, x, y, src, label):
    """Test print: [label] <ms since load> <message>."""
    lb = c.obj(x + 160, y, "loadbang")
    t = op(c, x, y + 22, "t a b", src)
    tm = c.obj(x + 160, y + 44, "timer")
    c.connect(lb, 0, tm, 0)
    c.connect(t, 1, tm, 1)
    lp = c.obj(x, y + 88, "list prepend 0")
    c.connect(tm, 0, lp, 1)                                         # logical ms (WAV time + 300)
    c.connect(t, 0, lp, 0)
    c.connect(lp, 0, c.obj(x, y + 110, f"print {label}"), 0)


def to_voice(c, x, y, src, name, invert=False):
    """src's message -> [s name0] when voice 0 is the event's voice, else [s name1] (invert: the other voice)."""
    for v in (0, 1):
        sp = op(c, x + v * 130, y, "spigot", src)
        ctrl = f"ch_vs{(1 - v) if invert else v}"
        c.connect(c.obj(x + v * 130 + 60, y - 22, f"r {ctrl}"), 0, sp, 1)
        c.connect(sp, 0, c.obj(x + v * 130, y + 22, f"s {name}{v}"), 0)


def packmsg(c, x, y, src, names, template):
    """src bangs -> [pack] of [v names...] (right to left) -> [msg template]."""
    n = len(names)
    t = op(c, x, y, "t" + " b" * n, src)
    pk = c.obj(x, y + 66, "pack" + " f" * n)
    for i, nm in enumerate(names):
        c.connect(op(c, x + i * 90, y + 33, f"v {nm}", (t, i)), 0, pk, i)
    m = c.msg(x, y + 99, template)
    c.connect(pk, 0, m, 0)
    return m


