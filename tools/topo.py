# --- the map --------------------------------------------------------------------------------------------------------
# 32 steps (two bars of 16ths). Digits 0-9 = importance (x28 -> 0..252), '.' = never, '|' is only for reading.
# At Fill f a step plays when 28*d > 255*(1 - f): 9s play from f ~ 0.02, 5s from 0.45, 1s from 0.89.
# S-lane 9s add the clap, H-lane 9s are open hats.
# X: four-on-the-floor -> electro/funk -> hip-hop -> breakbeat/jungle -> broken/polyrhythmic.
# Y: sparse -> busy.

def every(n, d, off=0):
    return "".join(str(d) if i % n == off % n else "." for i in range(STEPS))


def merge(*ps):
    ps = [p.replace("|", "") for p in ps]
    return "".join(max(chs) for chs in zip(*ps))


