def mutate(Canvas):
    """Re-draws (auto per beat, Record burst), X/Y drift, home store/recall, vanilla."""
    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, "One mutation: random lane + step < length. 50% move (swap with a neighbour; a flip if that wouldn't "
                  "be heard), 30% flip, 20% heal (offset 0). Lock stops auto re-draws and drift (Record still mutates).")
    lock = c.obj(10, 30, "r tp_lock")
    nl = op(c, 10, 52, "== 0", lock)
    auto = c.obj(100, 96, "spigot 1")
    c.connect(c.obj(100, 30, "r tp_beat"), 0, auto, 0)
    c.connect(nl, 0, auto, 1)
    un = c.obj(100, 330, "until")
    # per beat: int(amt) mutations, plus one more with probability frac(amt)
    ta = op(c, 100, 140, "t f f", fl(c, 100, 118, "f 0", auto, "tp_namt"))
    tb = op(c, 160, 184, "t f f", op(c, 160, 162, "int", (ta, 1)))
    fr = c.obj(100, 206, "-")
    add = c.obj(100, 306, "+")
    c.connect(tb, 1, fr, 1)
    c.connect(tb, 0, add, 1)
    c.connect(ta, 0, fr, 0)
    tf = op(c, 100, 250, "t b f", op(c, 100, 228, "* 1000", fr))
    lt = c.obj(100, 284, "<")
    c.connect(tf, 1, lt, 1)
    rp = rnd(c, 30, 284, 25, rng=1000, seed="tp_seed")
    c.connect(tf, 0, rp, 0)
    c.connect(rp, 0, lt, 0)
    c.connect(lt, 0, add, 0)
    c.connect(add, 0, un, 0)
    c.connect(fl(c, 250, 118, "f 4", c.obj(250, 96, "r tp_mutnow"), "tp_nburst"), 0, un, 0)
    c.connect(c.obj(400, 30, "r tp_len"), 0, c.obj(400, 52, "v tp_vlen"), 0)

    def pick(rng, k, name, mult=None, rng_recv=None):
        def fn(c, x, y, src):
            r = rnd(c, x, y + 66, k, rng=rng, seed="tp_seed")
            c.connect(src[0], src[1], r, 0)
            if rng_recv:
                c.connect(c.obj(x + 60, y + 44, f"r {rng_recv}"), 0, r, 1)
            o = op(c, x, y + 88, f"* {mult}", r) if mult else r
            setv(c, x, y + 110, name, o)
        return fn

    def dispatch(c, x, y, src):
        m5 = op(c, x, y + 22, "moses 5", op(c, x, y, "v tp_mk", src))
        m8 = op(c, x + 300, y + 44, "moses 8", (m5, 1))
        # swap (0..4)
        sx, sy = x, y + 120
        trig(c, sx, sy, (m5, 0), [
            lambda c, x_, y_, s: setv(c, x_, y_ + 66, "tp_mi1", vadd(c, x_, y_, s, "tp_mL", "tp_ms")),
            neighbour,
            lambda c, x_, y_, s: level(c, x_, y_ + 200, s, "tp_mi1", "tp_ml1", "tp_mc1"),
            lambda c, x_, y_, s: level(c, x_, y_ + 400, s, "tp_mi2", "tp_ml2", "tp_mc2"),
            decide,
        ])
        # flip (5..7): a silent step gets a level in [thr, 255), a playing one a level below 0.9*thr
        nx_ = x + 700
        trig(c, nx_, sy, (m8, 0), [
            lambda c, x_, y_, s: setv(c, x_, y_ + 66, "tp_mi1", vadd(c, x_, y_, s, "tp_mL", "tp_ms")),
            lambda c, x_, y_, s: level(c, x_, y_ + 100, s, "tp_mi1", "tp_ml1", "tp_mc1"),
            flip,
            lambda c, x_, y_, s: write_off(c, x_, y_ + 450, s, "tp_mi1", "tp_mr", "tp_mc1"),
        ])
        # heal (8, 9): off = 0
        hx = x + 1150
        ti = vadd(c, hx, sy, (m8, 1), "tp_mL", "tp_ms")
        tb = op(c, hx, sy + 66, "t b f", ti)
        tw = c.obj(hx, sy + 110, "tabwrite tp_off")
        c.connect(tb, 1, tw, 1)
        z = c.msg(hx, sy + 88, "0")
        c.connect(tb, 0, z, 0)
        c.connect(z, 0, tw, 0)

    def neighbour(c, x, y, src):
        """n = (s + len + d) mod len, d = -2, -1, 1 or 2 -> tp_mi2 = lane*32 + n."""
        t = op(c, x, y, "t b b b", src)
        mdo = c.obj(x, y + 154, "mod 32")
        b = c.obj(x, y + 132, "+")
        a = c.obj(x, y + 110, "+")
        tl = op(c, x + 140, y + 44, "t f f", op(c, x + 140, y + 22, "v tp_vlen", (t, 2)))
        c.connect(tl, 1, mdo, 1)
        c.connect(tl, 0, b, 1)
        c.connect(op(c, x + 70, y + 22, "v tp_ms", (t, 1)), 0, a, 1)
        r = rnd(c, x, y + 66, 23, rng=4, seed="tp_seed")
        c.connect(t, 0, r, 0)
        mz = op(c, x, y + 88, "moses 0", op(c, x, y + 66, "- 2", r))
        c.connect(mz, 0, a, 0)
        c.connect(op(c, x + 50, y + 88, "+ 1", (mz, 1)), 0, a, 0)
        c.connect(a, 0, b, 0)
        c.connect(b, 0, mdo, 0)
        tb = op(c, x, y + 176, "t f b", mdo)
        ad = c.obj(x, y + 220, "+")
        c.connect(op(c, x + 60, y + 198, "v tp_mL", (tb, 1)), 0, ad, 1)
        c.connect(tb, 0, ad, 0)
        setv(c, x, y + 242, "tp_mi2", ad)

    def decide(c, x, y, src):
        """Swap only if exactly one of the two steps plays (an audible move); otherwise flip step 1."""
        t = op(c, x, y, "t b b b", src)
        th = chain(c, x + 160, y, op(c, x + 160, y + 22, "v tp_mL", (t, 2)), ["/ 32", "tabread tp_thrt"])
        ge1 = c.obj(x, y + 110, ">=")
        ge2 = c.obj(x + 80, y + 110, ">=")
        c.connect(th, 0, ge1, 1)
        c.connect(th, 0, ge2, 1)
        c.connect(op(c, x + 80, y + 88, "v tp_ml2", (t, 1)), 0, ge2, 0)
        c.connect(op(c, x, y + 88, "v tp_ml1", (t, 0)), 0, ge1, 0)
        ne = op(c, x, y + 132, "!=", ge1, ge2)
        sl = op(c, x, y + 154, "sel 0", ne)
        trig(c, x, y + 200, (sl, 0), [
            flip,
            lambda c, x_, y_, s: write_off(c, x_, y_ + 700, s, "tp_mi1", "tp_mr", "tp_mc1"),
        ])
        trig(c, x + 300, y + 200, op(c, x + 300, y + 176, "t b", (sl, 1)), [
            lambda c, x_, y_, s: write_off(c, x_, y_, s, "tp_mi1", "tp_ml2", "tp_mc1"),
            lambda c, x_, y_, s: write_off(c, x_, y_ + 100, s, "tp_mi2", "tp_ml1", "tp_mc2"),
        ])

    def flip(c, x, y, src):
        """tp_mr = thr + u*(255 - thr) if the step is silent (level < thr), else u*0.9*thr. u = random 0..1."""
        t = op(c, x, y + 300, "t b b b", src)
        th = chain(c, x + 160, y + 300, op(c, x + 160, y + 322, "v tp_mL", (t, 2)), ["/ 32", "tabread tp_thrt"])
        setv(c, x + 160, y + 388, "tp_mth", th)
        r = rnd(c, x + 80, y + 388, 24, rng=1000, seed="tp_seed")
        c.connect(t, 1, r, 0)
        setv(c, x + 80, y + 432, "tp_mu", op(c, x + 80, y + 410, "* 0.001", r))
        tc = op(c, x, y + 454, "t b b", (t, 0))
        mo = c.obj(x, y + 498, "moses")
        c.connect(op(c, x + 50, y + 476, "v tp_mth", (tc, 1)), 0, mo, 1)
        c.connect(op(c, x, y + 476, "v tp_ml1", (tc, 0)), 0, mo, 0)
        # silent -> play: thr + u*(255 - thr), but only with probability 0.7*fill (else unchanged). Most steps are
        # silent, so without this heavy mutation just fills the pattern in; this way it settles near the density
        # Fill implies (playing share ~ 0.7f/(1 + 0.7f)).
        on = op(c, x, y + 520, "t b b", (mo, 0))
        lt = c.obj(x - 120, y + 586, "<")
        c.connect(chain(c, x - 60, y + 542, op(c, x - 60, y + 542, "v tp_vfill", (on, 1)), ["* 700"]), 0, lt, 1)
        rr = rnd(c, x - 120, y + 564, 26, rng=1000, seed="tp_seed")
        c.connect(on, 0, rr, 0)
        c.connect(rr, 0, lt, 0)
        sel = op(c, x - 120, y + 608, "sel 1 0", lt)
        setv(c, x - 120, y + 652, "tp_mr", op(c, x - 120, y + 630, "v tp_ml1", (sel, 1)))
        sp = chain(c, x, y + 586, vmul(c, x, y + 542, (sel, 0), "tp_mu", "tp_mspan"), ["+ 0"])     # right: thr
        # playing -> silent: u * 0.9 * thr
        off = op(c, x + 150, y + 520, "t b", (mo, 1))
        sl = chain(c, x + 150, y + 520, vmul(c, x + 150, y + 542, off, "tp_mu", "tp_mth"), ["* 0.9"])
        setv(c, x + 150, y + 650, "tp_mr", sl)
        # tp_mspan = 255 - thr, and the + thr
        c.connect(chain(c, x + 250, y + 388, th, ["* -1", "+ 255"]), 0, c.obj(x + 250, y + 454, "v tp_mspan"), 0)
        c.connect(th, 0, sp, 1)
        setv(c, x, y + 650, "tp_mr", sp)

    trig(c, 100, 200, un, [
        pick(4, 20, "tp_mL", mult=STEPS),
        pick(32, 21, "tp_ms", rng_recv="tp_len"),
        pick(10, 22, "tp_mk"),
        dispatch,
    ])

    # --- drift: per step, unless locked, dx/dy random-walk by tp_drate (|d| <= 0.5) ---
    x, y = 10, 1100
    dg = c.obj(x, y + 22, "spigot 1")
    c.connect(c.obj(x, y, "r tp_drift"), 0, dg, 0)
    c.connect(nl, 0, dg, 1)
    tdr = op(c, x, y + 44, "t b b", dg)
    for k, A in enumerate("xy"):
        xx = x + k * 200
        r = rnd(c, xx, y + 132, 30 + k, rng=2001, seed="tp_seed")
        c.connect(tdr, k, r, 0)
        dlt = fl(c, xx, y + 176, "* 0", op(c, xx, y + 154, "- 1000", r), "tp_drate")
        acc = op(c, xx, y + 198, "+", dlt)
        c.connect(c.obj(xx + 60, y + 176, f"r tp_d{A}"), 0, acc, 1)
        chain(c, xx, y + 198, acc, ["clip -0.5 0.5", "change", f"s tp_d{A}"])
        c.connect(c.obj(xx + 100, y + 280, f"r tp_d{A}"), 0, c.obj(xx + 100, y + 302, f"v tp_vd{A}"), 0)

    # --- home: store / recall the offsets and the drift position ---
    x, y = 500, 1100
    ts = op(c, x, y + 22, "t b b b", c.obj(x, y, "r tp_store"))
    copy(c, x, y + 60, (ts, 2), "tp_off", "tp_home")
    for k, A in enumerate("xy"):
        setv(c, x + 200 + k * 100, y + 66, f"tp_hd{A}", op(c, x + 200 + k * 100, y + 44, f"v tp_vd{A}", (ts, k)))
    x = 900
    tr = op(c, x, y + 22, "t b b b", c.obj(x, y, "r tp_recall"))
    copy(c, x, y + 60, (tr, 2), "tp_home", "tp_off")
    for k, A in enumerate("xy"):
        c.connect(op(c, x + 200 + k * 100, y + 44, f"v tp_hd{A}", (tr, k)), 0,
                  c.obj(x + 200 + k * 100, y + 66, f"s tp_d{A}"), 0)
    # --- vanilla (File double-tap): no mutations, no drift offset; home is kept ---
    x = 1300
    tv = op(c, x, y + 22, "t b b b", c.obj(x, y, "r tp_vanilla"))
    copy(c, x, y + 60, (tv, 2), None, "tp_off")
    for k, A in enumerate("xy"):
        z = c.msg(x + 200 + k * 100, y + 44, "0")
        c.connect(tv, k, z, 0)
        c.connect(z, 0, c.obj(x + 200 + k * 100, y + 66, f"s tp_d{A}"), 0)
    return c


def voice_ctl(c, x, y, V):
    """tp_trig_V vel -> read V's kit parameters (Sound-interpolated) into [v tp_V_*] -> round-robin go."""
    params = KITS[V]
    t = op(c, x, y + 22, "t f b", c.obj(x, y, f"r tp_trig_{V}"))
    tp = op(c, x, y + 44, "t" + " b" * len(params), (t, 1))
    base = snd_base(V)
    for p, (name, kind, _) in enumerate(params):
        px, py = x + p * 120, y + 80
        idx = op(c, px, py + 22, f"+ {base + p * ANCHORS}", op(c, px, py, "v tp_sa", (tp, p)))
        ti = op(c, px, py + 44, "t f f", idx)
        tv = op(c, px + 60, py + 88, "t f f", op(c, px + 60, py + 66, "tabread tp_snd", (ti, 1)))
        v1 = op(c, px, py + 88, "tabread tp_snd", op(c, px, py + 66, "+ 1", (ti, 0)))
        m = fl(c, px, py + 132, "* 0", op(c, px, py + 110, "-", v1, (tv, 0)), "tp_sfr")
        val = op(c, px, py + 154, "+", m, (tv, 1))
        yy = py + 176
        if kind == "hz":
            val = fl(c, px, yy + 44, "* 1", chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp"]), "tp_tune")
        elif kind == "log":
            val = chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp"])
        elif kind == "oct":
            val = chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp", "- 1"])
        elif kind == "dec":
            val = fl(c, px, yy, "* 1", val, "tp_decay")
        setv(c, px, yy + 88, f"tp_{V}_{name}", val)
    tg = op(c, x, y + 400, "t b f", (t, 0))
    setv(c, x + 60, y + 422, f"tp_{V}_vel", (tg, 1))
    rr = c.obj(x, y + 444, "f")
    c.connect(tg, 0, rr, 0)
    c.connect(chain(c, x + 60, y + 444, rr, ["+ 1", "mod 2"]), 0, rr, 1)
    sl = op(c, x, y + 466, "sel 0 1", rr)
    if V == "CH":
        c.connect(op(c, x + 200, y + 444, "t b", (tg, 0)), 0, c.obj(x + 200, y + 466, "s tp_ckOH"), 0)
    for k in (0, 1):
        c.connect(sl, k, c.obj(x + k * 100, y + 490, f"s tp_go_{V}{k}"), 0)


def xenv(c, x, y, lb):
    """Exponential envelope: [vline~] ramp u (0 -> 1) read through tp_exp. Starts silent (u = 1).
    Returns (vline~, envelope signal)."""
    vl = c.obj(x, y, "vline~")
    one = c.msg(x + 60, y - 22, "1")
    c.connect(lb, 0, one, 0)
    c.connect(one, 0, vl, 0)
    env = op(c, x, y + 66, "tabread4~ tp_exp", op(c, x, y + 44, "+~ 1", op(c, x, y + 22, f"*~ {EXPN}", vl)))
    return vl, env


# go actions (each is called as fn(c, x, y, (trigger, outlet)))
def a_v(name, dst, inlet=1, scale=None):
    """[v name] (optionally * scale) -> dst inlet."""
    def fn(c, x, y, s):
        o = op(c, x, y, f"v {name}", s)
        if scale is not None:
            o = op(c, x, y + 22, f"* {scale:g}", o)
        c.connect(o, 0, dst, inlet)
    return fn


def a_mul(a, b, dst, inlet=1, scale=1.0):
    def fn(c, x, y, s):
        m = vmul(c, x, y, s, a, b)
        if scale != 1.0:
            m = op(c, x, y + 66, f"* {scale:g}", m)
        c.connect(m, 0, dst, inlet)
    return fn


def a_msg(text, *dsts, name=None):
    """A message (with \\$1 = [v name] if given) -> each dst inlet 0."""
    def fn(c, x, y, s):
        m = c.msg(x, y + 22, text)
        c.connect(op(c, x, y, f"v {name}", s) if name else s[0], 0 if name else s[1], m, 0)
        for d in dsts:
            c.connect(m, 0, d, 0)
    return fn


def a_send(name):
    def fn(c, x, y, s):
        c.connect(s[0], s[1], c.obj(x, y, f"s {name}"), 0)
    return fn


def osc_sweep(c, x, y, env):
    """osc~ at f*(1 + k*env): returns (osc~, [*~ 0] for f*k, [+~ 0] for f)."""
    fk = op(c, x, y, "*~ 0", env)
    fs = op(c, x, y + 22, "+~ 0", fk)
    return op(c, x, y + 44, "osc~", fs), fk, fs


def half(c, x, y, V, k, lb, noise):
    """One round-robin half of voice V. Returns its output signal object."""
    pv = f"tp_{V}_"
    other = a_send(f"tp_ck_{V}{1 - k}")
    ck = c.obj(x + 700, y + 22, f"r tp_ck_{V}{k}")
    if V == "K":
        pvl, pe = xenv(c, x, y + 300, lb)
        avl, ae = xenv(c, x + 150, y + 300, lb)
        osc, fk, fs = osc_sweep(c, x, y + 400, pe)
        tone = op(c, x, y + 466, "*~", osc, ae)
        cvl = c.obj(x + 300, y + 300, "vline~")
        cn = op(c, x + 300, y + 344, "*~", op(c, x + 300, y + 322, "hip~ 1500", noise), cvl)
        ca = op(c, x + 300, y + 366, "*~ 0", cn)
        drv = op(c, x, y + 510, "*~ 0", op(c, x, y + 488, "+~", tone, ca))
        out = op(c, x, y + 650, "*~ 0", softclip(c, x, y + 532, drv))
        choke = [avl]
        acts = [other,
                lambda c_, x_, y_, s: phase(c_, x_, y_, s, [osc]),
                a_v(pv + "f", fs), a_mul(pv + "f", pv + "sweep", fk), a_v(pv + "click", ca),
                a_v(pv + "drive", drv), a_v(pv + "vel", out, scale=LEVEL[V]),
                a_msg("0 \\, 1 \\$1", pvl, name=pv + "ptime"), a_msg("0 \\, 1 \\$1", avl, name=pv + "decay"),
                a_msg("1 \\, 0 4", cvl)]
    elif V == "S":
        pvl, pe = xenv(c, x, y + 300, lb)
        tvl, te = xenv(c, x + 150, y + 300, lb)
        nvl, ne = xenv(c, x + 300, y + 300, lb)
        o1, fk1, fs1 = osc_sweep(c, x, y + 400, pe)
        o2, fk2, fs2 = osc_sweep(c, x + 100, y + 400, pe)
        tone = op(c, x, y + 510, "*~", op(c, x, y + 488, "+~", o1, op(c, x + 100, y + 466, "*~ 0.6", o2)), te)
        tg = op(c, x, y + 532, "*~ 0", tone)
        h1 = op(c, x + 300, y + 400, "hip~ 1500", noise)
        h2 = op(c, x + 300, y + 422, "hip~ 1500", h1)
        nz = op(c, x + 300, y + 466, "*~", op(c, x + 300, y + 444, "lop~ 9000", h2), ne)
        ng = op(c, x + 300, y + 488, "*~ 0", nz)
        out = op(c, x, y + 650, "+~", tg, ng)
        choke = [tvl, nvl]

        def gains(c_, x_, y_, s):
            t = op(c_, x_, y_, "t b b", s)
            # noise: vel * level * 1.6 * snappy;  tone: vel * level * (1 - 0.5 snappy)
            n = vmul(c_, x_ + 60, y_ + 22, (t, 1), pv + "vel", pv + "snappy")
            c_.connect(op(c_, x_ + 60, y_ + 88, f"* {LEVEL[V] * 1.6:g}", n), 0, ng, 1)
            sn = chain(c_, x_, y_ + 22, op(c_, x_, y_ + 22, f"v {pv}snappy", (t, 0)), ["* -0.5", "+ 1"])
            m = op(c_, x_, y_ + 110, "*", sn, None)
            tv = op(c_, x_, y_ + 66, "t f b", sn)
            c_.connect(op(c_, x_ + 40, y_ + 88, f"v {pv}vel", (tv, 1)), 0, m, 1)
            c_.connect(tv, 0, m, 0)
            c_.connect(op(c_, x_, y_ + 132, f"* {LEVEL[V]:g}", m), 0, tg, 1)
        acts = [other, lambda c_, x_, y_, s: phase(c_, x_, y_, s, [o1, o2]),
                a_v(pv + "f1", fs1), a_v(pv + "f1", fk1, scale=0.5), a_v(pv + "f2", fs2), a_v(pv + "f2", fk2, scale=0.5),
                a_v(pv + "ncut", h1), a_v(pv + "ncut", h2), gains,
                a_msg("0 \\, 1 15", pvl), a_msg("0 \\, 1 \\$1", tvl, name=pv + "tdec"),
                a_msg("0 \\, 1 \\$1", nvl, name=pv + "ndec")]
    elif V == "C":
        bvl = c.obj(x, y + 300, "vline~")
        tvl, te = xenv(c, x + 150, y + 300, lb)
        env = op(c, x, y + 388, "+~", bvl, op(c, x + 150, y + 388, "*~ 0.7", te))
        bp = op(c, x + 300, y + 300, "bp~ 1250 2", noise)
        nz = op(c, x + 300, y + 410, "*~", op(c, x + 300, y + 322, "hip~ 400", bp), env)
        out = op(c, x, y + 650, "*~ 0", nz)
        choke = [tvl]
        bz = c.msg(x + 800, y + 44, "0 3")
        c.connect(ck, 0, bz, 0)
        c.connect(bz, 0, bvl, 0)
        acts = [other, a_v(pv + "fc", bp), a_v(pv + "vel", out, scale=LEVEL[V] * 3),
                a_msg(CLAP_BURSTS, bvl), a_msg(CLAP_TAIL, tvl, name=pv + "tail")]
    elif V in ("CH", "OH"):
        sq = None
        phs = []
        for i in range(len(METAL)):
            ph = c.obj(x + i * 90, y + 300, "phasor~ 300")
            phs.append(ph)
            s_ = chain(c, x + i * 90, y + 300, ph, ["-~ 0.5", "*~ 1e+09", "clip~ -1 1"])
            sq = s_ if sq is None else op(c, x + i * 90, y + 388, "+~", sq, s_)
        mm = op(c, x, y + 410, "*~ 0", op(c, x, y + 400, f"*~ {1 / len(METAL):.4f}", sq))
        nm = op(c, x + 300, y + 410, "*~ 0", noise)
        bp = op(c, x, y + 454, "bp~ 8000 1", op(c, x, y + 432, "+~", mm, nm))
        h1 = op(c, x, y + 476, "hip~ 4000", bp)
        h2 = op(c, x, y + 498, "hip~ 4000", h1)
        avl, ae = xenv(c, x + 600, y + 300, lb)
        out = op(c, x, y + 650, "*~ 0", op(c, x, y + 520, "*~", h2, ae))
        choke = [avl]
        acts = [other] + [a_v(pv + "metal", phs[i], 0, scale=f) for i, f in enumerate(METAL)] + [
            a_v(pv + "cut", bp), a_v(pv + "cut", h1, scale=0.6), a_v(pv + "cut", h2, scale=0.6),
            lambda c_, x_, y_, s: mixset(c_, x_, y_, s, pv + "noise", mm, nm),
            a_v(pv + "vel", out, scale=LEVEL[V] * 2), a_msg("0 \\, 1 \\$1", avl, name=pv + "decay")]
    else:   # P
        pvl, pe = xenv(c, x, y + 300, lb)
        avl, ae = xenv(c, x + 150, y + 300, lb)
        osc, fk, fs = osc_sweep(c, x, y + 400, pe)
        tone = op(c, x, y + 466, "*~", osc, ae)
        cvl = c.obj(x + 300, y + 300, "vline~")
        cn = op(c, x + 300, y + 344, "*~", op(c, x + 300, y + 322, "bp~ 3000 2", noise), cvl)
        ca = op(c, x + 300, y + 366, "*~ 0", cn)
        out = op(c, x, y + 650, "*~ 0", op(c, x, y + 488, "+~", tone, ca))
        choke = [avl]
        acts = [other, lambda c_, x_, y_, s: phase(c_, x_, y_, s, [osc]),
                a_v(pv + "f", fs), a_mul(pv + "f", pv + "sweep", fk), a_v(pv + "noise", ca, scale=4),
                a_v(pv + "vel", out, scale=LEVEL[V]),
                a_msg("0 \\, 1 40", pvl), a_msg("0 \\, 1 \\$1", avl, name=pv + "decay"), a_msg("1 \\, 0 6", cvl)]
    # choke: this half fades out (the other half is starting; for the open hat also a closed hat)
    cm = c.msg(x + 700, y + 44, f"1 {CHOKE_MS}")
    c.connect(ck, 0, cm, 0)
    if V == "OH":
        c.connect(c.obj(x + 800, y + 22, "r tp_ckOH"), 0, cm, 0)
    for vl in choke:
        c.connect(cm, 0, vl, 0)
    trig(c, x, y + 30, c.obj(x, y, f"r tp_go_{V}{k}"), acts)
    return out


def phase(c, x, y, s, oscs):
    """Oscillators from 0.75 turns: osc~ is a cosine, so the tone starts on a rising zero crossing."""
    m = c.msg(x, y, "0.75")
    c.connect(s[0], s[1], m, 0)
    for o in oscs:
        c.connect(m, 0, o, 1)


def mixset(c, x, y, s, name, metal, noise):
    """[v name] = noise share: metal gain 1 - n, noise gain n."""
    t = op(c, x, y + 22, "t f f", op(c, x, y, f"v {name}", s))
    c.connect(t, 1, noise, 1)
    c.connect(chain(c, x, y + 22, t, ["* -1", "+ 1"]), 0, metal, 1)


def voices(Canvas):
    """Six analog-model voices, two round-robin halves each, panned -> two outlet~."""
    c = Canvas("#N canvas 0 50 1400 900 %NAME% 0;")
    c.text(10, 5, "Per voice: kit params from tp_snd at each hit (Sound-interpolated) -> one of two halves (the other "
                  "is choked). Envelopes: vline~ ramp read through tp_exp (exponential).")
    lb = c.obj(10, 30, "loadbang")
    sums = [None, None]
    for vi, V in enumerate(VOICES):
        x0 = 10 + vi * 2400
        voice_ctl(c, x0, 60, V)
        noise = c.obj(x0 + 1300, 560, "noise~")
        halves = [half(c, x0 + k * 1000, 560, V, k, lb, noise) for k in (0, 1)]
        v = op(c, x0, 1300, "+~", halves[0], halves[1])
        th = (PAN[V] + 1) * math.pi / 4
        for ch, g in enumerate((math.cos(th) * math.sqrt(2), math.sin(th) * math.sqrt(2))):
            gm = op(c, x0 + ch * 100, 1370, f"*~ {g:.4f}", v)
            sums[ch] = gm if sums[ch] is None else op(c, x0 + ch * 100, 1400, "+~", sums[ch], gm)
    for ch in (0, 1):
        c.connect(sums[ch], 0, c.obj(10 + ch * 100, 1450, "outlet~"), 0)
    return c


