    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, "Reset=clock (16ths). Source gate jack=back to step 1. Freeze=lock. Record=mutate. File: short=recall "
                  "home / long=store home. start/size=map X/Y density=fill overlap=chaos window=auto-mutate "
                  "blend=sound speed=drift pitch=tune")
    lb = c.obj(1100, 30, "loadbang")
    d = c.obj(1100, 55, "delay 1000")
    m = c.msg(1100, 80, "1")
