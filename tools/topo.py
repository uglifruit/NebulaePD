def steps(Canvas):
    """Clock -> step counter (reset, length, cycle start, drift tick) -> swing delay -> lane levels -> triggers."""
    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, "Clock: o2 period/swing, o1 advance (cycle start -> mutate, then drift), o0 schedule the play")
    lb = c.obj(1000, 30, "loadbang")
    one = c.msg(1000, 52, "1")
    c.connect(lb, 0, one, 0)
    setv(c, 1000, 74, "tp_rflag", one)
    rr = c.msg(1100, 52, "1")
    c.connect(c.obj(1100, 30, "r tp_rst"), 0, rr, 0)
    setv(c, 1100, 74, "tp_rflag", rr)
    c.connect(c.obj(1200, 30, "r tp_len"), 0, c.obj(1200, 52, "v tp_vlen"), 0)

    te = op(c, 10, 52, "t b b b", c.obj(10, 30, "r tp_clock"))
    # o2: step period -> swing delay = swing * period / 3 (1 = 12/8); a gap over 2 s keeps the last one
    tt = op(c, 400, 80, "t b b", (te, 2))
    tm = c.obj(400, 102, "timer")
    c.connect(tt, 1, tm, 1)
    c.connect(tt, 0, tm, 0)
    mo = op(c, 400, 124, "moses 2000", tm)
    sw = fl(c, 400, 168, "* 0", op(c, 400, 146, f"* {1 / 3:.6f}", (mo, 0)), "tp_swing")   # 1 = 12/8 (triplet)
    setv(c, 400, 190, "tp_swd", sw)
    # o1: advance (or 0 after a reset / at load)
    sr = op(c, 10, 112, "sel 0", op(c, 10, 90, "v tp_rflag", (te, 1)))
    md = fl(c, 10, 178, "mod 32", op(c, 10, 156, "+ 1", op(c, 10, 134, "v tp_step", (sr, 0))), "tp_len")
    zz = op(c, 120, 134, "t b b", (sr, 1))
    z1 = c.msg(180, 156, "0")
    c.connect(zz, 1, z1, 0)
    setv(c, 180, 178, "tp_rflag", z1)
    z0 = c.msg(120, 156, "0")
    c.connect(zz, 0, z0, 0)
    st = c.obj(10, 210, "t b f")
    c.connect(md, 0, st, 0)
    c.connect(z0, 0, st, 0)
    ts2 = op(c, 60, 232, "t f f f", (st, 1))
    setv(c, 180, 254, "tp_step", (ts2, 2))
    c.connect(chain(c, 120, 232, ts2, ["mod 4", "sel 0"], outlet=1), 0, c.obj(120, 300, "s tp_beat"), 0)  # auto-mutate
    c.connect(op(c, 60, 254, "sel 0", (ts2, 0)), 0, c.obj(60, 276, "s tp_cycle"), 0)
    c.connect(st, 0, c.obj(10, 300, "s tp_drift"), 0)
    # o0: schedule the play: odd steps wait tp_swd ms
    tq = op(c, 600, 80, "t f f b", op(c, 600, 58, "v tp_step", (te, 0)))
    mul = c.obj(660, 146, "*")
    c.connect(op(c, 720, 102, "v tp_swd", (tq, 2)), 0, mul, 1)
    hold = c.obj(600, 190, "f")
    c.connect(tq, 1, hold, 1)
    c.connect(op(c, 660, 124, "mod 2", (tq, 0)), 0, mul, 0)
    dl = op(c, 660, 168, "delay 0", mul)
    c.connect(dl, 0, hold, 0)
    tpl = op(c, 600, 212, "t f f f f f", hold)
    c.connect(tpl, 4, c.obj(900, 240, "s tp_pst"), 0)       # the step being played (tests print it)
    los = [lane(c, 10 + L * 300, 260, (tpl, 3 - L), L) for L in range(4)]
    # K, P: plain
    vel(c, 10, 660, (los[0], 1), "K")
    vel(c, 910, 660, (los[3], 1), "P")
    # S: snare, + clap on the strongest steps
    tS = op(c, 310, 660, "t f f", (los[1], 1))
    vel(c, 310, 682, (tS, 0), "S")
    mc = op(c, 400, 682, f"moses {ACCENT}", (tS, 1))
    vel(c, 400, 704, (mc, 1), "C")
    # H: closed, or open on the strongest steps
    mh = op(c, 610, 660, f"moses {ACCENT}", (los[2], 1))
    vel(c, 610, 682, (mh, 0), "CH")
    vel(c, 700, 682, (mh, 1), "OH")
    return c


