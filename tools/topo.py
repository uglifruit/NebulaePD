def snd_values():
    """tp_snd: index = (voice*NP + param)*ANCHORS + anchor."""
    rng = random.Random(SEED)
    out = []
    for v in VOICES:
        lim = LIMITS[v]
        for p, base in zip(PARAMS, KIT[v]):
            lo, hi = lim.get(p, (None, None))
            row = []
            for a in range(ANCHORS):
                u = rng.uniform(-1, 1)
                if a == 0:
                    val = base
                elif p in LOGP or p in MULP:
                    val = base * 2 ** (u * SPREAD[p] * (0.3 + 0.7 * a / 7))
                else:
                    val = base + u * SPREAD[p] * (0.3 + 0.7 * a / 7)
                if lo is not None:
                    val = min(max(val, lo), hi)
                if p in ("nmix",):
                    val = min(max(val, 0), 1)
                if p == "sweep":
                    val = max(val, 0)
                row.append(math.log2(val) if p in LOGP else val)
            out += row
    return out


# --- helpers -------------------------------------------------------------------------------------------------------
def trig(c, x, y, src, actions):
    """[t b b ...] from src that fires the given action callbacks in list order (rightmost outlet first).
    Each callback gets (c, x, y, (trigger, outlet))."""
    n = len(actions)
    t = op(c, x, y, "t" + " b" * n, src)
    for i, fn in enumerate(actions):
        fn(c, x + i * 110, y + 30, (t, n - 1 - i))
    return t


def vto(name, dst, inlet=0):
    """Action: bang [v name] into dst's inlet."""
    def fn(c, x, y, src):
        c.connect(op(c, x, y, f"v {name}", src), 0, dst, inlet)
    return fn


def vmul(c, x, y, src, a, b):
    """bang -> [v a] * [v b]; returns the [*]."""
    t = op(c, x, y, "t b b", src)
    m = c.obj(x, y + 44, "*")
    c.connect(op(c, x + 50, y + 22, f"v {b}", (t, 1)), 0, m, 1)
    c.connect(op(c, x, y + 22, f"v {a}", (t, 0)), 0, m, 0)
    return m


def vadd(c, x, y, src, a, b):
    t = op(c, x, y, "t b b", src)
    m = c.obj(x, y + 44, "+")
    c.connect(op(c, x + 50, y + 22, f"v {b}", (t, 1)), 0, m, 1)
    c.connect(op(c, x, y + 22, f"v {a}", (t, 0)), 0, m, 0)
    return m


def setv(c, x, y, name, src):
    """src (an object id or (id, outlet)) -> [v name] (a float sets it)."""
    s, o = src if isinstance(src, tuple) else (src, 0)
    c.connect(s, o, c.obj(x, y, f"v {name}"), 0)


def cube(c, x, y, a):
    return op(c, x, y + 22, "*~", op(c, x, y, "*~", a, a), a)


# --- subpatches ----------------------------------------------------------------------------------------------------
def tables(Canvas):
    """Load the map and the kit anchors at load time."""
    c = Canvas("#N canvas 0 50 700 400 %NAME% 0;")
    c.text(10, 5, "tp_map (25 nodes x 4 lanes x 32 steps) and tp_snd (6 voices x 10 params x 8 anchors), from "
                  "tools/topo.py")
    lb = c.obj(10, 30, "loadbang")
    vals = map_values()
    for i in range(0, len(vals), 128):
        m = c.msg(10 + (i // 128 % 5) * 130, 60 + (i // 640) * 25, f"\\; tp_map {i} " + " ".join(map(str, vals[i:i + 128])))
        c.connect(lb, 0, m, 0)
    sv = snd_values()
    for i in range(0, len(sv), 80):
        m = c.msg(10 + (i // 80) * 100, 220, f"\\; tp_snd {i} " + " ".join(f"{v:.5g}" for v in sv[i:i + 80]))
        c.connect(lb, 0, m, 0)
    return c


