def mutate(Canvas):
    """Re-draws (auto per cycle, Record burst), X/Y drift, home store/recall."""
    c = Canvas("#N canvas 0 50 1300 900 %NAME% 0;")
    c.text(10, 5, "One mutation: random lane + step < length. 50% swap with a neighbour (a hit moves), 30% new level, "
                  "20% heal (offset 0). Lock stops auto re-draws and drift (Record still mutates).")
    lock = c.obj(10, 30, "r tp_lock")
    nl = op(c, 10, 52, "== 0", lock)
    auto = c.obj(100, 96, "spigot 1")
    c.connect(c.obj(100, 30, "r tp_cycle"), 0, auto, 0)
    c.connect(nl, 0, auto, 1)
    un = c.obj(100, 160, "until")
    c.connect(fl(c, 100, 118, "f 0", auto, "tp_namt"), 0, un, 0)
    c.connect(fl(c, 250, 118, "f 4", c.obj(250, 96, "r tp_mutnow"), "tp_nburst"), 0, un, 0)
    c.connect(c.obj(400, 30, "r tp_len"), 0, c.obj(400, 52, "v tp_vlen"), 0)

    def pick(rng, k, name, mult=None, rng_recv=None):
        def fn(c, x, y, src):
            r = rnd(c, x, y + 66, k, rng=rng, seed="tp_seed")
            c.connect(src[0], src[1], r, 0)
            if rng_recv:
                c.connect(c.obj(x + 60, y + 44, f"r {rng_recv}"), 0, r, 1)
            o = op(c, x, y + 88, f"* {mult}", r) if mult else r
            setv(c, x, y + 110, name, o)
        return fn

    def dispatch(c, x, y, src):
        m5 = op(c, x, y + 22, "moses 5", op(c, x, y, "v tp_mk", src))
        m8 = op(c, x + 300, y + 44, "moses 8", (m5, 1))
        # swap (0..4)
        sx, sy = x, y + 120
        trig(c, sx, sy, (m5, 0), [
            lambda c, x_, y_, s: setv(c, x_, y_ + 66, "tp_mi1", vadd(c, x_, y_, s, "tp_mL", "tp_ms")),
            neighbour,
            lambda c, x_, y_, s: level(c, x_, y_ + 200, s, "tp_mi1", "tp_ml1", "tp_mc1"),
            lambda c, x_, y_, s: level(c, x_, y_ + 400, s, "tp_mi2", "tp_ml2", "tp_mc2"),
            decide,
        ])
        # flip (5..7): a silent step gets a level in [thr, 255), a playing one a level below 0.9*thr
        nx_ = x + 700
        trig(c, nx_, sy, (m8, 0), [
            lambda c, x_, y_, s: setv(c, x_, y_ + 66, "tp_mi1", vadd(c, x_, y_, s, "tp_mL", "tp_ms")),
            lambda c, x_, y_, s: level(c, x_, y_ + 100, s, "tp_mi1", "tp_ml1", "tp_mc1"),
            flip,
            lambda c, x_, y_, s: write_off(c, x_, y_ + 450, s, "tp_mi1", "tp_mr", "tp_mc1"),
        ])
        # heal (8, 9): off = 0
        hx = x + 1150
        ti = vadd(c, hx, sy, (m8, 1), "tp_mL", "tp_ms")
        tb = op(c, hx, sy + 66, "t b f", ti)
        tw = c.obj(hx, sy + 110, "tabwrite tp_off")
        c.connect(tb, 1, tw, 1)
        z = c.msg(hx, sy + 88, "0")
        c.connect(tb, 0, z, 0)
        c.connect(z, 0, tw, 0)

    def neighbour(c, x, y, src):
        """n = (s + len + d) mod len, d = -2, -1, 1 or 2 -> tp_mi2 = lane*32 + n."""
        t = op(c, x, y, "t b b b", src)
        mdo = c.obj(x, y + 154, "mod 32")
        b = c.obj(x, y + 132, "+")
        a = c.obj(x, y + 110, "+")
        tl = op(c, x + 140, y + 44, "t f f", op(c, x + 140, y + 22, "v tp_vlen", (t, 2)))
        c.connect(tl, 1, mdo, 1)
        c.connect(tl, 0, b, 1)
        c.connect(op(c, x + 70, y + 22, "v tp_ms", (t, 1)), 0, a, 1)
        r = rnd(c, x, y + 66, 23, rng=4, seed="tp_seed")
        c.connect(t, 0, r, 0)
        mz = op(c, x, y + 88, "moses 0", op(c, x, y + 66, "- 2", r))
        c.connect(mz, 0, a, 0)
        c.connect(op(c, x + 50, y + 88, "+ 1", (mz, 1)), 0, a, 0)
        c.connect(a, 0, b, 0)
        c.connect(b, 0, mdo, 0)
        tb = op(c, x, y + 176, "t f b", mdo)
        ad = c.obj(x, y + 220, "+")
        c.connect(op(c, x + 60, y + 198, "v tp_mL", (tb, 1)), 0, ad, 1)
        c.connect(tb, 0, ad, 0)
        setv(c, x, y + 242, "tp_mi2", ad)

    def decide(c, x, y, src):
        """Swap only if exactly one of the two steps plays (an audible move); otherwise flip step 1."""
        t = op(c, x, y, "t b b b", src)
        th = chain(c, x + 160, y, op(c, x + 160, y + 22, "v tp_mL", (t, 2)), ["/ 32", "tabread tp_thrt"])
        ge1 = c.obj(x, y + 110, ">=")
        ge2 = c.obj(x + 80, y + 110, ">=")
        c.connect(th, 0, ge1, 1)
        c.connect(th, 0, ge2, 1)
        c.connect(op(c, x + 80, y + 88, "v tp_ml2", (t, 1)), 0, ge2, 0)
        c.connect(op(c, x, y + 88, "v tp_ml1", (t, 0)), 0, ge1, 0)
        ne = op(c, x, y + 132, "!=", ge1, ge2)
        sl = op(c, x, y + 154, "sel 0", ne)
        trig(c, x, y + 200, (sl, 0), [
            flip,
            lambda c, x_, y_, s: write_off(c, x_, y_ + 700, s, "tp_mi1", "tp_mr", "tp_mc1"),
        ])
        trig(c, x + 300, y + 200, op(c, x + 300, y + 176, "t b", (sl, 1)), [
            lambda c, x_, y_, s: write_off(c, x_, y_, s, "tp_mi1", "tp_ml2", "tp_mc1"),
            lambda c, x_, y_, s: write_off(c, x_, y_ + 100, s, "tp_mi2", "tp_ml1", "tp_mc2"),
        ])

    def flip(c, x, y, src):
        """tp_mr = thr + u*(255 - thr) if the step is silent (level < thr), else u*0.9*thr. u = random 0..1."""
        t = op(c, x, y + 300, "t b b b", src)
        th = chain(c, x + 160, y + 300, op(c, x + 160, y + 322, "v tp_mL", (t, 2)), ["/ 32", "tabread tp_thrt"])
        setv(c, x + 160, y + 388, "tp_mth", th)
        r = rnd(c, x + 80, y + 388, 24, rng=1000, seed="tp_seed")
        c.connect(t, 1, r, 0)
        setv(c, x + 80, y + 432, "tp_mu", op(c, x + 80, y + 410, "* 0.001", r))
        tc = op(c, x, y + 454, "t b b", (t, 0))
        mo = c.obj(x, y + 498, "moses")
        c.connect(op(c, x + 50, y + 476, "v tp_mth", (tc, 1)), 0, mo, 1)
        c.connect(op(c, x, y + 476, "v tp_ml1", (tc, 0)), 0, mo, 0)
        # silent -> play: thr + u*(255 - thr)
        on = op(c, x, y + 520, "t b", (mo, 0))
        sp = chain(c, x, y + 586, vmul(c, x, y + 542, on, "tp_mu", "tp_mspan"), ["+ 0"])     # right inlet: thr
        # playing -> silent: u * 0.9 * thr
        off = op(c, x + 150, y + 520, "t b", (mo, 1))
        sl = chain(c, x + 150, y + 520, vmul(c, x + 150, y + 542, off, "tp_mu", "tp_mth"), ["* 0.9"])
        setv(c, x + 150, y + 650, "tp_mr", sl)
        # tp_mspan = 255 - thr, and the + thr
        c.connect(chain(c, x + 250, y + 388, th, ["* -1", "+ 255"]), 0, c.obj(x + 250, y + 454, "v tp_mspan"), 0)
        c.connect(th, 0, sp, 1)
        setv(c, x, y + 650, "tp_mr", sp)

    trig(c, 100, 200, un, [
        pick(4, 20, "tp_mL", mult=STEPS),
        pick(32, 21, "tp_ms", rng_recv="tp_len"),
        pick(10, 22, "tp_mk"),
        dispatch,
    ])

    # --- drift: per step, unless locked, dx/dy random-walk by tp_drate (|d| <= 0.5) ---
    x, y = 10, 1100
    dg = c.obj(x, y + 22, "spigot 1")
    c.connect(c.obj(x, y, "r tp_drift"), 0, dg, 0)
    c.connect(nl, 0, dg, 1)
    tdr = op(c, x, y + 44, "t b b", dg)
    for k, A in enumerate("xy"):
        xx = x + k * 200
        r = rnd(c, xx, y + 132, 30 + k, rng=2001, seed="tp_seed")
        c.connect(tdr, k, r, 0)
        dlt = fl(c, xx, y + 176, "* 0", op(c, xx, y + 154, "- 1000", r), "tp_drate")
        acc = op(c, xx, y + 198, "+", dlt)
        c.connect(c.obj(xx + 60, y + 176, f"r tp_d{A}"), 0, acc, 1)
        chain(c, xx, y + 198, acc, ["clip -0.5 0.5", "change", f"s tp_d{A}"])
        c.connect(c.obj(xx + 100, y + 280, f"r tp_d{A}"), 0, c.obj(xx + 100, y + 302, f"v tp_vd{A}"), 0)

    # --- home: store / recall the offsets and the drift position ---
    x, y = 500, 1100
    ts = op(c, x, y + 22, "t b b b", c.obj(x, y, "r tp_store"))
    copy(c, x, y + 60, (ts, 2), "tp_off", "tp_home")
    for k, A in enumerate("xy"):
        setv(c, x + 200 + k * 100, y + 66, f"tp_hd{A}", op(c, x + 200 + k * 100, y + 44, f"v tp_vd{A}", (ts, k)))
    x = 900
    tr = op(c, x, y + 22, "t b b b", c.obj(x, y, "r tp_recall"))
    copy(c, x, y + 60, (tr, 2), "tp_home", "tp_off")
    for k, A in enumerate("xy"):
        c.connect(op(c, x + 200 + k * 100, y + 44, f"v tp_hd{A}", (tr, k)), 0,
                  c.obj(x + 200 + k * 100, y + 66, f"s tp_d{A}"), 0)
    return c


def voice_ctl(c, x, y, V, vi):
    """tp_trig_V vel -> read the 10 params (Sound-interpolated) into [v tp_V_*] -> round-robin go."""
    t = op(c, x, y + 22, "t f b", c.obj(x, y, f"r tp_trig_{V}"))
    tp = op(c, x, y + 44, "t" + " b" * NP, (t, 1))         # outlet p = param p; fires 9..0 (sweep before f)
    for p, name in enumerate(PARAMS):
        px, py = x + p * 120, y + 80
        idx = op(c, px, py + 22, f"+ {(vi * NP + p) * ANCHORS}", op(c, px, py, "v tp_sa", (tp, p)))
        ti = op(c, px, py + 44, "t f f", idx)
        tv = op(c, px + 60, py + 88, "t f f", op(c, px + 60, py + 66, "tabread tp_snd", (ti, 1)))
        v1 = op(c, px, py + 88, "tabread tp_snd", op(c, px, py + 66, "+ 1", (ti, 0)))
        m = fl(c, px, py + 132, "* 0", op(c, px, py + 110, "-", v1, (tv, 0)), "tp_sfr")
        val = op(c, px, py + 154, "+", m, (tv, 1))
        yy = py + 176
        if name == "f":
            tuned = fl(c, px, yy + 44, "* 1", chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp"]), "tp_tune")
            tf = op(c, px, yy + 66, "t f f b", tuned)
            mk = c.obj(px, yy + 110, "*")
            c.connect(op(c, px + 60, yy + 88, f"v tp_{V}_k", (tf, 2)), 0, mk, 1)
            setv(c, px + 40, yy + 132, f"tp_{V}_F", (tf, 1))
            c.connect(tf, 0, mk, 0)
            setv(c, px, yy + 154, f"tp_{V}_FK", mk)
        elif name == "ratio":
            setv(c, px, yy + 44, f"tp_{V}_R", chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp"]))
        elif name == "index":
            setv(c, px, yy + 22, f"tp_{V}_I", chain(c, px, yy - 22, val, [f"* {1 / (2 * math.pi):.6f}"]))
        elif name in ("idec", "adec", "ndec"):
            setv(c, px, yy + 22, f"tp_{V}_{name}", fl(c, px, yy, "* 1", val, "tp_decay"))
        elif name == "sweep":
            setv(c, px, yy + 66, f"tp_{V}_k", chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp", "- 1"]))
        elif name == "stime":
            setv(c, px, yy, f"tp_{V}_stime", val)
        elif name == "nmix":
            tn = op(c, px, yy, "t f f", val)
            setv(c, px, yy + 88, f"tp_{V}_TG", chain(c, px + 50, yy, tn, ["* -1", "+ 1", f"* {LEVEL[V]:g}"], outlet=1))
            setv(c, px, yy + 44, f"tp_{V}_NG", chain(c, px, yy, tn, [f"* {LEVEL[V] * NGAIN[V]:g}"]))
        elif name == "ncut":
            setv(c, px, yy + 66, f"tp_{V}_NC", chain(c, px, yy - 22, val, [f"* {LN2:.6f}", "exp", "clip 20 16000"]))
    tg = op(c, x, y + 400, "t b f", (t, 0))
    setv(c, x + 60, y + 422, f"tp_{V}_vel", (tg, 1))
    rr = c.obj(x, y + 444, "f")
    c.connect(tg, 0, rr, 0)
    c.connect(chain(c, x + 60, y + 444, rr, ["+ 1", "mod 2"]), 0, rr, 1)
    sl = op(c, x, y + 466, "sel 0 1", rr)
    if V == "CH":
        tc = op(c, x + 200, y + 444, "t b", (tg, 0))
        c.connect(tc, 0, c.obj(x + 200, y + 466, "s tp_ckOH"), 0)
    for k in (0, 1):
        c.connect(sl, k, c.obj(x + k * 100, y + 490, f"s tp_go_{V}{k}"), 0)


def subvoice(c, x, y, V, k, noise):
    """One round-robin half of voice V. Returns its outlet object (a signal sum)."""
    pv = f"tp_{V}_"
    # signal graph
    penv = c.obj(x, y + 420, "vline~")
    fm = op(c, x, y + 466, "*~ 0", op(c, x, y + 444, "*~", penv, penv))
    fs = op(c, x, y + 488, "+~ 0", fm)
    ph = op(c, x, y + 510, "phasor~", fs)
    mf = op(c, x + 100, y + 510, "*~ 0", fs)
    mo = op(c, x + 100, y + 532, "osc~", mf)
    ienv = c.obj(x + 200, y + 466, "vline~")
    ii = op(c, x + 200, y + 510, "*~ 0", op(c, x + 200, y + 488, "*~", ienv, ienv))
    tone = op(c, x, y + 598, "cos~", op(c, x, y + 576, "+~", ph, op(c, x + 100, y + 554, "*~", mo, ii)))
    aenv = c.obj(x + 300, y + 532, "vline~")
    tg = op(c, x, y + 642, "*~ 0", op(c, x, y + 620, "*~", tone, cube(c, x + 300, y + 554, aenv)))
    bp = op(c, x + 400, y + 532, f"bp~ 1000 {BPQ[V]:g}", noise)
    nenv = c.obj(x + 500, y + 532, "vline~")
    ng = op(c, x + 400, y + 642, "*~ 0", op(c, x + 400, y + 620, "*~", bp, cube(c, x + 500, y + 554, nenv)))
    out = op(c, x, y + 670, "+~", tg, ng)
    # choke (the other half starting, or for the open hat a closed hat)
    ck = c.msg(x + 600, y + 466, f"0 {CHOKE_MS}")
    c.connect(c.obj(x + 600, y + 444, f"r tp_ck_{V}{k}"), 0, ck, 0)
    if V == "OH":
        c.connect(c.obj(x + 700, y + 444, "r tp_ckOH"), 0, ck, 0)
    c.connect(ck, 0, aenv, 0)
    c.connect(ck, 0, nenv, 0)
    # go: set everything, then fire the envelopes
    amsg = CLAP_ENV if V == "C" else ENV

    def env(name, dst, text):
        def fn(c, x_, y_, s):
            m = c.msg(x_, y_ + 44, text)
            c.connect(op(c, x_, y_, f"v {pv}{name}", s), 0, m, 0)
            c.connect(m, 0, dst, 0)
        return fn

    def mulset(a, dst):
        def fn(c, x_, y_, s):
            c.connect(vmul(c, x_, y_, s, f"{pv}{a}", f"{pv}vel"), 0, dst, 1)
        return fn

    def phase0(c, x_, y_, s):
        """Carrier from 0.75 turns (cos~ = 0: the tone starts on a zero crossing), modulator from 0."""
        z = c.msg(x_, y_, "0.75")
        c.connect(s[0], s[1], z, 0)
        c.connect(z, 0, ph, 1)
        z0 = c.msg(x_ + 50, y_, "0")
        c.connect(s[0], s[1], z0, 0)
        c.connect(z0, 0, mo, 1)

    def choke_other(c, x_, y_, s):
        c.connect(s[0], s[1], c.obj(x_, y_, f"s tp_ck_{V}{1 - k}"), 0)

    trig(c, x, y + 22, c.obj(x, y, f"r tp_go_{V}{k}"), [
        choke_other,
        vto(f"{pv}NC", bp, 1),
        phase0,
        vto(f"{pv}F", fs, 1),
        vto(f"{pv}FK", fm, 1),
        vto(f"{pv}R", mf, 1),
        vto(f"{pv}I", ii, 1),
        mulset("TG", tg),
        mulset("NG", ng),
        env("stime", penv, "1 \\, 0 \\$1"),
        env("idec", ienv, "1 \\, 0 \\$1"),
        env("adec", aenv, amsg),
        env("ndec", nenv, amsg),
    ])
    return out


def voices(Canvas):
    """Six FM + noise voices, two round-robin halves each, panned -> two outlet~."""
    c = Canvas("#N canvas 0 50 1400 900 %NAME% 0;")
    c.text(10, 5, "Per voice: params from tp_snd at each hit (Sound-interpolated) -> one of two halves (the other is "
                  "choked). Tone = cos~(phasor~ + index*osc~), pitch sweep, + band-passed noise. Envelopes cubed.")
    sums = [None, None]
    for vi, V in enumerate(VOICES):
        x0 = 10 + vi * 2400
        voice_ctl(c, x0, 30, V, vi)
        noise = c.obj(x0 + 1300, 560, "noise~")
        halves = [subvoice(c, x0 + k * 800, 560, V, k, noise) for k in (0, 1)]
        v = op(c, x0, 1300, "+~", halves[0], halves[1])
        if V in HIP:
            v = op(c, x0, 1322, f"hip~ {HIP[V]}", v)
        if V in ("CH", "OH"):
            v = op(c, x0, 1344, f"hip~ {HIP[V]}", v)       # hats: 2 poles
        th = (PAN[V] + 1) * math.pi / 4
        for ch, g in enumerate((math.cos(th) * math.sqrt(2), math.sin(th) * math.sqrt(2))):
            gm = op(c, x0 + ch * 100, 1370, f"*~ {g:.4f}", v)
            sums[ch] = gm if sums[ch] is None else op(c, x0 + ch * 100, 1400, "+~", sums[ch], gm)
    for ch in (0, 1):
        c.connect(sums[ch], 0, c.obj(10 + ch * 100, 1450, "outlet~"), 0)
    return c


def test_clock(Canvas):
    """Test clock: [r tp_tclk] (1 = on, 0 = off) sends Reset pulses every [r tp_tper] ms (default 125 = 16ths at
    120 BPM). Prints each step and hit with its time since load (step: t n / hit_V: t vel)."""
    c = Canvas("#N canvas 0 50 900 400 %NAME% 0;")
    lb = c.obj(600, 10, "loadbang")
    met = fl(c, 10, 32, "metro 125", c.obj(10, 10, "r tp_tclk"), "tp_tper")
    t = op(c, 10, 54, "t b", met)
    c.connect(t, 0, c.msg(10, 76, "\\; reset 1"), 0)
    c.connect(op(c, 100, 76, "delay 4", t), 0, c.msg(100, 98, "\\; reset 0"), 0)
    for i, (rname, label) in enumerate([("tp_pst", "step"), ("tp_cycle", "cycle")] +
                                       [(f"tp_trig_{V}", f"hit_{V}") for V in VOICES]):
        x = 10 + i * 110
        tb = op(c, x, 160, "t b f", c.obj(x, 138, f"r {rname}"))
        pk = c.obj(x, 226, "pack 0 0")
        c.connect(tb, 1, pk, 1)
        tm = c.obj(x, 204, "timer")
        c.connect(lb, 0, tm, 0)
        c.connect(tb, 0, tm, 1)
        c.connect(tm, 0, pk, 0)
        c.connect(pk, 0, c.obj(x, 248, f"print {label}"), 0)
    return c


def topo_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "06_topo: clocked drum-pattern generator (Grids-style map) + FM drum synth. See docs/TOPO.md.")
    c.text(10, 20, "Clock (16ths) into Reset. Source gate = back to step 1. Freeze = lock. Record = mutate. "
                   "File: short = recall home / long = store home.")
    c.text(10, 35, "start/size = map X/Y. density = fill. overlap = chaos. window = auto-mutate. blend = sound. "
                   "speed = drift. pitch = tune. Alt: fills K/S/H/P + length + decay + swing (pitch_alt).")
    c.sub(10, 60, "nebulae_controls", controls_canvas())
    c.obj(200, 60, f"table tp_map {25 * NODE}")
    c.obj(350, 60, f"table tp_off {NODE}")
    c.obj(500, 60, f"table tp_home {NODE}")
    c.obj(650, 60, f"table tp_snd {len(VOICES) * NP * ANCHORS}")
    c.obj(800, 60, "table tp_thrt 4")
    c.sub(10, 90, "tables", tables(Canvas))
    c.sub(100, 90, "ui", ui(Canvas))
    c.sub(170, 90, "pos", pos(Canvas))
    c.sub(240, 90, "mapq", mapq(Canvas))
    c.sub(320, 90, "thr", thr(Canvas))
    c.sub(390, 90, "steps", steps(Canvas))
    c.sub(470, 90, "mutate", mutate(Canvas))
    vo = c.sub(10, 140, "voices", voices(Canvas))
    outs = []
    for ch, x in [(0, 10), (1, 220)]:
        outs.append(softclip(c, x, 200, op(c, x, 170, "*~ 0.8", (vo, ch))))
    dac = c.obj(10, 340, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        c.sub(10, 370, "testclock", test_clock(Canvas))
        lb = c.obj(600, 340, "loadbang")
        steps_ = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps_):
            if wav and "pd quit" in msg:
                msg = "\\; tp_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 365 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 387 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            # record into tables and save at quit: writesf~ drops audio in fast -batch runs (its disk thread lags)
            n = int(max(ms for ms, _ in steps_) * SR / 1000)
            for ch, x in [(0, 10), (1, 200)]:
                side = "lr"[ch]
                c.obj(x, 470, f"table tp_rec{side} {n}")
                tw = c.obj(x, 440, f"tabwrite~ tp_rec{side}")
                c.connect(outs[ch], 0, tw, 0)
                c.connect(lb, 0, tw, 0)        # starts with DSP: WAV time 0 = DSP start
            rs = c.obj(400, 440, "r tp_save")
            wm2 = c.msg(400, 462, f"write -bytes 4 {wav} tp_recl tp_recr")
            sf = c.obj(400, 484, "soundfiler")
            c.connect(rs, 0, wm2, 0)
            c.connect(wm2, 0, sf, 0)
    return c
