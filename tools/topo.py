def lane_values(s):
    s = s.replace("|", "")
    assert len(s) == STEPS, (s, len(s))
    return [0 if ch == "." else 28 * int(ch) for ch in s]


def map_values():
    """tp_map: index = (y*5 + x)*128 + lane*32 + step."""
    out = []
    for y in range(5):
        for x in range(5):
            for s in NODES[(x, y)]:
                out += lane_values(s)
    return out


