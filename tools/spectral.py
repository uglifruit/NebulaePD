    c.connect(pf, 0, tf, 0)
    on = c.msg(130, 165, "\\; sp_cap 1")
    c.connect(tf, 1, on, 0)
    dl = c.obj(220, 165, "delay 25")          # >= 2 hops, so at least one whole frame re-captures
    c.connect(tf, 0, dl, 0)
    c.connect(dl, 0, c.msg(220, 190, "\\; sp_cap 0"), 0)
    for i, (src, dst) in enumerate([("freeze", "sp_frz"), ("source", "sp_seal"), ("record", "sp_gat")]):
        r = c.obj(300 + i * 110, 30, f"r {src}")
        chain(c, 300 + i * 110, 30, r, ["change", f"s {dst}"])

    # seed the random generators from the time to the first Reset or density move (after priming)
    sg = c.obj(10, 230, "spigot 1")
    c.connect(p, 0, sg, 0)
    rdn = c.obj(90, 186, "r density")
    rdc = chain(c, 90, 186, rdn, ["change"])
    rdp = c.obj(160, 186, "r sp_primed")
    rds = op(c, 90, 230, "spigot", rdc, rdp)
    c.connect(rds, 0, sg, 0)
    ts = c.obj(10, 252, "t b b")
    c.connect(sg, 0, ts, 0)
    z = c.msg(80, 274, "0")
    c.connect(ts, 1, z, 0)
    c.connect(z, 0, sg, 1)
    tm = c.obj(10, 296, "timer")
    c.connect(lb, 0, tm, 0)
    c.connect(ts, 0, tm, 1)
    chain(c, 10, 296, tm, ["* 1000", "int", "s sp_seed"])

    # --- latch logic: g = gat*(1-cap), nfz = 1 - frz*(1-cap), nfzg = nfz*(1-g) ---
    x0, y0 = 300, 120
    comp = c.obj(x0, y0 + 60, "t b b b")
    for i, n in enumerate(["frz", "gat", "cap"]):
        r = c.obj(x0 + i * 90, y0, f"r sp_{n}")
        t = c.obj(x0 + i * 90, y0 + 22, "t b f")
        c.connect(r, 0, t, 0)
        c.connect(t, 1, c.obj(x0 + i * 90 + 40, y0 + 44, f"v sp_v{n}"), 0)
        c.connect(t, 0, comp, 0)
    y1 = y0 + 90
    # comp outlet 2: 1 - cap -> right inlets of the two products
    vc = c.obj(x0 + 330, y1, "v sp_vcap")
    c.connect(comp, 2, vc, 0)
    nc = chain(c, x0 + 330, y1, vc, ["* -1", "+ 1"])
    nfzg = c.obj(x0, y1 + 110, "*")
    # outlet 1: g (and 1 - g into nfzg)
    vg = c.obj(x0 + 110, y1, "v sp_vgat")
    c.connect(comp, 1, vg, 0)
    tg = op(c, x0 + 110, y1 + 44, "t f f", op(c, x0 + 110, y1 + 22, "*", vg, nc))
    c.connect(tg, 1, c.obj(x0 + 200, y1 + 66, "s sp_g"), 0)
    c.connect(chain(c, x0 + 110, y1 + 44, tg, ["* -1", "+ 1"]), 0, nfzg, 1)
    # outlet 0: nfz
    vf = c.obj(x0, y1, "v sp_vfrz")
    c.connect(comp, 0, vf, 0)
    nf = chain(c, x0, y1 + 22, op(c, x0, y1 + 22, "*", vf, nc), ["* -1", "+ 1"])
    tn = op(c, x0, y1 + 88, "t f f", nf)
    c.connect(tn, 1, c.obj(x0 + 60, y1 + 110, "s sp_nfz"), 0)
    c.connect(tn, 0, nfzg, 0)
    c.connect(nfzg, 0, c.obj(x0, y1 + 132, "s sp_nfzg"), 0)
    # gather decay, but none while frozen (Freeze + Gather layers new material in without losing the hold)
    x3 = x0 + 500
    cd = c.obj(x3, y0 + 66, "t b b")
    for i, n in enumerate(["frz", "d"]):
        r = c.obj(x3 + i * 90, y0, f"r sp_{n}")
        t = op(c, x3 + i * 90, y0 + 22, "t b f", r)
        c.connect(t, 1, c.obj(x3 + i * 90 + 40, y0 + 44, f"v sp_w{n}"), 0)
