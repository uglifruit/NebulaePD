    c.connect(mxd, 0, c.obj(x3, y0 + 132, "s sp_deff"), 0)
    # held bins keep their own frequency when sealed OR gathering: a gathered partial given the phase of whatever
    # unrelated live bin is under it turns into a noise sweep. Source (sealed) only matters for a plain freeze.
    x4 = x0 + 700
    ch_ = c.obj(x4, y0 + 66, "t b b")
    for i, n in enumerate(["seal", "g"]):
        r = c.obj(x4 + i * 90, y0, f"r sp_{n}")
        t = op(c, x4 + i * 90, y0 + 22, "t b f", r)
        c.connect(t, 1, c.obj(x4 + i * 90 + 40, y0 + 44, f"v sp_h{n}"), 0)
        c.connect(t, 0, ch_, 0)
    mxh = op(c, x4, y0 + 110, "max", op(c, x4, y0 + 88, "v sp_hseal", (ch_, 0)), op(c, x4 + 90, y0 + 88, "v sp_hg", (ch_, 1)))
    c.connect(mxh, 0, c.obj(x4, y0 + 132, "s sp_hold"), 0)

    # --- knobs ---
    x, y = 10, 400
    r = c.obj(x, y, "r density")
    chain(c, x, y, r, ["* -1", "+ 0.5", "s sp_hp"])             # threshold offset 0.5 - p
    r = c.obj(x + 110, y, "r size")
    chain(c, x + 110, y, r, [f"* {math.log(32):.5f}", "exp", "* 4", "s sp_nt"])   # 4..128 bands
    r = c.obj(x + 220, y, "r overlap")
    chain(c, x + 220, y, r, ["* 0.5", "s sp_tex"])             # +-0.5 turn at full
    r = c.obj(x + 330, y, "r blend")
    chain(c, x + 330, y, r, ["s sp_wet"])
    # window -> smoothing coefficient: snap below 0.1, then tau 50 ms .. 3 s; lp = exp(-1/(tau*FR))
    x, y = 10, 520
    r = c.obj(x, y, "r window")
    mo = op(c, x, y + 22, "moses 0.1", r)
    z = c.msg(x, y + 44, "0")
    c.connect(mo, 0, z, 0)
    k1 = 1 / (0.05 * FR)
    hi = chain(c, x + 60, y + 22, mo, ["- 0.1", "/ 0.9", f"* -{math.log(60):.5f}", "exp", f"* -{k1:.6f}", "exp"],
               outlet=1)
    cg = c.obj(x, y + 180, "change")
    c.connect(z, 0, cg, 0)
    c.connect(hi, 0, cg, 0)
    c.connect(cg, 0, c.obj(x, y + 202, "s sp_lp"), 0)
    # start -> re-roll threshold per tick (of 1e6): off below 0.1, then mean interval 3 s .. every tick
    x = 220
    r = c.obj(x, y, "r start")
    mo = op(c, x, y + 22, "moses 0.1", r)
    z = c.msg(x, y + 44, "0")
    c.connect(mo, 0, z, 0)
    lk = math.log(3 * FR)
    hi = chain(c, x + 60, y + 22, mo, ["- 0.1", "/ 0.9", "- 1", f"* {lk:.5f}", "exp", "* 1e+06"], outlet=1)
    cg = c.obj(x, y + 180, "change")
    c.connect(z, 0, cg, 0)
    c.connect(hi, 0, cg, 0)
    c.connect(cg, 0, c.obj(x, y + 202, "s sp_rr"), 0)
    # speed -> drift per tick: 16*d*|d| cycles/s (click +-0.25, ends +-4), positive = pattern rises
    x = 430
    r = c.obj(x, y, "r speed")
    t = c.obj(x, y + 44, "t f f")
    c.connect(op(c, x, y + 22, "- 0.5", r), 0, t, 0)
    ab = c.obj(x + 60, y + 66, "abs")
    c.connect(t, 1, ab, 0)
    pr = op(c, x, y + 88, "*", t, ab)
    chain(c, x, y + 88, pr, [f"* -{16 / FR:.6f}", "change", "s sp_du"])
    # pitch -> semitones pitch*60 - 36 (click 0.6 = 0), dead zone +-0.05
    x = 640
    r = c.obj(x, y, "r pitch")
    sm = chain(c, x, y, r, ["* 60", "- 36"])
    m1 = op(c, x, y + 66, "moses -0.05", sm)
    m2 = c.obj(x + 60, y + 88, "moses 0.05")
    c.connect(m1, 1, m2, 0)
    z = c.msg(x + 60, y + 110, "0")
    c.connect(m2, 0, z, 0)
    cg = c.obj(x, y + 132, "change")
    for s_, o in [(m1, 0), (z, 0), (m2, 1)]:
        c.connect(s_, o, cg, 0)
    t = c.obj(x, y + 154, "t f f f f f f")
    c.connect(cg, 0, t, 0)
    chain(c, x + 300, y + 154, t, ["!= 0", "s sp_pitched"], outlet=5)
    chain(c, x + 240, y + 154, t, [f"* {math.log(2) / 12:.7f}", "exp", "* 0.25", "s sp_r4"], outlet=4)
    chain(c, x + 180, y + 154, t, [f"* -{math.log(2) / 12:.7f}", "exp", "s sp_ir"], outlet=3)
    # peak search window for the pitched path: level = clip(ceil(1 - semis/12), 1, 4), i.e. 2^level >= 2/r bins
    # centred on k/r (read at k/r - off, off = 2^(level-1) - 0.5)
    lv = chain(c, x + 120, y + 176, op(c, x + 120, y + 176, "* -0.0833333", (t, 2)),
               ["+ 1.9999", "int", f"clip 1 {LEVELS - 1}", "change"])
    tl = op(c, x + 120, y + 286, "t f f", lv)
    c.connect(tl, 1, c.obj(x + 200, y + 308, "s sp_lvl"), 0)
    so = op(c, x + 120, y + 308, "sel " + " ".join(str(v) for v in range(1, LEVELS)), tl)
