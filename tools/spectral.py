"""05_spectral: "Spectral Clouds+" for the Nebulae, after WorkshopSpectral (Workshop Computer port of Kammerl's
Spectral Clouds). Philosophically the same instrument, not a port: random gains on log-spaced bands, gated by a
probability threshold, morphed by smoothing, with phase-scramble texture and a normal/sealed freeze. New here:
true stereo with a Spread control, spectral pitch (V/oct), band drift, spectral gather, and a tape delay on the alt
layer.

Generated by tools/gen.py. Design notes: docs/SPECTRAL.md. User guide: patches/05_spectral_README.md.

Engine
- [pd stft] runs at block~ 2048 overlap 4 (hop 512 = 10.67 ms). Per channel, in DSP order (dummy signal links):
  - ana: sine window -> rfft~ -> magnitude (sqrt~), phase in turns (the original's atan(min/max) cubic plus octant
    reflections, built from abs~/min~/max~ with clip~ steps, because old vanilla has no atan2~ or >~), and true
    frequency in bins from the frame-to-frame phase advance. Write-back store sp_M0/F0/P0: freeze holds it, gather
    max-holds it with a decay, and P (frame-centred phase) is live, or advanced at the stored frequency (sealed).
  - pool1..4: max-pooled copies of the store over 2, 4, 8, 16 bins (argmax M, F, P, bin J), switch~ed off unless
    pitched at that search level.
  - syn: unpitched = the store as is. Pitched ([pd pitched], switch~ed off while unpitched) = peak-locked: bin k
    takes the loudest bin J near k/r and renders it at r*F with the window kernel W(k - r*F)/W(J - F) and J's
    centred phase (reseeded 40 ms after Pitch settles, then accumulated). Then the band mask (each bin's gate eased
    over a few frames: de-click), texture, and cos~ + rifft~.
- [pd bands] runs at control rate, one tick per hop: re-roll band targets, smooth the band gains, threshold them by
  mean + (0.5 - probability) * spread, and write the per-band gains (sp_effL/R) that syn reads per bin through
  sp_L, the log band coordinate (+ the drift offset).
- Post: tape delay (alt layer), dry/wet with the dry delayed to match the STFT latency, soft clip.
"""

import math

from gloop import press
from glitch import chain, rnd

SR = 48000
N = 2048                       # FFT size
HOP = N // 4                   # overlap 4
FR = SR / HOP                  # frames (and band ticks) per second: 93.75
TICK_MS = 1000 / FR            # 10.667
NB = 128                       # band gain tables (the original's kMaxBands)
LOWMERGE = int(190 * N / SR)   # bins <= this (~190 Hz) share band 0 (8 at N = 2048)
LAT_MS = (N - 64) * 1000 / SR  # STFT latency (reblocking: N minus the parent block), measured offline
BIG = "1e+30"                  # step(x) = clip~(x * BIG, 0, 1)
LEVELS = 5                     # store + max-pooled levels of 2, 4, 8, 16 bins (pitch peak search, to -36 st)
DECLICK = 0.35                 # per-frame easing of each bin's band gate (0.35: ~95% in 7 frames = 75 ms)
WN = 513                       # sp_W: sine-window kernel |W(d)|, d = (i - 256)/64 (+1/128), main lobe only

# alt-layer defaults (the module only sends alt values while Source is held)
ALT_DEF = dict(start_alt=0.0, size_alt=0.5, window_alt=0.5, overlap_alt=0.5, density_alt=0.3, blend_alt=0.0)


def decay_of(a):
    """size_alt -> per-frame gather decay: -60 dB in 1 s .. 60 s (exponential)."""
    return math.exp(-6.9078 / (math.exp(a * math.log(60)) * FR))


def op(c, x, y, text, a=None, b=None):
    """Object with a -> inlet 0 and b -> inlet 1 (each an object id or (id, outlet))."""
    n = c.obj(x, y, text)
    for src, inl in ((a, 0), (b, 1)):
        if src is not None:
            s, o = src if isinstance(src, tuple) else (src, 0)
            c.connect(s, o, n, inl)
    return n


def fl(c, x, y, text, a, rname):
    """[text] (an argful ~ object, so its right inlet takes floats) with [r rname] into the right inlet."""
    n = op(c, x, y, text, a)
    r = c.obj(x + 70, y - 22, f"r {rname}")
    c.connect(r, 0, n, 1)
    return n


def step(c, x, y, a, k=BIG):
    """1 where a*k > 0 else 0 (old Pd has no >~)."""
    return op(c, x, y + 22, "clip~ 0 1", op(c, x, y, f"*~ {k}", a))


def lerp(c, x, y, a, b, rname):
    """a + t*(b - a), t from [r rname] (a float)."""
    d = op(c, x, y, "-~", b, a)
    m = fl(c, x, y + 22, "*~ 0", d, rname)
    return op(c, x, y + 44, "+~", a, m)


def pickup(c, x, y, knob, dst, convert):
    """Alt knob -> [s dst] only after it moves 0.02 from where it was when its stream (re)started (alt values only
    stream while Source is held, and the first ones are the stored values). A jump > 0.2 (alt reset) re-baselines.
    Same logic as gloop.takeover, for one destination."""
    r = c.obj(x, y, f"r {knob}")
    t = c.obj(x, y + 22, "t f f b f")
    last = c.obj(x + 120, y + 44, "f")
    diff = c.obj(x + 60, y + 44, "-")
    ab = c.obj(x + 60, y + 66, "abs")
    mj = c.obj(x + 60, y + 88, "moses 0.2")
    gt = c.obj(x + 60, y + 110, "> 0.02")
    s1 = c.obj(x + 60, y + 132, "sel 1")
    opn = c.msg(x + 60, y + 154, "1")
    spg = c.obj(x, y + 176, "spigot")
    c.connect(r, 0, t, 0)
    c.connect(t, 3, last, 1)
    c.connect(t, 1, diff, 0)
    c.connect(diff, 0, ab, 0)
    c.connect(ab, 0, mj, 0)
    c.connect(mj, 0, gt, 0)
    c.connect(gt, 0, s1, 0)
    c.connect(s1, 0, opn, 0)
    c.connect(opn, 0, spg, 1)
    c.connect(t, 0, spg, 0)
    rb = c.obj(x + 170, y + 88, "t b b")
    rbz = c.msg(x + 170, y + 110, "0")
    c.connect(mj, 1, rb, 0)
    c.connect(rb, 1, last, 0)
    c.connect(last, 0, diff, 1)
    c.connect(rb, 0, rbz, 0)
    c.connect(rbz, 0, spg, 1)
    tb = c.obj(x + 230, y + 22, "t b b")
    tm = c.obj(x + 230, y + 44, "timer")
    c.connect(t, 2, tb, 0)
    c.connect(tb, 1, tm, 1)
    c.connect(tb, 0, tm, 0)
    idl = c.obj(x + 230, y + 66, "> 150")
    si = c.obj(x + 230, y + 88, "sel 1")
    c.connect(tm, 0, idl, 0)
    c.connect(idl, 0, si, 0)
    c.connect(si, 0, rb, 0)
    last_obj = chain(c, x, y + 176, spg, convert + [f"s {dst}"])
    return last_obj


def softclip(c, x, y, a, knee=0.7):
    """Linear to +-knee, then c + e*room/(room + |e|): approaches +-1 without ever pinning (as the original's
    SoftClipOut). Returns the output object."""
    room = 1 - knee
    cl = op(c, x, y, f"clip~ -{knee:g} {knee:g}", a)
    e = op(c, x + 100, y + 22, "-~", a, cl)
    den = chain(c, x + 160, y + 22, op(c, x + 160, y + 44, "abs~", e), [f"+~ {room:g}"])
    q = op(c, x + 100, y + 88, "/~", op(c, x + 100, y + 66, f"*~ {room:g}", e), den)
    return op(c, x, y + 110, "+~", cl, q)


