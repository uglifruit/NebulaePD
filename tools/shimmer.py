def sig(c, x, y, rname, ms=50):
    """[r rname] -> [pack f ms] -> [line~]."""
    return chain(c, x, y, c.obj(x, y, f"r {rname}"), [f"pack f {ms}", "line~"])


def watch(c, x, y, names, comp):
    """Each [r n] stores its value in [v n_v], then bangs comp."""
    for i, n in enumerate(names):
        t = op(c, x + i * 100, y + 22, "t b f", c.obj(x + i * 100, y, f"r {n}"))
        c.connect(t, 1, c.obj(x + i * 100 + 40, y + 44, f"v {n}_v"), 0)
        c.connect(t, 0, comp, 0)


def taps(c, x, y, frecv, dname):
    """Rotating two-tap pitch shifter reading delay dname; phasor rate from [r frecv] = (1 - ratio) * 1000/W."""
    ph = op(c, x, y + 22, "phasor~", c.obj(x, y, f"r {frecv}"))
    q = op(c, x + 120, y + 66, "wrap~", op(c, x + 120, y + 44, "+~ 0.5", ph))
    da = op(c, x, y + 110, f"vd~ {dname}", op(c, x, y + 88, "+~ 1.5", op(c, x, y + 66, f"*~ {W:g}", ph)))
    db = op(c, x + 120, y + 132, f"vd~ {dname}", op(c, x + 120, y + 110, "+~ 1.5", op(c, x + 120, y + 88, f"*~ {W:g}", q)))
    cs = op(c, x + 240, y + 44, "cos~", ph)
    ga = op(c, x + 240, y + 88, "+~ 0.5", op(c, x + 240, y + 66, "*~ -0.5", cs))
    gb = op(c, x + 320, y + 88, "+~ 0.5", op(c, x + 320, y + 66, "*~ 0.5", cs))
    return op(c, x, y + 176, "+~", op(c, x, y + 154, "*~", da, ga), op(c, x + 120, y + 154, "*~", db, gb))


def allpass(c, x, y, a, name, ms, g):
    """Schroeder allpass: w = a + g*w[-D], out = w[-D] - g*w."""
    dl = c.obj(x + 120, y, f"delread~ {name} {ms:g}")
    w = op(c, x, y + 22, "+~", a, op(c, x + 120, y + 22, f"*~ {g:g}", dl))
    c.connect(w, 0, c.obj(x + 200, y + 66, f"delwrite~ {name} {ms + 10:g}"), 0)
    return op(c, x, y + 66, "+~", dl, op(c, x + 60, y + 44, f"*~ {-g:g}", w))


