"""07_shimmer: a Strymon-style shimmer reverb for the Nebulae.

Generated by tools/gen.py. Design notes: docs/SHIMMER.md. User guide: patches/07_shimmer_README.md.

Signal flow
  adc~ -> [swell] -> low cut -> pre-delay -> (+ shimmer) -> 4-stage allpass diffuser -> 8-line FDN tank
  tank lines 0/1 (one per side) -> pitch shifter (voices A + B) -> shimmer LP -> low cut -> back into the diffuser
  tank out -> [chorus] -> x wet gain x duck x clear -> + dry -> soft clip -> dac~

- Tank: 8 delay lines (vd~, lengths TANK_MS x room scale, each slowly modulated), one-pole damping, per-line gain
  10^(-3 L/RT60), mixed by an 8x8 Hadamard (3 butterfly stages, /sqrt 8), soft-clipped at each write.
- Loop shimmer (Source off): lines 0 and 1 hand a share sin(theta) of their energy to the shifter (their own
  feedback keeps cos(theta)), and the shifted signal comes back through the diffuser into all 8 lines at 0.5 each.
  The shifted energy replaces at most what was taken out, so the loop gain never exceeds the reverb's own.
  Every pass climbs another interval, as in the BigSky / blueSky shimmer.
- Pre shimmer (Source on): the shifter takes the input instead, and the reverb gets cos(phi)*dry + sin(phi)*shifted.
- Pitch shifter: two-tap rotating delay (W ms), sin^2 windows, no makeup gain (power 0.5..1 per pass, never > 1).
- Freeze: input muted, tank gain 1, no damping, loop shimmer paused (an exact hold).
"""

import math

