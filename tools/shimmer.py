def reverb(Canvas):
    """Low cut -> pre-delay -> (+ shimmer) -> diffuser -> FDN tank with the shifter on lines 0/1. One canvas: a
    subpatch is sorted as a unit, so the tank/shifter loop must not cross subpatch boundaries."""
    c = Canvas("#N canvas 0 50 1800 1100 %NAME% 0;")
    c.text(10, 5, "8-line FDN (Hadamard) + 2-tap pitch shifter in the loop. See docs/SHIMMER.md.")
    lb = c.obj(1500, 5, "loadbang")
    ins = [c.obj(10 + s * 700, 30, "inlet~") for s in (0, 1)]
    pd = sig(c, 1400, 30, "sh_pd", 100)
    g = {n: sig(c, 1400 + (i % 4) * 90, 100 + (i // 4) * 60, f"sh_{n}", 50)
         for i, n in enumerate(["cL", "sL", "cP", "sP", "selz", "selx", "gA", "gB", "nfc"])}
    gl = [sig(c, 10 + i * 180, 480, f"sh_g{i}", 30) for i in range(8)]
    scale = sig(c, 1400, 300, "sh_scale", 300)
    mdep = sig(c, 1500, 300, "sh_mdep", 100)
    # input: low cut -> pre-delay
    xs = []
    for s in (0, 1):
        x0 = 10 + s * 700
        h = fl(c, x0, 80, "hip~ 80", ins[s], "sh_lc")
        c.connect(h, 0, c.obj(x0, 110, f"delwrite~ sh_pre{s} 1100"), 0)
        xs.append(op(c, x0 + 150, 140, f"vd~ sh_pre{s}", pd))
    # tank reads (modulated), damping
    rd, z = [], []
    for i in range(8):
        xi = 10 + i * 180
        osc = op(c, xi, 300, "osc~", chain(c, xi, 256, c.obj(xi, 256, "r sh_mrate"), [f"* {MODK[i]}"]))
        ph = c.msg(xi + 60, 278, f"{i / 8:g}")
        c.connect(lb, 0, ph, 0)
        c.connect(ph, 0, osc, 1)
        t = op(c, xi, 344, "+~", op(c, xi, 322, f"*~ {TANK_MS[i]}", scale), op(c, xi + 60, 322, "*~", osc, mdep))
        r = op(c, xi, 366, f"vd~ sh_t{i}", t)
        rd.append(r)
        z.append(fl(c, xi, 410, "lop~ 7000", r, "sh_damp"))
    # shifter on lines 0/1 (Loop) or the input (Pre)
    T = []
    for s in (0, 1):
        x0 = 10 + s * 700
        si = op(c, x0, 640, "+~", op(c, x0, 620, "*~", z[s], g["selz"]), op(c, x0 + 80, 620, "*~", xs[s], g["selx"]))
        c.connect(si, 0, c.obj(x0, 662, f"delwrite~ sh_sh{s} 120"), 0)
        a = taps(c, x0, 690, f"sh_fA{s}", f"sh_sh{s}")
        b = taps(c, x0 + 360, 690, f"sh_fB{s}", f"sh_sh{s}")
        sm = op(c, x0, 900, "+~", op(c, x0, 878, "*~", a, g["gA"]), op(c, x0 + 360, 878, "*~", b, g["gB"]))
        T.append(fl(c, x0, 950, "hip~ 80", fl(c, x0, 922, "lop~ 6000", sm, "sh_stone"), "sh_lc"))
    # feedback: lines 0/1 keep cos(theta) of themselves; all lines x g_i, then Hadamard
    fb = []
    for i in range(8):
        xi = 10 + i * 180
        f = op(c, xi, 440, "*~", z[i], g["cL"]) if i < 2 else z[i]
        fb.append(op(c, xi, 530, "*~", f, gl[i]))
    v = fb
    for st, step in enumerate((1, 2, 4)):
        nv = [None] * 8
        for a in range(8):
            if a & step == 0:
                b = a + step
                nv[a] = op(c, 10 + a * 180, 1000 + st * 30, "+~", v[a], v[b])
                nv[b] = op(c, 10 + b * 180, 1000 + st * 30, "-~", v[a], v[b])
        v = nv
    # diffuser input: x * GIN * cP * nfc + T * (sqrt2 * sL * g_s + GIN * sP * nfc)
    u = []
    gx = op(c, 1400, 420, f"*~ {GIN}", op(c, 1400, 400, "*~", g["cP"], g["nfc"]))
    gp = op(c, 1500, 420, f"*~ {GIN}", op(c, 1500, 400, "*~", g["sP"], g["nfc"]))
    for s in (0, 1):
        x0 = 10 + s * 700
        gt = op(c, x0 + 300, 1140, "+~", op(c, x0 + 300, 1120, "*~ 1.41421",
                                            op(c, x0 + 300, 1100, "*~", g["sL"], gl[s])), gp)
        d = op(c, x0, 1180, "+~", op(c, x0, 1160, "*~", xs[s], gx), op(c, x0 + 100, 1160, "*~", T[s], gt))
        for k, (ms, gg) in enumerate(AP):
            d = allpass(c, x0, 1210 + k * 90, d, f"sh_ap{s}{k}", ms * (AP_R if s else 1), gg)
        u.append(d)
    # inject (lines of the same parity as the side), soft clip, write
    for i in range(8):
        xi = 10 + i * 180
        w = op(c, xi, 1600, "+~", v[i], u[i % 2])
        c.connect(softclip(c, xi, 1630, w), 0, c.obj(xi, 1760, f"delwrite~ sh_t{i} 250"), 0)
    # out: OUTG * (sum of the 4 reads per side)
    for s in (0, 1):
        x0 = 10 + s * 700
        a = op(c, x0, 1800, "+~", rd[s], rd[s + 2])
        b = op(c, x0 + 80, 1800, "+~", rd[s + 4], rd[s + 6])
        o = op(c, x0, 1844, f"*~ {OUTG}", op(c, x0, 1822, "+~", a, b))
        c.connect(o, 0, c.obj(x0, 1866, "outlet~"), 0)
    return c


def chorus(Canvas):
    """3-voice ensemble per side: out = in * cw + (sum of voices)/sqrt3 * cc."""
    c = Canvas("#N canvas 0 50 900 500 %NAME% 0;")
    lb = c.obj(800, 5, "loadbang")
    cdep, cw, cc = (sig(c, 600 + i * 90, 30, n, ms) for i, (n, ms) in
                    enumerate([("sh_cdep", 100), ("sh_cw", 50), ("sh_cc", 50)]))
    for s in (0, 1):
        x0 = 10 + s * 400
        inl = c.obj(x0, 30, "inlet~")
        c.connect(inl, 0, c.obj(x0, 60, f"delwrite~ sh_ch{s} 40"), 0)
        tot = None
        for k, ms in enumerate(CHO_MS):
            xk = x0 + k * 120
            osc = op(c, xk, 140, "osc~", chain(c, xk, 96, c.obj(xk, 96, "r sh_mrate"), [f"* {CHOK[k]}"]))
            ph = c.msg(xk + 60, 118, f"{(k / 3 + 0.5 * s) % 1:.4f}")
            c.connect(lb, 0, ph, 0)
            c.connect(ph, 0, osc, 1)
            vd = op(c, xk, 206, f"vd~ sh_ch{s}", op(c, xk, 184, f"+~ {ms:g}", op(c, xk, 162, "*~", osc, cdep)))
            tot = vd if tot is None else op(c, xk, 228, "+~", tot, vd)
        wet = op(c, x0 + 100, 272, "*~", op(c, x0 + 100, 250, "*~ 0.57735", tot), cc)
        o = op(c, x0, 294, "+~", op(c, x0, 272, "*~", inl, cw), wet)
        c.connect(o, 0, c.obj(x0, 320, "outlet~"), 0)
    return c


def duck(Canvas):
    """Dry input envelope -> wet gain 1 - dk * min(1, 4 rms); fast down (15 ms), slow up (350 ms)."""
    c = Canvas("#N canvas 0 50 600 500 %NAME% 0;")
    a = op(c, 10, 60, "+~", c.obj(10, 30, "inlet~"), c.obj(100, 30, "inlet~"))
    e = chain(c, 10, 82, op(c, 10, 82, "*~ 0.5", a), ["env~ 1024 512", "dbtorms", "* 4", "min 1"])
    m = op(c, 10, 192, "*", e, c.obj(80, 170, "r sh_dk"))
    t = op(c, 10, 236, "t f f f", chain(c, 10, 192, m, ["* -1", "+ 1"]))
    lt = op(c, 200, 258, "<", (t, 2))
    c.connect(t, 0, lt, 1)                       # previous value (set after the compare)
    sl = op(c, 200, 280, "sel 1 0", lt)
    pk = c.obj(10, 330, "pack f 350")
    for k, ms in enumerate((15, 350)):
        mm = c.msg(200 + k * 50, 302, str(ms))
        c.connect(sl, k, mm, 0)
        c.connect(mm, 0, pk, 1)
    c.connect(t, 1, pk, 0)
    ln = op(c, 10, 352, "line~", pk)
    one = c.msg(100, 330, "1")
    c.connect(c.obj(100, 308, "loadbang"), 0, one, 0)
    c.connect(one, 0, ln, 0)
    c.connect(ln, 0, c.obj(10, 380, "outlet~"), 0)
    return c


def swell(Canvas):
    """Record latch: the reverb input fades in over 1 s at each onset (re-armed after 150 ms below -50 dB)."""
    c = Canvas("#N canvas 0 50 700 500 %NAME% 0;")
    il, ir = c.obj(10, 30, "inlet~"), c.obj(400, 30, "inlet~")
    ln = c.obj(300, 360, "line~")
    one = c.msg(500, 302, "1")
    c.connect(c.obj(500, 280, "loadbang"), 0, one, 0)
    c.connect(one, 0, ln, 0)
    e = chain(c, 10, 82, op(c, 10, 82, "*~ 0.5", op(c, 10, 60, "+~", il, ir)), ["env~ 1024 512"])
    sp = op(c, 10, 150, "spigot", e, c.obj(80, 128, "r sh_swell"))
    m1 = op(c, 10, 172, "moses 50", sp)
    m2 = op(c, 100, 194, "moses 55", (m1, 1))
    ch = c.obj(10, 240, "change")
    off = c.msg(10, 216, "0")
    c.connect(m1, 0, off, 0)
    c.connect(off, 0, ch, 0)
    on = c.msg(150, 216, "1")
    c.connect(m2, 1, on, 0)
    c.connect(on, 0, ch, 0)
    sl = op(c, 10, 262, "sel 0 1", ch)
    dl = op(c, 10, 284, "delay 150", (sl, 0))
    rel = c.msg(10, 306, "0 80")
    c.connect(dl, 0, rel, 0)
    c.connect(rel, 0, ln, 0)
    t1 = op(c, 120, 284, "t b b", (sl, 1))
    stp = c.msg(200, 306, "stop")
    c.connect(t1, 1, stp, 0)
    c.connect(stp, 0, dl, 0)
    att = c.msg(120, 306, "1 1000")
    c.connect(t1, 0, att, 0)
    c.connect(att, 0, ln, 0)
    # enable / disable
    se = op(c, 400, 260, "sel 0 1", chain(c, 400, 216, c.obj(400, 216, "r sh_swell"), ["change"]))
    for k, txt in enumerate(("1 20", "0 50")):     # on = armed at 0: the next onset swells in
        mm = c.msg(400 + k * 80, 290, txt)
        c.connect(se, k, mm, 0)
        c.connect(mm, 0, ln, 0)
    rst = c.msg(560, 290, "set 0")                 # so input already playing counts as an onset
    c.connect(se, 1, rst, 0)
    c.connect(rst, 0, ch, 0)
    for s, inl in enumerate((il, ir)):
        c.connect(op(c, 10 + s * 400, 400, "*~", inl, ln), 0, c.obj(10 + s * 400, 430, "outlet~"), 0)
    return c


def test_source(Canvas):
    """Test input: 440 Hz (sh_tfreq) burst 0.3 s at 0.5 (sh_tburst bang), noise burst (sh_tnoise bang), sustained
    sine at amplitude [r sh_tsin]. Same on both outlets."""
    c = Canvas("#N canvas 0 50 600 400 %NAME% 0;")
    osc = op(c, 10, 30, "osc~ 440", c.obj(10, 8, "r sh_tfreq"))
    env = []
    for k, rn in enumerate(("sh_tburst", "sh_tnoise")):
        m = c.msg(150 + k * 150, 30, "0.5 5 \\, 0 20 300")
        c.connect(c.obj(150 + k * 150, 8, f"r {rn}"), 0, m, 0)
        env.append(op(c, 150 + k * 150, 52, "vline~", m))
    sn = sig(c, 450, 8, "sh_tsin", 5)
    bs = op(c, 10, 120, "*~", osc, op(c, 150, 90, "+~", env[0], sn))
    nz = op(c, 300, 120, "*~", c.obj(300, 90, "noise~"), env[1])
    tot = op(c, 10, 150, "+~", bs, nz)
    c.connect(tot, 0, c.obj(10, 180, "outlet~"), 0)
    c.connect(tot, 0, c.obj(100, 180, "outlet~"), 0)
    return c


def shimmer_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "07_shimmer: Strymon-style shimmer reverb (8-line FDN + pitch shifter in the loop). "
                  "See docs/SHIMMER.md.")
    c.text(10, 20, "blend=mix size=decay window=tone start=pre-delay density=shimmer overlap=mod pitch=voice A "
                   "speed=voice B. Freeze=hold File(held)=hold Source=pre/loop Record=swell Reset=clear.")
    c.text(10, 35, "Alt: start=low cut size=room density=shimmer tone overlap=mod rate window=A/B blend=duck "
                   "pitch=detune.")
    c.sub(10, 60, "nebulae_controls", controls_canvas())
    c.sub(150, 60, "ui", ui(Canvas))
    adc = c.sub(10, 100, "testsrc", test_source(Canvas)) if test else c.obj(10, 100, "adc~ 1 2")
    sw = c.sub(10, 140, "swell", swell(Canvas))
    rv = c.sub(10, 170, "reverb", reverb(Canvas))
    ch = c.sub(10, 200, "chorus", chorus(Canvas))
    dk = c.sub(200, 140, "duck", duck(Canvas))
    for s in (0, 1):
        c.connect(adc, s, sw, s)
        c.connect(sw, s, rv, s)
        c.connect(rv, s, ch, s)
        c.connect(adc, s, dk, s)
    gw = sig(c, 400, 100, "sh_gw", 30)
    gd = sig(c, 500, 100, "sh_gd", 30)
    clw = op(c, 600, 122, "line~", c.obj(600, 100, "r sh_clrw"))
    wg = op(c, 400, 200, "*~", op(c, 400, 178, "*~", gw, clw), dk)
    outs = []
    for s, x in [(0, 10), (1, 220)]:
        o = op(c, x, 260, "+~", op(c, x, 238, "*~", (adc, s), gd), op(c, x + 100, 238, "*~", (ch, s), wg))
        outs.append(softclip(c, x, 290, o))
    dac = c.obj(10, 420, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        lb = c.obj(600, 340, "loadbang")
        steps_ = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps_):
            if wav and "pd quit" in msg:
                msg = "\\; sh_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 365 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 387 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            # record into tables and save at quit: writesf~ drops audio in fast -batch runs (its disk thread lags)
            n = int(max(ms for ms, _ in steps_) * SR / 1000)
            for ch_, x in [(0, 10), (1, 200)]:
                side = "lr"[ch_]
                c.obj(x, 500, f"table sh_rec{side} {n}")
                tw = c.obj(x, 470, f"tabwrite~ sh_rec{side}")
                c.connect(outs[ch_], 0, tw, 0)
                c.connect(lb, 0, tw, 0)        # starts with DSP: WAV time 0 = DSP start
            rs = c.obj(400, 470, "r sh_save")
            wm2 = c.msg(400, 492, f"write -bytes 4 {wav} sh_recl sh_recr")
            sf = c.obj(400, 514, "soundfiler")
            c.connect(rs, 0, wm2, 0)
            c.connect(wm2, 0, sf, 0)
    return c
