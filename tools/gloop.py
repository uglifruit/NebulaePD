def gloop_patch(Canvas, controls_canvas, test_source=None, level_printer=None, test=None):
    c = Canvas("#N canvas 0 50 1100 650 10;")
    c.text(10, 5, "03_gloop: 4-play-head looper after Cutlasses Gloop. See docs/GLOOP.md for the control map.")
    c.text(10, 20, "Record=rec/overdub. File/Source/Reset/Freeze = select head 1-4. Knobs edit the selected head after you move them.")
    c.text(10, 35, "Hold Source: start/size/density/overlap = head 1-4 volume. blend_alt=degrade window_alt=wobble. Alt Record=clear. Alt File=grid.")
    c.sub(10, 60, "nebulae_controls", controls_canvas())
    c.obj(200, 60, f"table gl_bufl {BUF}")
    c.obj(400, 60, f"table gl_bufr {BUF}")
    c.sub(10, 90, "ui", controls_ui(Canvas))
    c.sub(10, 115, "knobs", knobs_heads(Canvas))
    c.sub(10, 140, "recorder", recorder(Canvas))
    c.sub(10, 165, "writer", writer(Canvas))
    c.sub(10, 190, "wobble", wobble(Canvas))
    for n in range(1, 5):
        c.sub(200 + (n - 1) * 90, 190, f"head{n}", head(Canvas, n))
    # input -> send~ for the writer
    adc = c.sub(10, 240, "testsrc", blip_source(Canvas)) if test else c.obj(10, 240, "adc~ 1 2")
    sl = c.obj(10, 270, "send~ gl_inl")
    sr = c.obj(120, 270, "send~ gl_inr")
    c.connect(adc, 0, sl, 0)
    c.connect(adc, 1, sr, 0)
    # mix: dry*(1-wet) + heads*wet
    rw = c.obj(400, 240, "r gl_wet")
    pk = c.obj(400, 262, "pack f 20")
    wet = c.obj(400, 284, "line~")
    c.connect(rw, 0, pk, 0)
    c.connect(pk, 0, wet, 0)
    di = c.obj(500, 306, "*~ -1")
    dry = c.obj(500, 328, "+~ 1")
    c.connect(wet, 0, di, 0)
    c.connect(di, 0, dry, 0)
    outs = []
    for ch, (side, x) in enumerate([("l", 10), ("r", 220)]):
        ca = c.obj(x, 360, f"catch~ gl_out{side}")
        hm = c.obj(x, 385, "*~ 0.7")
        c.connect(ca, 0, hm, 0)
        wm = c.obj(x, 410, "*~")
        c.connect(hm, 0, wm, 0)
        c.connect(wet, 0, wm, 1)
        dm = c.obj(x + 100, 410, "*~")
        c.connect(adc, ch, dm, 0)
        c.connect(dry, 0, dm, 1)
        sm = c.obj(x, 440, "+~")
        c.connect(wm, 0, sm, 0)
        c.connect(dm, 0, sm, 1)
        cl = c.obj(x, 465, "clip~ -1 1")
        c.connect(sm, 0, cl, 0)
        outs.append(cl)
    dac = c.obj(10, 500, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        level_printer(c, 10, 540, outs[0], "L")
        steps = test.get("steps", [])
        lb = c.obj(600, 500, "loadbang")
        for i, (ms, msg) in enumerate(steps):
            d = c.obj(600 + (i % 4) * 120, 525 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 547 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if test.get("wav"):
            wsf = c.obj(10, 600, "writesf~ 2")
            c.connect(outs[0], 0, wsf, 0)
            c.connect(outs[1], 0, wsf, 1)
            wd = c.obj(200, 580, "delay 1")
            wm2 = c.msg(200, 600, f"open -bytes 4 {test['wav']} \\, start")
            c.connect(lb, 0, wd, 0)
            c.connect(wd, 0, wm2, 0)
            c.connect(wm2, 0, wsf, 0)
    return c
