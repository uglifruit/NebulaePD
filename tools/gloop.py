"""03_gloop: a functional take on Cutlasses Gloop (4-play-head performance looper) for the Nebulae.

Generated by tools/gen.py. Design notes and control map: docs/GLOOP.md.

Engine
- Stereo buffer [table gl_bufl/gl_bufr], 2 minutes at 48 kHz.
- Write loop: an rpole~ sample counter reads the old sample (tabread~), mixes degrade + overdub input, and tabwrite~
  writes it back. Both restart together on a metro tick at every loop wrap, so read and write stay sample-aligned.
- Each head: phasor~ over its sub-loop. samphold~ latches position, size and jitter at every wrap.
  It reads with tabread4~, applies an edge fade (the crossfade time), volume and pan, then throw~ to the mix.

Controls arrive continuously (the Nebulae resends every value about every ms), so button presses are detected with
[change], and nothing acts on them until 1 s after load, so stored latch states are not mistaken for presses.
"""

SR = 48000
BUF = 120 * SR + 512  # 2 minutes + guard samples for tabread4~
DEBUG_HEAD = 0        # tests: set to a head number to print its phase/index


def press(c, x, y, name, rising_only=False):
    """[r name] -> [change] -> primed spigot (-> [sel 1]); returns the object whose outlet 0 fires on a press."""
    r = c.obj(x, y, f"r {name}")
    ch = c.obj(x, y + 22, "change")
    sp = c.obj(x, y + 44, "spigot")
    rp = c.obj(x + 60, y + 22, "r gl_primed")
    c.connect(r, 0, ch, 0)
    c.connect(ch, 0, sp, 0)
    c.connect(rp, 0, sp, 1)
    if rising_only:
        s1 = c.obj(x, y + 66, "sel 1")
        c.connect(sp, 0, s1, 0)
        return s1
    return sp


def controls_ui(Canvas):
    """Button presses -> head select / record / clear / grid; global knobs -> sends."""
    c = Canvas("#N canvas 0 50 1000 700 %NAME% 0;")
    c.text(10, 5, "Head = 1 + Source + 2*Freeze (their LEDs show it). Record=rec/overdub. Reset=restart heads. File=pause head. "
                  "Alt: Record=clear - File=grid")
    # priming: open the press spigots 1 s after load
    lb = c.obj(800, 30, "loadbang")
    d = c.obj(800, 55, "delay 1000")
    m = c.msg(800, 80, "1")
    sp = c.obj(800, 105, "s gl_primed")
    c.connect(lb, 0, d, 0)
    c.connect(d, 0, m, 0)
    c.connect(m, 0, sp, 0)
    # defaults until the knobs report (the module streams real values straight away)
    dflt = c.msg(600, 55, f"\\; gl_xf {5 * SR // 1000} \\; gl_wet 1 \\; gl_degr 0 \\; gl_wobd 0 \\; gl_grid 0 "
                          f"\\; gl_transp 1")
    c.connect(lb, 0, dflt, 0)
    # head select = 1 + source + 2*freeze, read from the latch states themselves, so the Source and Freeze LEDs
    # always show the selected head (1: both off, 2: Source, 3: Freeze, 4: both) - also after a power cycle.
    rs = c.obj(10, 40, "r source")
    cs = c.obj(10, 62, "change")
    add = c.obj(10, 140, "+ 0")
    c.connect(rs, 0, cs, 0)
    c.connect(cs, 0, add, 0)
    rf = c.obj(120, 40, "r freeze")
    cf = c.obj(120, 62, "change")
    m2 = c.obj(120, 84, "* 2")
    tf = c.obj(120, 106, "t b f")
    c.connect(rf, 0, cf, 0)
    c.connect(cf, 0, m2, 0)
    c.connect(m2, 0, tf, 0)
    c.connect(tf, 1, add, 1)
    c.connect(tf, 0, add, 0)
    c.connect(lb, 0, add, 0)                     # head 1 until the module reports its states
    p1 = c.obj(10, 162, "+ 1")
    chs = c.obj(10, 184, "change")
    ss = c.obj(10, 206, "s gl_sel")
    c.connect(add, 0, p1, 0)
    c.connect(p1, 0, chs, 0)
    c.connect(chs, 0, ss, 0)

    # Reset (+gate): restart all heads. File button: pause/resume the selected head.
    p = press(c, 250, 40, "reset", True)
    s = c.obj(250, 140, "s gl_restart")
    c.connect(p, 0, s, 0)
    p = press(c, 400, 40, "filestate", True)
    fsel = c.obj(400, 140, "f 1")
    rsel = c.obj(460, 118, "r gl_sel")
    c.connect(rsel, 0, fsel, 1)
    c.connect(p, 0, fsel, 0)
    rt = c.obj(400, 162, "route 1 2 3 4")
    c.connect(fsel, 0, rt, 0)
    for h in range(4):
        s = c.obj(400 + h * 70, 184, f"s h{h + 1}_pause")
        c.connect(rt, h, s, 0)

    # record / overdub
    # (each toggle of the latching value is one press; send a bang, not the 0/1 state)
    for x, src, dst in [(10, "record", "gl_press_rec"), (160, "record_alt", "gl_clear")]:
        p = press(c, x, 220, src)
        tb = c.obj(x, 290, "t b")
        b = c.obj(x, 312, f"s {dst}")
        c.connect(p, 0, tb, 0)
        c.connect(tb, 0, b, 0)
    # grid: file_alt cycles 0..3 -> off/4/8/16
    r = c.obj(310, 220, "r file_alt")
    ch = c.obj(310, 242, "change")
    sel = c.obj(310, 264, "sel 0 1 2 3")
    c.connect(r, 0, ch, 0)
    c.connect(ch, 0, sel, 0)
    sg = c.obj(310, 320, "s gl_grid")
    for j, g in enumerate([0, 4, 8, 16]):
        mg = c.msg(310 + j * 35, 290, str(g))
        c.connect(sel, j, mg, 0)
        c.connect(mg, 0, sg, 0)

    # alt pots -> head volumes
    for i, name in enumerate(["start_alt", "size_alt", "density_alt", "overlap_alt"]):
        r = c.obj(10 + i * 110, 380, f"r {name}")
        s = c.obj(10 + i * 110, 405, f"s h{i + 1}_vol")
        c.connect(r, 0, s, 0)
    # window -> crossfade 5..1000 ms (exponential), as samples
    r = c.obj(10, 450, "r window")
    a = c.obj(10, 472, "* 5.2983")
    e = c.obj(10, 494, "exp")
    f = c.obj(10, 516, "* 5")
    sm = c.obj(10, 538, f"* {SR // 1000}")
    s = c.obj(10, 560, "s gl_xf")
    for x1, x2 in [(r, a), (a, e), (e, f), (f, sm), (sm, s)]:
        c.connect(x1, 0, x2, 0)
    # blend -> wet, blend_alt -> degrade, window_alt -> wobble
    for i, (src, dst) in enumerate([("blend", "gl_wet"), ("blend_alt", "gl_degr"), ("window_alt", "gl_wobd")]):
        r = c.obj(200 + i * 120, 450, f"r {src}")
        s = c.obj(200 + i * 120, 475, f"s {dst}")
        c.connect(r, 0, s, 0)
    return c


def takeover(c, x, y, knob, param, convert, idle_ms=None, max_jump=None):
    """Per-knob takeover for the selected head: the knob only drives a head after moving 0.02 from where it was
    when that head was selected. `convert` is a list of object texts (or a builder) applied before sending.
    idle_ms: if no message arrived for this long (e.g. alt values, which only stream while Source is held), the next
             value becomes the new baseline instead of a move.
    max_jump: a change bigger than this in one message (e.g. an alt-reset click) re-baselines instead of moving."""
    r = c.obj(x, y, f"r {knob}")
    t = c.obj(x, y + 22, "t f f b f" if idle_ms else "t f f f")
    last_out = 3 if idle_ms else 2
    last = c.obj(x + 120, y + 44, "f")           # last knob value (cold)
    diff = c.obj(x + 60, y + 44, "-")             # v - snapshot
    ab = c.obj(x + 60, y + 66, "abs")
    gt = c.obj(x + 60, y + 88, "> 0.02")
    s1 = c.obj(x + 60, y + 110, "sel 1")
    opn = c.msg(x + 60, y + 132, "1")
    spg = c.obj(x, y + 154, "spigot")
    c.connect(r, 0, t, 0)
    c.connect(t, last_out, last, 1)
    c.connect(t, 1, diff, 0)
    c.connect(diff, 0, ab, 0)
    c.connect(gt, 0, s1, 0)
    c.connect(s1, 0, opn, 0)
    c.connect(opn, 0, spg, 1)
    c.connect(t, 0, spg, 0)
    # re-baseline: snapshot := current value, close the spigot
    rb = c.obj(x + 200, y + 66, "t b b")
    rbz = c.msg(x + 200, y + 88, "0")
    c.connect(rb, 1, last, 0)
    c.connect(rb, 0, rbz, 0)
    c.connect(rbz, 0, spg, 1)
    if max_jump:
        mj = c.obj(x + 60, y + 66 + 11, f"moses {max_jump}")
        c.connect(ab, 0, mj, 0)
        c.connect(mj, 0, gt, 0)
        c.connect(mj, 1, rb, 0)
    else:
        c.connect(ab, 0, gt, 0)
    if idle_ms:
        tb = c.obj(x + 260, y + 22, "t b b")
        tm = c.obj(x + 260, y + 44, "timer")
        c.connect(t, 2, tb, 0)
        c.connect(tb, 1, tm, 1)
        c.connect(tb, 0, tm, 0)
        idl = c.obj(x + 260, y + 66, f"> {idle_ms}")
        si = c.obj(x + 260, y + 88, "sel 1")
        c.connect(tm, 0, idl, 0)
        c.connect(idl, 0, si, 0)
        c.connect(si, 0, rb, 0)
    prev = spg
    yy = y + 176
    if callable(convert):
        conv_in, conv_out, yy = convert(c, x, yy)
        c.connect(prev, 0, conv_in, 0)
        prev = conv_out
    else:
        for txt in convert:
            o = c.obj(x, yy, txt)
            c.connect(prev, 0, o, 0)
            prev = o
            yy += 22
    lp = c.obj(x, yy, "list prepend 1")
    c.connect(prev, 0, lp, 0)
    rt = c.obj(x, yy + 22, "route 1 2 3 4")
    c.connect(lp, 0, rt, 0)
    for h in range(4):
        s = c.obj(x + h * 0, yy + 44 + h * 22, f"s h{h + 1}_{param}")
        c.connect(rt, h, s, 0)
    # on head select: set prefix, snapshot the knob, close the spigot
    rs = c.obj(x + 180, y, "r gl_sel")
    ts = c.obj(x + 180, y + 22, "t b b f")
    c.connect(rs, 0, ts, 0)
    c.connect(ts, 2, lp, 1)
    c.connect(ts, 1, last, 0)
    c.connect(last, 0, diff, 1)
    cls = c.msg(x + 180, y + 132, "0")
    c.connect(ts, 0, cls, 0)
    c.connect(cls, 0, spg, 1)


def knobs_heads(Canvas):
    """Primary knobs -> parameters of the selected head (with takeover)."""
    c = Canvas("#N canvas 0 50 1400 600 %NAME% 0;")
    c.text(10, 5, "Selected-head knobs (takeover): start=pos size=size density=jitter overlap=pan speed=rate. "
                  "pitch_alt=interval. pitch (+1V/oct) = transpose ALL heads")
    takeover(c, 10, 30, "start", "pos", [])
    takeover(c, 240, 30, "size", "size", [])
    takeover(c, 470, 30, "density", "jit", [])
    takeover(c, 700, 30, "overlap", "pan", [])
    # speed: Nebulae curve. 0.5 = stop, 0.625 = x1 fwd, 0.375 = x1 rev, ends = x4.
    takeover(c, 930, 30, "speed", "spd", spd2rate)
    # Source + Pitch: interval of the selected head, semitones = round(pitch_alt*48) - 24 (0.5 = unison, +-2 oct).
    # Alt values only stream while Source is held: re-baseline after 150 ms of silence; ignore reset-click jumps.
    takeover(c, 1160, 30, "pitch_alt", "pit", ["* 48", "+ 0.5", "int", "- 24", "* 0.057762", "exp"],
             idle_ms=150, max_jump=0.2)
    # Pitch encoder + 1V/oct: transpose ALL heads, semitones = round(pitch*60) - 36 (click 0.6 = unison)
    x, y = 1450, 30
    prev = c.obj(x, y, "r pitch")
    for txt in ["* 60", "+ 0.5", "int", "- 36", "change", "* 0.057762", "exp", "s gl_transp"]:
        y += 22
        o = c.obj(x, y, txt)
        c.connect(prev, 0, o, 0)
        prev = o
    return c


def spd2rate(c, x, y):
    """speed 0..1 -> signed rate. |d| = |speed-0.5|: <=0.125 linear 0..1, above exponential 1..4."""
    sub = c.obj(x, y, "- 0.5")
    tt = c.obj(x, y + 22, "t f f")
    sg1 = c.obj(x + 100, y + 44, "< 0")
    sg2 = c.obj(x + 100, y + 66, "* -2")
    sg3 = c.obj(x + 100, y + 88, "+ 1")
    ab = c.obj(x, y + 44, "abs")
    mo = c.obj(x, y + 66, "moses 0.125")
    lin = c.obj(x, y + 88, "* 8")
    ex1 = c.obj(x + 50, y + 88, "- 0.125")
    ex2 = c.obj(x + 50, y + 110, "* 3.69675")
    ex3 = c.obj(x + 50, y + 132, "exp")
    mul = c.obj(x, y + 154, "*")
    c.connect(sub, 0, tt, 0)
    c.connect(tt, 1, sg1, 0)          # sign first (right outlet) -> cold inlet of [*]
    c.connect(sg1, 0, sg2, 0)
    c.connect(sg2, 0, sg3, 0)
    c.connect(sg3, 0, mul, 1)
    c.connect(tt, 0, ab, 0)
    c.connect(ab, 0, mo, 0)
    c.connect(mo, 0, lin, 0)
    c.connect(mo, 1, ex1, 0)
    c.connect(ex1, 0, ex2, 0)
    c.connect(ex2, 0, ex3, 0)
    c.connect(lin, 0, mul, 0)
    c.connect(ex3, 0, mul, 0)
    return sub, mul, y + 176


def recorder(Canvas):
    """Record state machine: 0 empty, 1 recording first loop, 2 looping, 3 overdubbing."""
    c = Canvas("#N canvas 0 50 900 600 %NAME% 0;")
    c.text(10, 5, "Record state: 0 empty -> 1 recording -> 2 looping <-> 3 overdub. Max 120 s. Clear -> 0.")
    rp = c.obj(10, 30, "r gl_press_rec")
    st = c.obj(10, 55, "f 0")
    sel = c.obj(10, 80, "sel 0 1 2 3")
    c.connect(rp, 0, st, 0)
    c.connect(st, 0, sel, 0)
    # 0 -> start first recording
    m0 = c.msg(10, 120, "\\; gl_len 0 \\; gl_keep 0 \\; gl_ingain 1 \\; gl_wstart bang")
    n1 = c.msg(10, 145, "1")
    tm = c.obj(250, 200, "timer")
    dmax = c.obj(250, 120, "delay 120000")
    c.connect(sel, 0, m0, 0)
    c.connect(sel, 0, n1, 0)
    c.connect(n1, 0, st, 1)
    c.connect(sel, 0, tm, 0)
    c.connect(sel, 0, dmax, 0)
    fire = c.obj(250, 145, "s gl_press_rec")
    c.connect(dmax, 0, fire, 0)
    # 1 -> stop: length in whole 64-sample blocks
    stp = c.msg(400, 120, "stop")
    c.connect(sel, 1, stp, 0)
    c.connect(stp, 0, dmax, 0)
    c.connect(sel, 1, tm, 1)
    blocks = c.obj(250, 225, f"* {SR / 1000 / 64:g}")    # ms -> blocks
    bi = c.obj(250, 250, "int")
    bm = c.obj(250, 275, "max 1")
    tl = c.obj(250, 300, "t f f")
    smp = c.obj(250, 325, "* 64")
    lens = c.obj(250, 350, "s gl_len")
    ms = c.obj(350, 325, f"* {64 / (SR / 1000):g}")
    lms = c.obj(350, 350, "s gl_len_ms")
    for a, b in [(tm, blocks), (blocks, bi), (bi, bm), (bm, tl)]:
        c.connect(a, 0, b, 0)
    c.connect(tl, 1, smp, 0)       # samples first...
    c.connect(smp, 0, lens, 0)
    c.connect(tl, 0, ms, 0)        # ...then ms (starts the write metro)
    c.connect(ms, 0, lms, 0)
    m1 = c.msg(10, 200, "\\; gl_keep 1 \\; gl_ingain 0")
    n2 = c.msg(10, 225, "2")
    c.connect(sel, 1, m1, 0)
    c.connect(sel, 1, n2, 0)
    c.connect(n2, 0, st, 1)
    # 2 -> overdub on ; 3 -> overdub off
    m2 = c.msg(10, 300, "\\; gl_ingain 1")
    n3 = c.msg(10, 325, "3")
    c.connect(sel, 2, m2, 0)
    c.connect(sel, 2, n3, 0)
    c.connect(n3, 0, st, 1)
    m3 = c.msg(10, 375, "\\; gl_ingain 0")
    n4 = c.msg(10, 400, "2")
    c.connect(sel, 3, m3, 0)
    c.connect(sel, 3, n4, 0)
    c.connect(n4, 0, st, 1)
    # clear
    rc = c.obj(500, 30, "r gl_clear")
    mc = c.msg(500, 55, "\\; gl_wstop bang \\; gl_len 0 \\; gl_len_ms 0 \\; gl_ingain 0 \\; "
                        "gl_bufl const 0 \\; gl_bufr const 0")
    n0 = c.msg(500, 80, "0")
    c.connect(rc, 0, mc, 0)
    c.connect(rc, 0, n0, 0)
    c.connect(n0, 0, st, 1)
    c.connect(rc, 0, stp, 0)
    return c


def writer(Canvas):
    """Write loop: idx counter + read-old + degrade + overdub input -> tabwrite~, restarted every loop."""
    c = Canvas("#N canvas 0 50 1000 650 %NAME% 0;")
    c.text(10, 5, "Write loop (record / overdub / degrade). Counter and tabwrite~ restart together each wrap.")
    # metro over loop length; 0 stops it
    rl = c.obj(600, 30, "r gl_len_ms")
    mo = c.obj(600, 55, "moses 1")
    stp = c.msg(600, 80, "stop")
    met = c.obj(680, 105, "metro 1000")
    c.connect(rl, 0, mo, 0)
    c.connect(mo, 0, stp, 0)
    c.connect(stp, 0, met, 0)
    tm = c.obj(680, 80, "t b f")
    c.connect(mo, 1, tm, 0)
    c.connect(tm, 1, met, 1)
    c.connect(tm, 0, met, 0)
    sw = c.obj(680, 130, "s gl_wstart")
    c.connect(met, 0, sw, 0)
    # counter
    rw = c.obj(10, 30, "r gl_wstart")
    clr = c.msg(10, 55, "clear")
    one = c.obj(120, 55, "sig~ 1")
    rpole = c.obj(10, 80, "rpole~ 1")
    idx = c.obj(10, 105, "-~ 0.5")   # rpole counts 1,2,3..; tabread~ truncates, so idx = n - 0.5 reads sample n-1
    c.connect(rw, 0, clr, 0)
    c.connect(clr, 0, rpole, 0)
    c.connect(one, 0, rpole, 0)
    c.connect(rpole, 0, idx, 0)
    # gains
    gains = {}
    for i, name in enumerate(["gl_keep", "gl_ingain"]):
        r = c.obj(300 + i * 130, 30, f"r {name}")
        pk = c.obj(300 + i * 130, 55, "pack f 3")
        ln = c.obj(300 + i * 130, 80, "line~")
        c.connect(r, 0, pk, 0)
        c.connect(pk, 0, ln, 0)
        gains[name] = ln
    # degrade: per pass gain g = 1 - 0.3*d, and mix toward a lowpassed copy by d
    rd = c.obj(600, 200, "r gl_degr")
    pk = c.obj(600, 225, "pack f 50")
    dl = c.obj(600, 250, "line~")
    c.connect(rd, 0, pk, 0)
    c.connect(pk, 0, dl, 0)
    gi = c.obj(700, 280, "*~ -0.3")
    g = c.obj(700, 305, "+~ 1")
    c.connect(dl, 0, gi, 0)
    c.connect(gi, 0, g, 0)
    di = c.obj(600, 280, "*~ -1")
    dr = c.obj(600, 305, "+~ 1")      # 1 - d (raw share)
    c.connect(dl, 0, di, 0)
    c.connect(di, 0, dr, 0)
    rws = c.obj(800, 30, "r gl_wstop")
    stopm = c.msg(800, 55, "stop")
    c.connect(rws, 0, stopm, 0)
    for ch, (x, side) in enumerate([(10, "l"), (330, "r")]):
        old = c.obj(x, 160, f"tabread~ gl_buf{side}")
        c.connect(idx, 0, old, 0)
        lp = c.obj(x + 120, 190, "lop~ 3000")
        c.connect(old, 0, lp, 0)
        raw = c.obj(x, 220, "*~")
        c.connect(old, 0, raw, 0)
        c.connect(dr, 0, raw, 1)
        lpm = c.obj(x + 120, 220, "*~")
        c.connect(lp, 0, lpm, 0)
        c.connect(dl, 0, lpm, 1)
        mix = c.obj(x, 250, "+~")
        c.connect(raw, 0, mix, 0)
        c.connect(lpm, 0, mix, 1)
        gg = c.obj(x, 275, "*~")
        c.connect(mix, 0, gg, 0)
        c.connect(g, 0, gg, 1)
        kp = c.obj(x, 300, "*~")
        c.connect(gg, 0, kp, 0)
        c.connect(gains["gl_keep"], 0, kp, 1)
        rin = c.obj(x + 120, 300, f"receive~ gl_in{side}")
        ing = c.obj(x + 120, 325, "*~")
        c.connect(rin, 0, ing, 0)
        c.connect(gains["gl_ingain"], 0, ing, 1)
        sm = c.obj(x, 350, "+~")
        c.connect(kp, 0, sm, 0)
        c.connect(ing, 0, sm, 1)
        cl = c.obj(x, 375, "clip~ -1 1")
        c.connect(sm, 0, cl, 0)
        tw = c.obj(x, 400, f"tabwrite~ gl_buf{side}")
        c.connect(cl, 0, tw, 0)
        c.connect(rw, 0, tw, 0)
        c.connect(stopm, 0, tw, 0)
    return c


def head(Canvas, n):
    """One play head. Params via receives hN_pos/size/jit/pan/spd/pit/vol plus globals."""
    c = Canvas("#N canvas 0 50 1100 700 %NAME% 0;")
    c.text(10, 5, f"Play head {n}: phasor~ over its sub-loop. Position/size/jitter latched each wrap (samphold~).")
    # defaults (alt pots only arrive while Source is held, so start with head 1 up, others muted)
    lb = c.obj(900, 10, "loadbang")
    dm = c.msg(900, 35, f"\\; h{n}_pos 0 \\; h{n}_size 1 \\; h{n}_jit 0 \\; h{n}_pan 0.5 \\; h{n}_spd 1 "
                        f"\\; h{n}_pit 1 \\; h{n}_vol {1 if n == 1 else 0}")
    c.connect(lb, 0, dm, 0)

    # --- control-rate geometry: loop length L, grid G, sub-loop start/size in samples ---
    # gl_len (samples) -> [max 64] -> inverse (for wrapping) and L (for de-normalising)
    rlen = c.obj(10, 30, "r gl_len")
    lmax = c.obj(10, 52, "max 64")
    tlen = c.obj(10, 74, "t f f")
    inv = c.obj(10, 96, "swap 1")
    invd = c.obj(10, 118, "/")
    c.connect(rlen, 0, lmax, 0)
    c.connect(lmax, 0, tlen, 0)
    c.connect(tlen, 1, inv, 0)
    c.connect(inv, 1, invd, 1)       # swap: right outlet (the length) fires first -> divisor
    c.connect(inv, 0, invd, 0)       # then 1 -> 1/L
    # on/off gate: len > 0
    gate_on = c.obj(120, 52, "> 0")
    c.connect(rlen, 0, gate_on, 0)
    gpk = c.obj(120, 74, "pack f 20")
    gln = c.obj(120, 96, "line~")
    c.connect(gate_on, 0, gpk, 0)
    c.connect(gpk, 0, gln, 0)

    # pos/size (0..1) -> optional grid quantise -> samples (* L).
    # Grid G: 0 = off (spigot A passes v straight), else spigot B: int(v*G [+0.5 for size]) / G (size >= 1/G).
    def quant(x, y, rname, is_size):
        r = c.obj(x, y, f"r {rname}")
        v = c.obj(x, y + 22, "f")              # stored value; banged again when G or L changes
        c.connect(r, 0, v, 0)
        tv = c.obj(x, y + 44, "t f f")
        c.connect(v, 0, tv, 0)
        spa = c.obj(x, y + 66, "spigot 1")     # grid off
        spb = c.obj(x + 60, y + 66, "spigot 0")  # grid on
        c.connect(tv, 0, spa, 0)
        c.connect(tv, 1, spb, 0)
        mg = c.obj(x + 60, y + 88, "* 0")
        c.connect(spb, 0, mg, 0)
        prev = mg
        if is_size:
            rnd = c.obj(x + 60, y + 110, "+ 0.5")
            c.connect(prev, 0, rnd, 0)
            prev = rnd
        it = c.obj(x + 60, y + 132, "int")
        c.connect(prev, 0, it, 0)
        prev = it
        if is_size:
            mx = c.obj(x + 60, y + 154, "max 1")
            c.connect(prev, 0, mx, 0)
            prev = mx
        dg = c.obj(x + 60, y + 176, "/ 1")
        c.connect(prev, 0, dg, 0)
        mL = c.obj(x, y + 200, "* 64")
        c.connect(spa, 0, mL, 0)
        c.connect(dg, 0, mL, 0)
        # grid change: set G, open/close spigots, re-evaluate
        rg = c.obj(x + 150, y, "r gl_grid")
        tg = c.obj(x + 150, y + 22, "t b f f f")
        c.connect(rg, 0, tg, 0)
        c.connect(tg, 3, mg, 1)
        c.connect(tg, 3, dg, 1)
        lt1 = c.obj(x + 150, y + 66, "< 1")
        ge1 = c.obj(x + 200, y + 66, ">= 1")
        c.connect(tg, 2, lt1, 0)
        c.connect(tg, 1, ge1, 0)
        c.connect(lt1, 0, spa, 1)
        c.connect(ge1, 0, spb, 1)
        c.connect(tg, 0, v, 0)
        # length change: set L, re-evaluate
        rl = c.obj(x + 150, y + 110, "r gl_len")
        ml = c.obj(x + 150, y + 132, "max 64")
        tl = c.obj(x + 150, y + 154, "t b f")
        c.connect(rl, 0, ml, 0)
        c.connect(ml, 0, tl, 0)
        c.connect(tl, 1, mL, 1)
        c.connect(tl, 0, v, 0)
        return mL

    pos_s = quant(250, 30, f"h{n}_pos", False)
    size_s = quant(500, 30, f"h{n}_size", True)
    # minimum sub-loop 64 samples
    smax = c.obj(500, 310, "max 64")
    c.connect(size_s, 0, smax, 0)
    tsz = c.obj(500, 332, "t f f")
    c.connect(smax, 0, tsz, 0)
    size_sig = c.obj(500, 400, "sig~")
    c.connect(tsz, 0, size_sig, 0)
    pos_sig = c.obj(250, 400, "sig~")
    c.connect(pos_s, 0, pos_sig, 0)

    # rate = spd * pit * wobble; phasor freq = rate * SR / size
    rsp = c.obj(750, 30, f"r h{n}_spd")
    rpi = c.obj(850, 8, f"r h{n}_pit")         # this head's interval ratio
    rtr = c.obj(950, 8, "r gl_transp")         # global transpose ratio (pitch encoder + 1V/oct)
    ptr = c.obj(850, 30, "* 1")
    ttr = c.obj(950, 30, "t b f")
    c.connect(rpi, 0, ptr, 0)
    c.connect(rtr, 0, ttr, 0)
    c.connect(ttr, 1, ptr, 1)
    c.connect(ttr, 0, ptr, 0)
    rate = c.obj(750, 74, "*")
    tpi = c.obj(850, 52, "t b f")
    c.connect(rsp, 0, rate, 0)
    c.connect(ptr, 0, tpi, 0)
    c.connect(tpi, 1, rate, 1)
    c.connect(tpi, 0, rate, 0)     # bang re-outputs with new pitch
    trate = c.obj(750, 96, "t f f")
    c.connect(rate, 0, trate, 0)
    # direction s = +1/-1 (rate >= 0 counts as forward)
    neg = c.obj(850, 118, "< 0")
    c.connect(trate, 1, neg, 0)
    sgn = c.obj(850, 140, "* -2")
    sg1 = c.obj(850, 162, "+ 1")
    c.connect(neg, 0, sgn, 0)
    c.connect(sgn, 0, sg1, 0)
    sgs = c.obj(850, 184, "sig~")
    c.connect(sg1, 0, sgs, 0)
    # freq = rate * SR / size  (control-rate, recomputed when rate or size changes)
    fr = c.obj(750, 140, f"* {SR}")
    c.connect(trate, 0, fr, 0)
    frd = c.obj(750, 162, "/ 1000")
    c.connect(fr, 0, frd, 0)
    # size change: set divisor first, then re-send the last rate
    lastr = c.obj(650, 140, "f")
    c.connect(fr, 0, lastr, 1)
    bsz = c.obj(650, 118, "t b f")
    c.connect(tsz, 1, bsz, 0)
    c.connect(bsz, 1, frd, 1)
    c.connect(bsz, 0, lastr, 0)
    c.connect(lastr, 0, frd, 0)
    # no glide: a glide would carry the phase forward when a new loop changes the size (and the phase reset)
    fln = c.obj(750, 206, "sig~")
    c.connect(frd, 0, fln, 0)
    wob = c.obj(750, 228, "receive~ gl_wob")
    fw0 = c.obj(750, 250, "*~")
    c.connect(fln, 0, fw0, 0)
    c.connect(wob, 0, fw0, 1)
    # pause (File button on the selected head): fade out while slowing to a stop; resume restarts from the top
    rpz = c.obj(1100, 30, f"r h{n}_pause")
    pz = c.obj(1100, 52, "f 0")
    pzn = c.obj(1100, 74, "== 0")
    c.connect(rpz, 0, pz, 0)
    c.connect(pz, 0, pzn, 0)
    c.connect(pzn, 0, pz, 1)              # toggle
    tpz = c.obj(1100, 96, "t f f")
    c.connect(pzn, 0, tpz, 0)
    run = c.obj(1100, 118, "== 0")         # running = not paused
    c.connect(tpz, 1, run, 0)
    rpk = c.obj(1100, 140, "pack f 150")
    rln = c.obj(1100, 162, "line~")
    c.connect(run, 0, rpk, 0)
    c.connect(rpk, 0, rln, 0)
    run0 = c.msg(1180, 118, "1 0")          # start running (no ramp)
    c.connect(lb, 0, run0, 0)
    c.connect(run0, 0, rln, 0)
    fw = c.obj(750, 270, "*~")
    c.connect(fw0, 0, fw, 0)
    c.connect(rln, 0, fw, 1)
    ph = c.obj(750, 292, "phasor~")
    c.connect(fw, 0, ph, 0)
    # restart from the top on: a new (or cleared) loop, Reset, or resuming from pause (reverse heads from the end)
    rnl = c.obj(1000, 230, "r gl_len")
    tnl = c.obj(1000, 252, "t b")
    c.connect(rnl, 0, tnl, 0)
    rrs = c.obj(1100, 230, "r gl_restart")
    c.connect(rrs, 0, tnl, 0)
    resume = c.obj(1100, 184, "sel 0")     # paused state went to 0 -> resumed
    c.connect(tpz, 0, resume, 0)
    c.connect(resume, 0, tnl, 0)
    ph0 = c.obj(1000, 274, "f 0")
    c.connect(tnl, 0, ph0, 0)
    c.connect(ph0, 0, ph, 1)
    # reverse: start phase just below 1
    c.connect(neg, 0, ph0, 1)
    # phase_n = (1-s)/2 + s*p   (rises then drops at every wrap, either direction)
    sp_ = c.obj(750, 310, "*~")
    c.connect(ph, 0, sp_, 0)
    c.connect(sgs, 0, sp_, 1)
    off1 = c.obj(850, 210, "*~ -0.5")
    off2 = c.obj(850, 232, "+~ 0.5")
    c.connect(sgs, 0, off1, 0)
    c.connect(off1, 0, off2, 0)
    phn = c.obj(750, 340, "+~")
    c.connect(sp_, 0, phn, 0)
    c.connect(off2, 0, phn, 1)

    # latch start (+jitter) and size at each wrap
    rj = c.obj(10, 330, f"r h{n}_jit")
    nz = c.obj(100, 360, "noise~")
    jm = c.obj(10, 400, "*~")
    c.connect(nz, 0, jm, 0)
    jsig = c.obj(10, 360, "sig~")
    c.connect(rj, 0, jsig, 0)
    jj = c.obj(10, 380, "*~")
    c.connect(jsig, 0, jj, 0)
    c.connect(size_sig, 0, jj, 1)
    c.connect(jj, 0, jm, 1)
    st = c.obj(250, 430, "+~")
    c.connect(pos_sig, 0, st, 0)
    c.connect(jm, 0, st, 1)
    hs = c.obj(250, 460, "samphold~")
    c.connect(st, 0, hs, 0)
    c.connect(phn, 0, hs, 1)
    hz = c.obj(500, 460, "samphold~")
    c.connect(size_sig, 0, hz, 0)
    c.connect(phn, 0, hz, 1)

    # index = wrap((start + p*size) / L) * L + 1
    ps = c.obj(500, 490, "*~")
    c.connect(ph, 0, ps, 0)
    c.connect(hz, 0, ps, 1)
    ix = c.obj(250, 520, "+~")
    c.connect(hs, 0, ix, 0)
    c.connect(ps, 0, ix, 1)
    nrm = c.obj(250, 545, "*~ 0")          # float right inlets: [*~ <arg>] (argless *~ wants a signal)
    c.connect(ix, 0, nrm, 0)
    c.connect(invd, 0, nrm, 1)
    wr = c.obj(250, 570, "wrap~")
    c.connect(nrm, 0, wr, 0)
    den = c.obj(250, 595, "*~ 64")
    c.connect(wr, 0, den, 0)
    c.connect(tlen, 0, den, 1)
    one = c.obj(250, 620, "+~ 1")
    c.connect(den, 0, one, 0)
    if DEBUG_HEAD == n:   # print phase and read index every 100 ms (tests only)
        dm_ = c.obj(10, 760, "metro 100")
        dlb = c.obj(10, 740, "loadbang")
        c.connect(dlb, 0, dm_, 0)
        for k, sig in enumerate([ph, one, hz]):
            sn = c.obj(100 + k * 120, 760, "snapshot~")
            c.connect(sig, 0, sn, 0)
            c.connect(dm_, 0, sn, 0)
            pr = c.obj(100 + k * 120, 785, f"print h{n}_{['phase', 'idx', 'hsize'][k]}")
            c.connect(sn, 0, pr, 0)

    # edge fade: clip(p*size/xf) * clip((1-p)*size/xf)
    rxf = c.obj(500, 520, "r gl_xf")
    xfm = c.obj(500, 542, "max 1")
    xfi = c.obj(500, 564, "swap 1")
    xfd = c.obj(500, 586, "/")
    c.connect(rxf, 0, xfm, 0)
    c.connect(xfm, 0, xfi, 0)
    c.connect(xfi, 0, xfd, 0)
    c.connect(xfi, 1, xfd, 1)
    xfs = c.obj(500, 608, "sig~")
    c.connect(xfd, 0, xfs, 0)
    a1 = c.obj(650, 520, "*~")
    c.connect(ps, 0, a1, 0)
    c.connect(xfs, 0, a1, 1)
    a2 = c.obj(650, 545, "clip~ 0 1")
    c.connect(a1, 0, a2, 0)
    pm = c.obj(800, 490, "*~ -1")
    c.connect(ph, 0, pm, 0)
    p1 = c.obj(800, 512, "+~ 1")
    c.connect(pm, 0, p1, 0)
    b0 = c.obj(800, 534, "*~")
    c.connect(p1, 0, b0, 0)
    c.connect(hz, 0, b0, 1)
    b1 = c.obj(800, 556, "*~")
    c.connect(b0, 0, b1, 0)
    c.connect(xfs, 0, b1, 1)
    b2 = c.obj(800, 578, "clip~ 0 1")
    c.connect(b1, 0, b2, 0)
    env = c.obj(650, 600, "*~")
    c.connect(a2, 0, env, 0)
    c.connect(b2, 0, env, 1)

    # volume (squared for a log-ish taper) * gate, pan (linear balance)
    rv = c.obj(950, 400, f"r h{n}_vol")
    vsq = c.obj(950, 422, "t f f")
    vm = c.obj(950, 444, "*")
    c.connect(rv, 0, vsq, 0)
    c.connect(vsq, 1, vm, 1)
    c.connect(vsq, 0, vm, 0)
    vpk = c.obj(950, 466, "pack f 20")
    vln = c.obj(950, 488, "line~")
    c.connect(vm, 0, vpk, 0)
    c.connect(vpk, 0, vln, 0)
    eg = c.obj(650, 630, "*~")
    c.connect(env, 0, eg, 0)
    c.connect(vln, 0, eg, 1)
    eg1 = c.obj(650, 655, "*~")
    c.connect(eg, 0, eg1, 0)
    c.connect(gln, 0, eg1, 1)
    eg2 = c.obj(650, 680, "*~")             # pause fade
    c.connect(eg1, 0, eg2, 0)
    c.connect(rln, 0, eg2, 1)
    rpn = c.obj(950, 530, f"r h{n}_pan")
    ppk = c.obj(950, 552, "pack f 20")
    pln = c.obj(950, 574, "line~")
    c.connect(rpn, 0, ppk, 0)
    c.connect(ppk, 0, pln, 0)
    # gL = clip(2*(1-pan), 0, 1), gR = clip(2*pan, 0, 1)
    gR0 = c.obj(1000, 600, "*~ 2")
    gR = c.obj(1000, 622, "clip~ 0 1")
    c.connect(pln, 0, gR0, 0)
    c.connect(gR0, 0, gR, 0)
    gL0 = c.obj(900, 600, "*~ -2")
    gL1 = c.obj(900, 622, "+~ 2")
    gL = c.obj(900, 644, "clip~ 0 1")
    c.connect(pln, 0, gL0, 0)
    c.connect(gL0, 0, gL1, 0)
    c.connect(gL1, 0, gL, 0)
    for side, gside, x in [("l", gL, 10), ("r", gR, 130)]:
        rd = c.obj(x, 650, f"tabread4~ gl_buf{side}")
        c.connect(one, 0, rd, 0)
        m1 = c.obj(x, 675, "*~")
        c.connect(rd, 0, m1, 0)
        c.connect(eg2, 0, m1, 1)
        m2 = c.obj(x, 700, "*~")
        c.connect(m1, 0, m2, 0)
        c.connect(gside, 0, m2, 1)
        th = c.obj(x, 725, f"throw~ gl_out{side}")
        c.connect(m2, 0, th, 0)
    return c


def wobble(Canvas):
    """Tape wobble: two LFOs whose rates wander; output 1 + depth*(...) as a signal multiplier (send~ gl_wob)."""
    c = Canvas("#N canvas 0 50 600 400 %NAME% 0;")
    c.text(10, 5, "Tape wobble: wow (~0.5 Hz) + flutter (~7 Hz) with wandering rates. depth = window_alt.")
    lb = c.obj(10, 30, "loadbang")
    met = c.obj(10, 55, "metro 1500")
    c.connect(lb, 0, met, 0)
    outs = []
    for i, (base, spread, amt) in enumerate([(0.3, 0.6, 0.012), (5.0, 4.0, 0.002)]):
        x = 10 + i * 250
        rnd = c.obj(x, 85, "random 1000")
        c.connect(met, 0, rnd, 0)
        sc = c.obj(x, 110, f"* {spread / 1000:g}")
        ad = c.obj(x, 135, f"+ {base}")
        pk = c.obj(x, 160, "pack f 1500")
        ln = c.obj(x, 185, "line~")
        osc = c.obj(x, 210, "osc~")
        am = c.obj(x, 235, f"*~ {amt}")
        for a, b in [(rnd, sc), (sc, ad), (ad, pk), (pk, ln), (ln, osc), (osc, am)]:
            c.connect(a, 0, b, 0)
        outs.append(am)
    sm = c.obj(10, 270, "+~")
    c.connect(outs[0], 0, sm, 0)
    c.connect(outs[1], 0, sm, 1)
    rd = c.obj(300, 270, "r gl_wobd")
    pk = c.obj(300, 292, "pack f 50")
    ln = c.obj(300, 314, "line~")
    c.connect(rd, 0, pk, 0)
    c.connect(pk, 0, ln, 0)
    dm = c.obj(10, 300, "*~")
    c.connect(sm, 0, dm, 0)
    c.connect(ln, 0, dm, 1)
    one = c.obj(10, 330, "+~ 1")
    c.connect(dm, 0, one, 0)
    s = c.obj(10, 355, "send~ gl_wob")
    c.connect(one, 0, s, 0)
    return c


