"""13_partials: an additive drone organ of 16 sine partials for the Nebulae.

Generated by tools/gen.py. Design notes: docs/PARTIALS.md. User guide: patches/13_partials_README.md.

Designed with the owner 2026-11-14 (Pitch click = C2; "sculpt + deal": Start = which partials, Size = stretch,
Window = tilt, Overlap = drift, Density = how many, Speed = drift speed with none between the clicks, Reset = deal
a new random mix, Freeze = hold the drift; Blend mixes the input). The rest is listed in docs/PARTIALS.md.

Per partial n (1..16), one control program on any change:
  f_n   = F1 x n^(1 + 0.4 Size)                         (F1 = C2 x 2^(5 (Pitch - 0.6)))
  lvl_n = mask_n(Start) x n^(-2 (1 - Window)) x fade_n(Density) x deal_n x (1 - Overlap + Overlap x drift_n)
          (0 above 18 kHz)
  mask_n(Start): all -> odd -> even (+ half the fundamental) -> primes, morphed (a 130-point table per partial)
  drift_n: a random walk, a step every 50 ms (size from Speed: 0 between the clicks; Freeze = 0)
  deal_n: Reset = new random levels 0.15..1, gliding (alt Density); File = all back to 1
Odd partials go to one bus, even to the other, panned apart by alt Start. The sum is normalised (0.25 / rms of the
levels), so the level stays put whatever the shape. Source adds a twin to every partial (alt Size cents up: slow
beating); Record adds a sine an octave below.
"""

import math

from gloop import press
from glitch import chain
from spectral import op, softclip, pickup
from shimmer import sig
from resonator import V, E, lift, mn, mx, gt, exp, sqrt, watched

SR = 48000
NP = 16
C2 = 65.406
PRIMES = {1, 2, 3, 5, 7, 11, 13}
TICK_MS = 50
MASK_N = 130                              # 129 steps: the 4 anchors land exactly on indices 0, 43, 86, 129
ALT_RESET = "\\; pt_wd 0.5 \\; pt_det 6 \\; pt_glide 2000"


def anchors(n):
    """The four masks Start morphs through, for partial n."""
    return [1.0, 1.0 if n % 2 else 0.0, (1.0 if n % 2 == 0 else (0.5 if n == 1 else 0.0)),
            1.0 if n in PRIMES else 0.0]


def mask(n, s):
    a = anchors(n)
    x = min(max(s, 0.0), 1.0) * 3
    i = min(int(x), 2)
    return a[i] + (a[i + 1] - a[i]) * (x - i)


def level(n, start, window, density, deal=1.0, overlap=0.0, drift=0.5, f=None):
    """lvl_n as the patch computes it (tests use this)."""
    fade = min(1.0, max(0.0, density * 15 + 2 - n))
    v = mask(n, start) * n ** (-2 * (1 - window)) * fade * deal * (1 - overlap + overlap * drift)
    return v if (f is None or f < 18000) else 0.0


def freq(n, pitch, size):
    return C2 * 2 ** ((pitch - 0.6) * 5) * n ** (1 + 0.4 * size)


def ui(Canvas, test=False):
    c = Canvas("#N canvas 0 50 1500 1100 %NAME% 0;")
    c.text(10, 5, "pitch=note start=which partials size=stretch window=tilt density=how many overlap=drift "
                  "speed=drift speed blend=mix. Reset=deal File=flatten Freeze=hold Source=twins Record=sub. "
                  "alt: start=width size=twin detune density=deal glide")
    lb = c.obj(1300, 30, "loadbang")
    c.connect(chain(c, 1300, 30, lb, ["delay 1000"]), 0, c.msg(1300, 80, "\\; pt_primed 1"), 0)
    c.connect(lb, 0, c.msg(700, 30, "\\; pt_P 0.6 \\; pt_sz 0 \\; pt_s 0 \\; pt_w 0.4 \\; pt_d 1 \\; pt_o 0.3 "
                                    "\\; pt_spd 0.5 \\; pt_frz 0 \\; pt_src 0 \\; pt_sub 0 \\; pt_gw 1 \\; pt_gd 0 "
                                    + ALT_RESET), 0)
    x, y = 10, 60
    for i, (src, dst, conv) in enumerate([
            ("pitch", "pt_P", []), ("start", "pt_s", ["clip 0 1"]), ("size", "pt_sz", ["clip 0 1"]),
            ("window", "pt_w", ["clip 0 1"]), ("density", "pt_d", ["clip 0 1"]), ("overlap", "pt_o", ["clip 0 1"]),
            ("speed", "pt_spd", ["clip 0 1"]), ("freeze", "pt_frz", []), ("source", "pt_src", []),
            ("record", "pt_sub", [])]):
        # change -1: the first value always passes (a knob at exactly 0 must replace the load default)
        chain(c, x + i * 120, y, c.obj(x + i * 120, y, f"r {src}"), ["change -1"] + conv + [f"s {dst}"])
    tb = op(c, x, y + 150, "t f f", chain(c, x, y + 100, c.obj(x, y + 100, "r blend"),
                                          ["change -1", "clip 0 1", "* 1.5708"]))
    chain(c, x + 60, y + 150, tb, ["sin", "s pt_gw"], outlet=1)
    chain(c, x, y + 150, tb, ["cos", "s pt_gd"])
    # Reset = deal, File = flatten (bangs to every partial)
    c.connect(press(c, x + 200, y + 100, "reset", True, primed="pt_primed"), 0, c.msg(x + 200, y + 190,
                                                                                      "\\; pt_deal bang"), 0)
    c.connect(press(c, x + 330, y + 100, "filestate", True, primed="pt_primed"), 0,
              c.msg(x + 330, y + 190, "\\; pt_flat bang"), 0)
    # drift step from Speed: none between the clicks, growing past them; Freeze = none
    SPD, FRZ = V("pt_spd_v"), V("pt_frz_v")
    mv = mn(1, mx(0, (E("abs", lift(SPD - 0.5)) - 0.125) / 0.375))
    watched(c, 10, 400, ["pt_spd", "pt_frz"], [("s:pt_stp", 0.1 * mv * mv * (1 - FRZ))])
    # the drift clock
    c.connect(chain(c, 400, 400, c.obj(400, 400, "loadbang"), [f"metro {TICK_MS}"]), 0,
              c.obj(400, 450, "s pt_tick"), 0)
    # alt layer (pickup by movement); Source + Record = defaults
    rb = "pt_altrb"
    tar = op(c, 1100, 600, "t b b", press(c, 1100, 530, "record_alt", primed="pt_primed"))
    c.connect(tar, 1, c.msg(1200, 622, "\\; pt_altrb bang"), 0)
    c.connect(tar, 0, c.msg(1100, 644, ALT_RESET), 0)
    x, y = 600, 700
    pickup(c, x, y, "start_alt", "pt_wd", ["clip 0 1"], rebase=rb)
    pickup(c, x + 250, y, "size_alt", "pt_det", ["clip 0 1", "* 20"], rebase=rb)
    pickup(c, x + 500, y, "density_alt", "pt_glide", ["clip 0 1", f"* {math.log(100):.6f}", "exp", "* 100"],
           rebase=rb)
    # normalisation: 0.25 / rms of the levels (capped at x2.5)
    S = None
    for n in range(1, NP + 1):
        t = V(f"pt_l{n}_v") * V(f"pt_l{n}_v")
        S = t if S is None else S + t
    watched(c, 10, 600, [f"pt_l{n}" for n in range(1, NP + 1)], [("s:pt_norm", mn(2.5, 0.25 / sqrt(mx(1e-6, S))))])
    if test:
        for i, nm in enumerate(["pt_norm", "pt_f1", "pt_stp"]):
            c.connect(c.obj(10 + i * 120, 1050, f"r {nm}"), 0, c.obj(10 + i * 120, 1072, f"print {nm[3:]}"), 0)
    return c


def partial_ctl(Canvas, n):
    """Partial n's drift walk, deal, and its level/frequency program."""
    c = Canvas("#N canvas 0 50 900 700 %NAME% 0;")
    c.obj(600, 10, f"table pt_m{n} {MASK_N}")
    c.connect(c.obj(600, 34, "loadbang"), 0,
              c.msg(600, 56, f"\\; pt_m{n} 0 " + " ".join(f"{mask(n, i / (MASK_N - 1)):.4f}" for i in range(MASK_N))), 0)
    # drift: a clipped random walk, a step every tick
    rnd = op(c, 10, 30, "random 1000", c.obj(10, 8, "r pt_tick"))
    stp = op(c, 10, 96, "* 0", chain(c, 10, 30, rnd, ["- 499.5", "/ 499.5"]))
    c.connect(c.obj(100, 74, "r pt_stp"), 0, stp, 1)
    acc = op(c, 10, 118, "+ 0.5", stp)
    tf = op(c, 10, 162, "t f f", chain(c, 10, 118, acc, ["clip 0 1"]))
    c.connect(tf, 1, acc, 1)
    c.connect(tf, 0, c.obj(10, 184, f"s pt_dr{n}"), 0)
    c.connect(chain(c, 150, 118, c.obj(150, 118, "loadbang"), ["f 0.5"]), 0, tf, 0)
    # deal: a new random level 0.15 .. 1 (Reset), or 1 (File, and at load), gliding
    dr = chain(c, 300, 8, c.obj(300, 8, "r pt_deal"), ["random 1000", "/ 1000", "* 0.85", "+ 0.15"])
    pk = c.obj(300, 120, "pack f 2000")
    c.connect(dr, 0, pk, 0)
    one = c.msg(420, 74, "1")
    c.connect(c.obj(420, 30, "r pt_flat"), 0, one, 0)
    c.connect(c.obj(480, 30, "loadbang"), 0, one, 0)
    c.connect(one, 0, pk, 0)
    c.connect(c.obj(400, 98, "r pt_glide"), 0, pk, 1)
    c.connect(chain(c, 300, 120, pk, [f"line 0 {TICK_MS}"]), 0, c.obj(300, 164, f"s pt_deal{n}"), 0)
    # level and frequency
    P, SZ, S_, W, D, O = (V(f"pt_{k}_v") for k in ("P", "sz", "s", "w", "d", "o"))
    DEAL, DR, SRC, DET = V(f"pt_deal{n}_v"), V(f"pt_dr{n}_v"), V("pt_src_v"), V("pt_det_v")
    ln = math.log(n)
    F1 = C2 * exp((P - 0.6) * (5 * math.log(2)))
    f = mn(30000, F1 * exp((1 + 0.4 * SZ) * ln)) if n > 1 else F1
    msk = E(f"tabread pt_m{n}", lift(S_ * (MASK_N - 1) + 0.5))      # tabread truncates: round
    tilt = exp((W - 1) * (2 * ln)) if n > 1 else lift(1)
    fade = mn(1, mx(0, D * 15 + (2 - n)))
    lvl = msk * tilt * fade * DEAL * (1 - O + O * DR) * gt(18000, V(f"pt_fv{n}"))
    watched(c, 10, 250, ["pt_P", "pt_sz", "pt_s", "pt_w", "pt_d", "pt_o", f"pt_deal{n}", f"pt_dr{n}", "pt_src",
                         "pt_det"],
            [(f"v:pt_fv{n} s:pt_f{n}", f), (f"s:pt_ft{n}", V(f"pt_fv{n}") * exp(SRC * DET * (math.log(2) / 1200))),
             (f"s:pt_l{n}", lvl)])
    return c


def voices(Canvas):
    """The oscillators: partial n (+ its twin, faded in by Source) -> bus pt_odd / pt_even."""
    c = Canvas("#N canvas 0 50 1600 900 %NAME% 0;")
    src = sig(c, 1400, 10, "pt_src", 40)
    for n in range(1, NP + 1):
        x, y = 10 + ((n - 1) % 8) * 190, 60 + ((n - 1) // 8) * 300
        o1 = op(c, x, y + 66, "osc~", sig(c, x, y, f"pt_f{n}", 15))
        o2 = op(c, x + 90, y + 66, "osc~", sig(c, x + 90, y, f"pt_ft{n}", 15))
        lv = sig(c, x, y + 100, f"pt_l{n}", TICK_MS + 10)
        tw = op(c, x + 90, y + 166, "*~", o2, src)
        s = op(c, x, y + 188, "*~", op(c, x, y + 166, "+~", o1, tw), lv)
        c.connect(s, 0, c.obj(x, y + 210, f"throw~ pt_{'odd' if n % 2 else 'even'}"), 0)
    # Record: a sine an octave below partial 1
    sub = op(c, 10, 760, "*~", op(c, 10, 738, "osc~", chain(c, 10, 690, c.obj(10, 690, "r pt_f1"), ["* 0.5"])),
             sig(c, 120, 690, "pt_sub", 200))
    c.connect(sub, 0, c.obj(10, 782, "outlet~"), 0)
    return c


def test_source(Canvas):
    """Left = right = a sine pt_tsf at pt_tsa (for Blend)."""
    c = Canvas("#N canvas 0 50 500 300 %NAME% 0;")
    s = op(c, 10, 40, "*~", op(c, 10, 30, "osc~ 1000", c.obj(10, 8, "r pt_tsf")), sig(c, 100, 8, "pt_tsa", 5))
    c.connect(s, 0, c.obj(10, 100, "outlet~"), 0)
    c.connect(s, 0, c.obj(200, 100, "outlet~"), 0)
    return c


def partials_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "13_partials: additive drone organ, 16 partials. See docs/PARTIALS.md and "
                  "patches/13_partials_README.md.")
    c.text(10, 20, "Pitch = note (click = C2). Start = which partials. Size = stretch. Window = tilt. Overlap = "
                   "drift. Reset = deal. Freeze = hold.")
    c.sub(10, 50, "nebulae_controls", controls_canvas())
    c.sub(10, 80, "ui", ui(Canvas, bool(test)))
    for n in range(1, NP + 1):
        c.sub(100 + (n - 1) % 8 * 90, 110 + (n - 1) // 8 * 25, f"partial{n}", partial_ctl(Canvas, n))
    vc = c.sub(10, 170, "voices", voices(Canvas))
    src = c.sub(10, 200, "testsrc", test_source(Canvas)) if test else c.obj(10, 200, "adc~ 1 2")
    odd, even = c.obj(300, 200, "catch~ pt_odd"), c.obj(450, 200, "catch~ pt_even")
    norm = sig(c, 600, 180, "pt_norm", 60)
    srcn = op(c, 700, 240, "-~", c.obj(700, 220, "sig~ 1"), op(c, 800, 220, "*~ 0.29", sig(c, 800, 160, "pt_src", 40)))
    gain = op(c, 600, 260, "*~", norm, srcn)                   # twins on: about -3 dB, so the level stays put
    # width (alt Start): odd partials left, even right; 0 = centre
    wd = sig(c, 900, 160, "pt_wd", 50)
    hw = op(c, 900, 220, "*~ 0.5", wd)
    a = op(c, 900, 260, "+~", c.obj(900, 240, "sig~ 0.5"), hw)       # 0.5 .. 1
    b = op(c, 1000, 260, "-~", c.obj(1000, 240, "sig~ 0.5"), hw)     # 0.5 .. 0
    gw, gd = sig(c, 400, 400, "pt_gw", 20), sig(c, 500, 400, "pt_gd", 20)
    outs = []
    for ch, x in ((0, 10), (1, 300)):
        ko, ke = (a, b) if ch == 0 else (b, a)
        mixd = op(c, x, 330, "+~", op(c, x, 310, "*~", odd, ko), op(c, x + 80, 310, "*~", even, ke))
        org = op(c, x, 352, "*~", mixd, gain)
        tone = op(c, x, 374, "+~", org, op(c, x + 80, 352, "*~ 0.15", vc))
        mix = op(c, x, 420, "+~", op(c, x, 398, "*~", tone, gw), op(c, x + 80, 398, "*~", (src, ch), gd))
        outs.append(softclip(c, x, 450, mix))
    dac = c.obj(10, 600, "dac~ 1 2")
    c.connect(outs[0], 0, dac, 0)
    c.connect(outs[1], 0, dac, 1)
    if test:
        lb = c.obj(600, 420, "loadbang")
        steps = test.get("steps", [])
        wav = test.get("wav")
        for i, (ms, msg) in enumerate(steps):
            if wav and "pd quit" in msg:
                msg = "\\; pt_save bang " + msg
            d = c.obj(600 + (i % 4) * 120, 445 + (i // 4) * 50, f"delay {ms}")
            m = c.msg(600 + (i % 4) * 120, 467 + (i // 4) * 50, msg)
            c.connect(lb, 0, d, 0)
            c.connect(d, 0, m, 0)
        if wav:
            n = int(max(ms for ms, _ in steps) * SR / 1000)
            for ch, x in [(0, 10), (1, 200)]:
                sd = "lr"[ch]
                c.obj(x, 700, f"table pt_rec{sd} {n}")
                tw = c.obj(x, 670, f"tabwrite~ pt_rec{sd}")
                c.connect(outs[ch], 0, tw, 0)
                c.connect(lb, 0, tw, 0)
            rs = c.obj(600, 670, "r pt_save")
            wm = c.msg(600, 692, f"write -bytes 4 {wav} pt_recl pt_recr")
            c.connect(rs, 0, wm, 0)
            c.connect(wm, 0, c.obj(600, 714, "soundfiler"), 0)
    return c
