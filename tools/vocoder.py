"""10_vocoder: a 20-band channel vocoder for the Nebulae (designed while the owner was away, 2026-11-14: the
decisions and their alternatives are listed in docs/VOCODER.md for review).

Generated by tools/gen.py. Design notes: docs/VOCODER.md. User guide: patches/10_vocoder_README.md.

Signal flow
  modulator = left input -> presence (alt Size) -> 20 bands (two RBJ band-pass biquad~ in series, 100 Hz ..
     8 kHz, Q on Size in 16 steps; Pd's bp~ has no zeros, so it lets the low end through every band)
     -> abs~ x noise gate (alt Blend) -> lop~ (Window; cutoff 0 = Freeze holds the envelope) -> send~ vc_e<k>
  carrier = internal supersaw chord (3 voices x 3 saws, Start = chord, Density = detune, Pitch = root V/oct,
     Record = Track: the root follows the voice's pitch (sigmund~), whisper noise on alt Density)
     or the right input (Source)
     -> the same 20 bands (+3 dB/oct tilt, so a saw's bands come out level)
     x the modulator envelope of band k - shift (Speed = formant shift, interpolated between neighbours)
     -> even bands left, odd bands right by the width (alt Start) -> sum
  + unvoiced noise (Overlap: the modulator's sibilance above 5 kHz drives high-passed noise)
  + carrier leak (alt Overlap)
  out = equal-power mix (Blend) of the dry modulator and the vocoder -> soft clip
"""

import math

from gloop import press
from glitch import chain
from spectral import op, softclip, pickup
from shimmer import sig
from resonator import V, mn, mx, eq, gt, exp, fabs, watched

SR = 48000
NB = 20                                   # bands
F_LO, F_HI = 100.0, 8000.0
FB = [F_LO * (F_HI / F_LO) ** (k / (NB - 1)) for k in range(NB)]
C3 = 130.8128
ZERO = 99                                 # vc_e99 = the silent envelope (shift past the ends)
SHAPES = [("unison", [0, 0, 0]), ("octaves", [0, 12, -12]), ("fifth", [0, 7, 12]), ("major", [0, 4, 7]),
          ("minor", [0, 3, 7]), ("sus4", [0, 5, 7]), ("maj7", [0, 4, 11]), ("min7", [0, 3, 10])]
QSTEPS = 16                               # Size: band Q 1.5 (smooth) .. 12 (narrow), log steps
QS = [1.5 * 8 ** (i / (QSTEPS - 1)) for i in range(QSTEPS)]


QDEF = 8                                  # Size at noon


def cof(f, q, g=1.0):
    return " ".join(f"{v:.9g}" for v in rbj_bp(f, q, g))


def rbj_bp(f, q, g=1.0):
    """RBJ band-pass (0 dB peak) as Pd biquad~ coefficients: fb1 fb2 ff1 ff2 ff3."""
    w0 = 2 * math.pi * f / SR
    al = math.sin(w0) / (2 * q)
    a0 = 1 + al
    return [2 * math.cos(w0) / a0, -(1 - al) / a0, g * al / a0, 0.0, -g * al / a0]


SHIFT_MAX = 6.0                           # bands, at the ends of Speed
CAL = 4.0                                 # carrier band gain (with the tilt: the internal chord's bands come out
TILT = [CAL * (f / F_LO) ** 0.5 for f in FB]   # about level; +3 dB/oct offsets a saw's falling band energy)
MAKEUP = 2.0                              # +6 dB: the narrow bands only pass part of a broadband signal
ALT_RESET = ("\\; vc_wd 0.5 \\; vc_pres 0.3 \\; vc_wh 0 \\; vc_leak 0 \\; vc_glide 30 "
             "\\; vc_thrl 0.001")         # gate -60 dB


def ui(Canvas):
    c = Canvas("#N canvas 0 50 1400 1000 %NAME% 0;")
    c.text(10, 5, "start=chord size=band Q density=detune overlap=sibilance window=envelope speed blend=mix "
                  "pitch=root speed=formant shift. Freeze=hold envelope (File held = momentary) Reset=next chord "
                  "Record=track Source=external carrier")
    lb = c.obj(1200, 30, "loadbang")
    c.connect(chain(c, 1200, 30, lb, ["delay 1000"]), 0, c.msg(1200, 80, "\\; vc_primed 1"), 0)
    c.connect(lb, 0, c.msg(700, 30, "\\; vc_zone 0 \\; vc_rcnt 0 \\; vc_qs 8 \\; vc_det 0.005 \\; vc_sib 0 "
                                    "\\; vc_fc 20 \\; vc_gd 0 \\; vc_gw 1 \\; vc_P 0 \\; vc_sh 0 \\; vc_ext 0 "
                                    "\\; vc_frz 0 \\; vc_ffz 0 \\; vc_trk 0 \\; vc_ftrk 220 " + ALT_RESET), 0)
    x, y = 10, 60
    chain(c, x, y, c.obj(x, y, "r start"), ["* 8", "int", "clip 0 7", "change", "s vc_zone"])
    chain(c, x + 130, y, c.obj(x + 130, y, "r size"), ["clip 0 1", f"* {QSTEPS - 0.01:g}", "int", "change",
                                                       "s vc_qs"])
    t = op(c, x + 260, y + 44, "t f f", chain(c, x + 260, y, c.obj(x + 260, y, "r density"), ["change", "clip 0 1"]))
    chain(c, x + 260, y + 44, op(c, x + 260, y + 66, "*", (t, 0), (t, 1)), ["* 0.02", "s vc_det"])
    chain(c, x + 390, y, c.obj(x + 390, y, "r overlap"), ["change", "clip 0 1", "s vc_sib"])
    # Window: envelope follower cutoff 200 Hz (snappy) .. 2 Hz (smooth)
    chain(c, x + 520, y, c.obj(x + 520, y, "r window"), ["change", "clip 0 1", "* -4.60517", "exp", "* 200",
                                                         "s vc_fc"])
    tb = op(c, x + 650, y + 66, "t f f", chain(c, x + 650, y, c.obj(x + 650, y, "r blend"),
                                              ["change", "clip 0 1", "* 1.5708"]))
    chain(c, x + 710, y + 66, tb, ["sin", "s vc_gw"], outlet=1)
    chain(c, x + 650, y + 66, tb, ["cos", "s vc_gd"])
    chain(c, x + 780, y, c.obj(x + 780, y, "r pitch"), ["change", "- 0.6", "* 60", "s vc_P"])
    # Speed: formant shift, 0 between the clicks, +-SHIFT_MAX bands at the ends
    ts = op(c, x + 910, y + 44, "t f f", chain(c, x + 910, y, c.obj(x + 910, y, "r speed"), ["change"]))
    # band k of the carrier reads the modulator's band k - shift: clockwise = formants up (vc_sh = -shift)
    dn = chain(c, x + 1020, y + 44, ts, ["* -1", "+ 0.375", "/ 0.375", "clip 0 1", f"* {SHIFT_MAX:g}"], outlet=1)
    up = chain(c, x + 910, y + 44, ts, ["- 0.625", "/ 0.375", "clip 0 1", f"* {-SHIFT_MAX:g}"])
    c.connect(op(c, x + 910, y + 176, "+", up, dn), 0, c.obj(x + 910, y + 198, "s vc_sh"), 0)

    # buttons
    x, y = 10, 300
    cnt = op(c, x, y + 100, "f", press(c, x, y, "reset", True, primed="vc_primed"))
    tc = op(c, x, y + 166, "t f f", chain(c, x, y + 100, cnt, ["+ 1", "mod 8"]))
    c.connect(tc, 1, cnt, 1)                                    # each press: the next chord
    c.connect(tc, 0, c.obj(x, y + 190, "s vc_rcnt"), 0)
    for i, (src, dst) in enumerate([("freeze", "vc_frz"), ("source", "vc_ext"), ("record", "vc_trk"),
                                    ("filestate", "vc_ffz")]):
        chain(c, x + 150 + i * 120, y, c.obj(x + 150 + i * 120, y, f"r {src}"), ["change", f"s {dst}"])
    # alt layer (pickup by movement); Source + Record = defaults
    rb = "vc_altrb"
    tar = op(c, 1000, 600, "t b b", press(c, 1000, 530, "record_alt", primed="vc_primed"))
    c.connect(tar, 1, c.msg(1100, 622, "\\; vc_altrb bang"), 0)
    c.connect(tar, 0, c.msg(1000, 644, ALT_RESET), 0)
    x, y = 10, 600
    pickup(c, x, y, "start_alt", "vc_wd", ["clip 0 1"], rebase=rb)
    pickup(c, x + 330, y, "size_alt", "vc_pres", ["clip 0 1"], rebase=rb)
    pickup(c, x + 660, y, "density_alt", "vc_wh", ["clip 0 1"], rebase=rb)
    pickup(c, x, y + 230, "overlap_alt", "vc_leak", ["clip 0 1", "* 0.5"], rebase=rb)
    pickup(c, x + 330, y + 230, "window_alt", "vc_glide", ["clip 0 1", "t f f", "*", "* 500"], rebase=rb)
    c.connect(c.n - 4, 1, c.n - 3, 1)     # [t f f] right -> [*] right: squared
    pickup(c, x + 660, y + 230, "blend_alt", "vc_thrl", ["clip 0 1", "* 60", "+ -80", "* 0.115129", "exp"],
           rebase=rb)                     # gate threshold -80 .. -20 dB
    return c


def ctl(Canvas, test=False):
    """Derived control: voice frequencies, shift routing, envelope cutoff, pans."""
    c = Canvas("#N canvas 0 50 1600 1200 %NAME% 0;")
    c.text(10, 5, "voices: root (V/oct, or tracked + rounded transpose) x chord; shift: receive~ pairs per band; "
                  "freeze: envelope cutoff 0")
    c.obj(10, 30, f"table vc_shapes {3 * len(SHAPES)}")
    c.connect(c.obj(200, 30, "loadbang"), 0,
              c.msg(200, 52, "\\; vc_shapes 0 " + " ".join(str(i) for _, s in SHAPES for i in s)), 0)
    P, TRK, FT = V("vc_P_v"), V("vc_trk_v"), V("vc_ftrk_v")
    SHP = V("vc_shp")
    root = TRK * FT * exp((E_round(P)) * (math.log(2) / 12)) + (1 - TRK) * C3 * exp(P * (math.log(2) / 12))
    assigns = [("v:vc_shp", E_mod8(V("vc_zone_v") + V("vc_rcnt_v"))),
               ("s:vc_gl", iff_(TRK, V("vc_glide_v"), 2))]          # glide first: it applies to these values
    for v in range(3):
        assigns.append((f"s:vc_fv{v}", mx(8, mn(5000, root * exp(E_tab("vc_shapes", SHP * 3 + v) * (math.log(2) / 12))))))
    watched(c, 10, 100, ["vc_P", "vc_trk", "vc_ftrk", "vc_zone", "vc_rcnt", "vc_glide"], assigns)
    # freeze: the envelope cutoff goes to 0 (lop~ holds its state)
    FZ = mx(V("vc_frz_v"), V("vc_ffz_v"))
    watched(c, 400, 100, ["vc_frz", "vc_ffz", "vc_fc"], [("s:vc_fce", (1 - FZ) * V("vc_fc_v"))])
    # gate threshold -> 1 / thr
    watched(c, 600, 100, ["vc_thrl"], [("s:vc_thri", 1 / mx(1e-5, V("vc_thrl_v")))])
    # pans: even bands left, odd right, by the width
    WD = V("vc_wd_v")
    watched(c, 800, 100, ["vc_wd"], [a for k in range(2) for a in (
        (f"s:vc_pl{k}", 1.41421 * MAKEUP * E_cos((1 + (1 if k else -1) * WD) * (math.pi / 4))),
        (f"s:vc_pr{k}", 1.41421 * MAKEUP * E_sin((1 + (1 if k else -1) * WD) * (math.pi / 4))))])
    # shift: i = floor(s), f = s - i -> band k reads envelopes k+i (x 1-f) and k+i+1 (x f)
    x, y = 10, 600
    tsh = op(c, x, y + 22, "t f f", c.obj(x, y, "r vc_sh"))
    c.connect(tsh, 1, c.obj(x + 100, y + 44, "v vc_shs"), 0)
    tf2 = op(c, x, y + 110, "t b f", chain(c, x, y + 22, tsh, ["+ 100", "int", "- 100"]))
    c.connect(tf2, 1, c.obj(x + 100, y + 132, "v vc_shi"), 0)
    ich = op(c, x + 200, y + 132, "change -999", (tf2, 1))       # -999: the first value always routes
    watched_like(c, x + 300, y + 132, (tf2, 0))
    for k in range(NB):
        for j, nm in enumerate(("vc_ra", "vc_rb")):
            xx = x + (k % 10) * 150 + j * 70
            yy = y + 260 + (k // 10) * 200
            a = op(c, xx, yy, f"+ {k + j}", ich)
            m0 = op(c, xx, yy + 22, "moses 0", a)
            m1 = op(c, xx, yy + 44, f"moses {NB}", (m0, 1))
            z = c.msg(xx + 40, yy + 66, str(ZERO))
            c.connect(m0, 0, z, 0)
            c.connect(m1, 1, z, 0)
            mf = c.obj(xx, yy + 88, "makefilename vc_e%d")
            c.connect(m1, 0, mf, 0)
            c.connect(z, 0, mf, 0)
            c.connect(chain(c, xx, yy + 88, mf, ["list prepend set", "list trim"]), 0,
                      c.obj(xx, yy + 154, f"s {nm}{k}"), 0)
    if test:
        for i, n in enumerate(["vc_fv0", "vc_fv1", "vc_fv2", "vc_fce", "vc_wf"]):
            c.connect(c.obj(10 + i * 120, 1150, f"r {n}"), 0, c.obj(10 + i * 120, 1172, f"print {n[3:]}"), 0)
    return c


# small E helpers (resonator's E with a few more ops)
from resonator import E, lift   # noqa: E402


def E_round(a):
    return E("int", lift(a) + 100.5) - 100


def E_mod8(a):
    return E("mod", lift(a), lift(8))


def E_tab(name, i):
    return E(f"tabread {name}", lift(i))


def E_cos(a):
    return E("cos", lift(a))


def E_sin(a):
    return E("sin", lift(a))


def iff_(cnd, a, b):
    return cnd * a + (1 - cnd) * b


def watched_like(c, x, y, src):
    """f = s - i on a bang (both from [v]) -> vc_wf (weight of the upper neighbour)."""
    from resonator import program
    return program(c, x, y, src, [("s:vc_wf", V("vc_shs") - V("vc_shi"))])


def carrier(Canvas):
    """Internal supersaw chord (+ whisper noise) or the right input -> outlet~."""
    c = Canvas("#N canvas 0 50 1200 600 %NAME% 0;")
    ext = c.obj(900, 10, "inlet~")
    tot = c.obj(10, 400, "+~")
    for v in range(3):
        x = 10 + v * 280
        pk = chain(c, x, 10, c.obj(x, 10, f"r vc_fv{v}"), ["pack f 2"])
        c.connect(c.obj(x + 80, 10, "r vc_gl"), 0, pk, 1)
        fv = op(c, x, 54, "line~", pk)
        for j, mul in enumerate(("-1", "0", "1")):
            dm = op(c, x + j * 80, 100, "*~ 0", fv)          # f x det x (-1/0/+1)
            c.connect(chain(c, x + j * 80 + 30, 78, c.obj(x + j * 80 + 30, 78, "r vc_det"), [f"* {mul}"]), 0,
                      dm, 1)
            ph = op(c, x + j * 80, 150, "phasor~", op(c, x + j * 80, 122, "+~", fv, dm))
            saw = chain(c, x + j * 80, 150, ph, ["*~ 2", "-~ 1"])
            c.connect(saw, 0, tot, 0)
    saws = op(c, 10, 430, "*~ 0.2", tot)
    wh = sig(c, 500, 300, "vc_wh", 30)
    nz = op(c, 400, 400, "*~", c.obj(400, 370, "noise~"), wh)
    dw = op(c, 500, 380, "-~", c.obj(500, 360, "sig~ 1"), wh)
    inner = op(c, 10, 470, "+~", op(c, 10, 450, "*~", saws, dw), nz)
    ex = sig(c, 700, 300, "vc_ext", 20)
    nex = op(c, 700, 360, "-~", c.obj(700, 340, "sig~ 1"), ex)
    out = op(c, 10, 520, "+~", op(c, 10, 500, "*~", inner, nex), op(c, 300, 500, "*~", ext, ex))
    c.connect(out, 0, c.obj(10, 560, "outlet~"), 0)
    return c


def bank(Canvas):
    """Modulator and carrier banks, envelopes, shift -> throw~ vc_ev (even bands) / vc_od (odd bands)."""
    c = Canvas("#N canvas 0 50 1800 1200 %NAME% 0;")
    c.text(10, 5, f"{NB} bands {F_LO:g} .. {F_HI:g} Hz, two band-pass biquad~ each. env_k = lop~(abs~(mod_k)) (mod gated); "
                  "out_k = car_k x [(1-f) env_(k+i) + f env_(k+i+1)]. The carrier's 2nd biquad carries a +3 dB/oct tilt")
    mod = c.obj(10, 30, "inlet~")
    car = c.obj(600, 30, "inlet~")
    # presence: mod + 3 x pres x hip~ 2000 (mod)
    pr = op(c, 100, 60, "*~ 0", chain(c, 100, 30, mod, ["hip~ 2000", "hip~ 2000"]))
    c.connect(chain(c, 200, 30, c.obj(200, 30, "r vc_pres"), ["* 3"]), 0, pr, 1)
    m1 = op(c, 10, 90, "+~", mod, pr)
    # gate: broadband envelope / threshold
    gate = chain(c, 300, 60, mod, ["abs~", "lop~ 20", "*~ 1000"])
    c.connect(c.obj(400, 80, "r vc_thri"), 0, gate, 1)
    gate = chain(c, 300, 126, gate, ["-~ 1", "*~ 4", "clip~ 0 1", "lop~ 30"])
    m2 = op(c, 10, 150, "*~", m1, gate)                      # the gated modulator feeds every band
    c.connect(c.obj(1000, 30, "sig~ 0"), 0, c.obj(1000, 52, f"send~ vc_e{ZERO}"), 0)
    wf = sig(c, 1200, 30, "vc_wf", 20)
    nwf = op(c, 1200, 90, "-~", c.obj(1200, 70, "sig~ 1"), wf)
    # Q steps: one message box per step sets every biquad (the carrier's 2nd stage with its tilt gain)
    qsel = op(c, 800, 52, "sel " + " ".join(map(str, range(QSTEPS))), c.obj(800, 30, "r vc_qs"))
    for i, q in enumerate(QS):
        txt = " ".join(f"\\; vc_bm{k} {cof(f, q)} \\; vc_bc{k} {cof(f, q, TILT[k])}" for k, f in enumerate(FB))
        c.connect(qsel, i, c.msg(800 + (i % 4) * 60, 80 + (i // 4) * 22, txt), 0)
    rfc = c.obj(900, 30, "r vc_fce")
    for k, f in enumerate(FB):
        x, y = 10 + (k % 5) * 350, 200 + (k // 5) * 240
        b1 = op(c, x, y, f"biquad~ {cof(f, QS[QDEF])}", m2)
        b2 = op(c, x, y + 22, f"biquad~ {cof(f, QS[QDEF])}", b1)
        c1 = op(c, x + 150, y, f"biquad~ {cof(f, QS[QDEF])}", car)
        c2 = op(c, x + 150, y + 22, f"biquad~ {cof(f, QS[QDEF], TILT[k])}", c1)
        rbm = c.obj(x + 300, y, f"r vc_bm{k}")
        for o in (b1, b2, c1):
            c.connect(rbm, 0, o, 0)
        c.connect(c.obj(x + 300, y + 22, f"r vc_bc{k}"), 0, c2, 0)
        env = op(c, x, y + 66, "lop~ 20", op(c, x, y + 44, "abs~", b2))
        c.connect(rfc, 0, env, 1)
        c.connect(env, 0, c.obj(x, y + 88, f"send~ vc_e{k}"), 0)
        ra, rb = c.obj(x + 250, y + 66, f"receive~ vc_e{k}"), c.obj(x + 250, y + 88, f"receive~ vc_e{k}")
        c.connect(c.obj(x + 250, y + 44, f"r vc_ra{k}"), 0, ra, 0)
        c.connect(c.obj(x + 320, y + 44, f"r vc_rb{k}"), 0, rb, 0)
        e = op(c, x + 250, y + 132, "+~", op(c, x + 250, y + 110, "*~", ra, nwf),
               op(c, x + 300, y + 110, "*~", rb, wf))
        g = op(c, x + 150, y + 154, "*~", c2, e)
        c.connect(g, 0, c.obj(x + 150, y + 176, f"throw~ vc_{'od' if k % 2 else 'ev'}"), 0)
    return c


def unvoiced(Canvas):
    """Sibilance: the modulator above 5 kHz drives high-passed noise (Overlap)."""
    c = Canvas("#N canvas 0 50 600 400 %NAME% 0;")
    mod = c.obj(10, 10, "inlet~")
    e = chain(c, 10, 10, mod, ["hip~ 5000", "hip~ 5000", "abs~", "lop~ 60", "*~ 8"])
    nz = chain(c, 200, 10, c.obj(200, 10, "noise~"), ["hip~ 4000", "hip~ 4000"])
    s = op(c, 10, 150, "*~", op(c, 10, 130, "*~", e, nz), sig(c, 300, 80, "vc_sib", 30))
    c.connect(s, 0, c.obj(10, 180, "outlet~"), 0)
    return c


def tracker(Canvas):
    """Record = Track: sigmund~ pitch of the modulator, rounded to semitones -> vc_ftrk (held when unvoiced). The
    subpatch is switched off unless Track is on (sigmund~ is the costliest object here)."""
    c = Canvas("#N canvas 0 50 600 400 %NAME% 0;")
    mod = c.obj(10, 10, "inlet~")
    c.connect(c.obj(200, 10, "r vc_trk"), 0, c.obj(200, 40, "switch~"), 0)
    sg = op(c, 10, 40, "sigmund~ -hop 512 -npts 2048 -npeak 10 -maxfreq 2000 pitch", mod)
    p = op(c, 10, 62, "moses 0", sg)
    chain(c, 10, 62, p, ["+ 0.5", "int", "change", "mtof", "s vc_ftrk"], outlet=1)
    return c


def test_source(Canvas):
    """Modulator (left) = sine vc_tsf at vc_tsa + noise vc_tna (+ a 6 kHz band of noise vc_tha); carrier (right) =
    sine vc_tcf at vc_tca."""
    c = Canvas("#N canvas 0 50 700 400 %NAME% 0;")
    s = op(c, 10, 40, "*~", op(c, 10, 30, "osc~ 220", c.obj(10, 8, "r vc_tsf")), sig(c, 100, 8, "vc_tsa", 5))
    n = op(c, 200, 40, "*~", c.obj(200, 20, "noise~"), sig(c, 260, 8, "vc_tna", 5))
    h = op(c, 350, 60, "*~", chain(c, 350, 20, c.obj(350, 20, "noise~"), ["bp~ 6500 3"]), sig(c, 450, 8, "vc_tha", 5))
    m = op(c, 10, 100, "+~", op(c, 10, 80, "+~", s, n), h)
    cr = op(c, 500, 40, "*~", op(c, 500, 30, "osc~ 1000", c.obj(500, 8, "r vc_tcf")), sig(c, 600, 8, "vc_tca", 5))
    c.connect(m, 0, c.obj(10, 140, "outlet~"), 0)
    c.connect(cr, 0, c.obj(500, 140, "outlet~"), 0)
    return c


def vocoder_patch(Canvas, controls_canvas, test=None):
    c = Canvas("#N canvas 0 50 1000 600 10;")
    c.text(10, 5, "10_vocoder: 20-band channel vocoder. See docs/VOCODER.md and patches/10_vocoder_README.md.")
    c.text(10, 20, "Left in = modulator. Carrier = internal chord (Pitch V/oct, Start = chord) or the right input "
                   "(Source). Freeze = hold the envelope. Speed = formant shift.")
    c.sub(10, 50, "nebulae_controls", controls_canvas())
    c.sub(10, 80, "ui", ui(Canvas))
    c.sub(100, 80, "ctl", ctl(Canvas, bool(test)))
    src = c.sub(10, 120, "testsrc", test_source(Canvas)) if test else c.obj(10, 120, "adc~ 1 2")
    car = c.sub(200, 160, "carrier", carrier(Canvas))
    c.connect(src, 1, car, 0)
    bk = c.sub(10, 200, "bank", bank(Canvas))
    c.connect(src, 0, bk, 0)
    c.connect(car, 0, bk, 1)
    uv = c.sub(200, 200, "unvoiced", unvoiced(Canvas))
    c.connect(src, 0, uv, 0)
    tk = c.sub(300, 200, "tracker", tracker(Canvas))
    c.connect(src, 0, tk, 0)
    wet = sig(c, 400, 240, "vc_gw", 20)
    dry = sig(c, 500, 240, "vc_gd", 20)
    leak = sig(c, 600, 240, "vc_leak", 20)
    outs = []
    ev, od = c.obj(400, 290, "catch~ vc_ev"), c.obj(500, 290, "catch~ vc_od")
    for ch, side, x in ((0, "l", 10), (1, "r", 260)):
        pe = op(c, x, 270, "*~ 1", ev)
